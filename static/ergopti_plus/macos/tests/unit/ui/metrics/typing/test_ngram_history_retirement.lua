--- tests/unit/ui/metrics/typing/test_ngram_history_retirement.lua

--- ==============================================================================
--- MODULE: Typing History Retirement Regression
--- DESCRIPTION:
--- Interrupted encodes cannot publish mutated data with an old watermark.
--- The extension is built aside: the accepted entry is never mutated nor
--- retired, so an interrupted or failed extension leaves it exactly in place.
--- ==============================================================================

local helpers = require("tests.helpers")
local Fixture = require("tests.support.ui.metrics.typing.ngram_retirement_fixture")

helpers.describe("ngram-history-retirement", function()
	helpers.it("(ngram-history-retirement) commits a healthy extension once", function()
		Fixture.run(function(state)
			state.advance()
			state.request()
			state.drain()
			state.assert_complete()
			state.assert_published()
			local histories = #state.histories
			state.request(72)
			state.drain()
			state.assert_complete()
			state.assert_published()
			helpers.assert_eq(#state.histories, histories, "accepted history is reused")
		end)
	end)

	helpers.it("(ngram-history-retirement) preserves accepted history when closed before merge", function()
		Fixture.run(function(state)
			state.advance()
			state.arm("before-merge")
			state.request()
			state.suspend()
			helpers.assert_eq(state.merges, 0)
			state.close()
			helpers.assert_true(rawequal(state.entry(), state.baseline))
			helpers.assert_eq(Fixture.count(state.entry().data, "b"), 0)
			state.arm(nil)
			state.reopen()
			state.drain()
			state.assert_complete()
			state.assert_published()
		end)
	end)

	helpers.it("(ngram-history-retirement) rebuilds after public close during historical JSON", function()
		Fixture.run(function(state)
			state.advance()
			state.arm("history-json")
			state.request()
			state.suspend()
			helpers.assert_eq(state.merges, 2, "the copy and the extension merge precede the paced encoding boundary")
			helpers.assert_eq(Fixture.count(state.history_data, "b"), 11, "the in-flight copy holds the extension")
			helpers.assert_eq(Fixture.count(state.baseline.data, "b"), 0, "the accepted data is never mutated")
			helpers.assert_true(rawequal(state.entry(), state.baseline), "the accepted entry stays admitted")
			helpers.assert_eq(state.entry().through, Fixture.PAST)
			state.close()
			helpers.assert_true(rawequal(state.entry(), state.baseline))
			helpers.assert_eq(Fixture.count(state.entry().data, "b"), 0)
			state.arm(nil)
			state.reopen()
			state.drain()
			state.assert_complete()
			state.assert_published()
		end)
	end)

	helpers.it("(ngram-history-retirement) retries repeated interrupted extensions without double counting", function()
		Fixture.run(function(state)
			state.advance()
			state.arm("history-json")
			state.request()
			for attempt = 1, 3 do
				state.suspend()
				helpers.assert_true(rawequal(state.entry(), state.baseline))
				helpers.assert_eq(Fixture.count(state.baseline.data, "b"), 0, "an interrupted attempt leaves no merged day")
				state.close()
				if attempt < 3 then
					state.arm("history-json")
					state.reopen()
				end
			end
			state.arm(nil)
			state.reopen()
			state.drain()
			state.assert_complete()
			state.assert_published()
			helpers.assert_eq(Fixture.count(state.baseline.data, "b"), 0, "retries never remerge into the accepted entry")
		end)
	end)

	helpers.it("(ngram-history-retirement) leaves every accepted history admitted during an extension", function()
		Fixture.run(function(state)
			local _, complete = state.projection.session(state.reader, "/fixture/db.sqlite", Fixture.NEXT)
				.range(Fixture.PAST, Fixture.NEXT, { "Other" })
			helpers.assert_eq(complete, true)
			local other = state.ranges()[1]
			helpers.assert_true(other.key ~= state.key)
			state.advance()
			state.arm("history-json")
			state.request()
			state.suspend()
			helpers.assert_true(rawequal(state.entry(), state.baseline))
			helpers.assert_eq(#state.ranges(), 2)
			local others = 0
			for _, entry in ipairs(state.ranges()) do
				if rawequal(entry, other) then others = others + 1 end
			end
			helpers.assert_eq(others, 1, "the unrelated history is untouched")
			state.close()
			state.arm(nil)
			state.reopen()
			state.drain()
			state.assert_complete()
			state.assert_published()
			helpers.assert_eq(#state.ranges(), 2)
			helpers.assert_true(rawequal(state.ranges()[2], other))
		end)
	end)

	helpers.it("(ngram-history-retirement) keeps the accepted entry when SQL refuses the extension", function()
		Fixture.run(function(state)
			local old_json = state.baseline.json
			state.advance()
			state.sql_refusal = true
			state.request()
			state.drain()
			helpers.assert_true(#state.errors > 0)
			helpers.assert_true(rawequal(state.entry(), state.baseline))
			helpers.assert_eq(state.entry().through, Fixture.PAST)
			helpers.assert_eq(state.entry().json, old_json)
			helpers.assert_eq(Fixture.count(state.entry().data, "b"), 0)
			helpers.assert_eq(state.merges, 0)
			state.sql_refusal = false
			state.request(72)
			state.drain()
			state.assert_complete()
			state.assert_published()
		end)
	end)

	helpers.it("(ngram-history-retirement) keeps accepted history when the real encoder rejects invalid UTF-8", function()
		Fixture.run(function(state)
			state.advance()
			state.extension_row.token = "\255"
			state.request()
			state.drain()
			helpers.assert_true(table.concat(state.errors, "\n"):find("string is not valid UTF-8", 1, true) ~= nil)
			helpers.assert_eq(state.merges, 2)
			helpers.assert_true(rawequal(state.entry(), state.baseline), "a refused encode admits nothing new")
			helpers.assert_eq(state.entry().through, Fixture.PAST)
			helpers.assert_eq(Fixture.count(state.entry().data, "b"), 0)
			state.extension_row.token = "b"
			state.request(72)
			state.drain()
			state.assert_complete()
			state.assert_published()
		end)
	end)

	helpers.it("(ngram-history-retirement) retains committed history when today's encode is cancelled", function()
		Fixture.run(function(state)
			state.advance()
			state.pad_today()
			state.arm("today-json")
			state.request()
			state.suspend()
			state.assert_complete()
			local accepted, histories = state.entry(), #state.histories
			state.close()
			helpers.assert_true(rawequal(state.entry(), accepted))
			state.arm(nil)
			state.reopen()
			state.drain()
			state.assert_complete()
			state.assert_published()
			helpers.assert_eq(#state.histories, histories)
		end)
	end)

	helpers.it("(ngram-history-retirement) cancels the owned job and restores the calendar on assertion failure", function()
		local previous_date, captured_job = os.date, nil
		local ok, detail = pcall(function()
			Fixture.run(function(state)
				state.advance()
				state.arm("history-json")
				state.request()
				state.suspend()
				captured_job = state.dashboard._job
				error("controlled retirement fixture assertion")
			end)
		end)
		helpers.assert_eq(ok, false)
		helpers.assert_true(tostring(detail):find("controlled retirement fixture assertion", 1, true) ~= nil)
		helpers.assert_true(rawequal(os.date, previous_date))
		helpers.assert_eq(captured_job.state, "cancelled")
		helpers.assert_eq(captured_job.timer, nil)
	end)
end)
