// static/ergopti_plus/windows/platform/native/key_press_ledger.h
/**
 * @file key_press_ledger.h
 * @brief Keys held right now, as only the native hook can know them.
 *
 * AutoHotkey cannot read dwExtraInfo, and its physical state misses three facts
 * the hook holds: a press the owner suppressed or captured never reached it, a
 * replayed edge is injected for it, and the fake LCtrl of an AltGr press shares
 * SC01D with the real one. The ledger keeps those facts per key with the order
 * of the presses, so one source answers "held", "pressed first" and "whose
 * LCtrl" whichever hook runs first.
 *
 * It holds the keys down at this instant and forgets each one at its release:
 * no history and no text. Pure C with no Win32 dependency, so the rules run
 * under the hook-free native tests; the caller owns the lock.
 */

#ifndef ERGOPTI_KEY_PRESS_LEDGER_H
#define ERGOPTI_KEY_PRESS_LEDGER_H

#include <stdbool.h>
#include <stdint.h>
#include <string.h>

/* Beyond any keyboard's rollover; a further key is counted, never guessed. */
#define ERGOPTI_LEDGER_CAPACITY 32u

/** The physical key is down. */
#define ERGOPTI_LEDGER_REAL_DOWN 0x01u
/** The press was suppressed or replayed: AutoHotkey's physical state misses it. */
#define ERGOPTI_LEDGER_HIDDEN 0x02u
/** A system-generated alias of this key is down (the fake LCtrl of AltGr). */
#define ERGOPTI_LEDGER_SYSTEM_DOWN 0x04u
/* The release was captured too, and its replay is still owed. Internal. */
#define ERGOPTI_LEDGER_UP_OWED 0x80u
#define ERGOPTI_LEDGER_PUBLIC_FLAGS 0x07u

/** Where one hook edge comes from. */
typedef enum ErgoptiLedger_Origin {
	/** Output of any injector: it presses no physical key. */
	ERGOPTI_LEDGER_ORIGIN_IGNORED = 0,
	/** A hardware edge. */
	ERGOPTI_LEDGER_ORIGIN_PHYSICAL = 1,
	/** The owner's own replay of a captured hardware edge. */
	ERGOPTI_LEDGER_ORIGIN_REPLAY = 2,
	/** Generated by the system: raw scan bits above the byte (0x21D and alike). */
	ERGOPTI_LEDGER_ORIGIN_SYSTEM = 3
} ErgoptiLedger_Origin;

/** What the owner did with one hardware edge. */
typedef enum ErgoptiLedger_Disposition {
	/** Passed on to the next hook. */
	ERGOPTI_LEDGER_PASSED = 0,
	/** Suppressed for good: navigation consumed it. */
	ERGOPTI_LEDGER_CONSUMED = 1,
	/** Queued in a terminal capture: its replay follows. */
	ERGOPTI_LEDGER_CAPTURED = 2
} ErgoptiLedger_Disposition;

typedef struct ErgoptiLedger_Slot {
	uint16_t sc;
	uint8_t state;
	uint64_t sequence;
} ErgoptiLedger_Slot;

typedef struct ErgoptiLedger {
	ErgoptiLedger_Slot slots[ERGOPTI_LEDGER_CAPACITY];
	uint64_t next_sequence;
	uint64_t overflowed;
} ErgoptiLedger;

/**
 * Forgets every key.
 *
 * @param ledger Ledger to clear.
 */
static inline void ErgoptiLedger_Reset(ErgoptiLedger *ledger)
{
	memset(ledger, 0, sizeof(*ledger));
}

/**
 * Lets go of every key held, keeping the press numbers increasing: the releases
 * were missed (the secure desktop takes the keyboard, and no hook sees what
 * happens there). A key really still down has its release ignored later, and
 * AutoHotkey's physical state keeps answering for it meanwhile.
 *
 * @param ledger Ledger to clear.
 */
static inline void ErgoptiLedger_ReleaseAll(ErgoptiLedger *ledger)
{
	memset(ledger->slots, 0, sizeof(ledger->slots));
}

/**
 * Classifies one raw hook tuple.
 *
 * @param raw_scan KBDLLHOOKSTRUCT scanCode, unmasked.
 * @param injected LLKHF_INJECTED is set.
 * @param lower_integrity LLKHF_LOWER_IL_INJECTED is set.
 * @param replay_marker dwExtraInfo is the owner's replay marker.
 * @return The origin of the edge.
 */
static inline ErgoptiLedger_Origin ErgoptiLedger_Classify(
	uint32_t raw_scan,
	bool injected,
	bool lower_integrity,
	bool replay_marker)
{
	/* A marker cannot grant lower-integrity input physical authority. */
	if (lower_integrity)
		return ERGOPTI_LEDGER_ORIGIN_IGNORED;
	if (injected)
		return replay_marker
			? ERGOPTI_LEDGER_ORIGIN_REPLAY : ERGOPTI_LEDGER_ORIGIN_IGNORED;
	return (raw_scan & 0xFF00u) != 0
		? ERGOPTI_LEDGER_ORIGIN_SYSTEM : ERGOPTI_LEDGER_ORIGIN_PHYSICAL;
}

/** Finds the slot of a key, or NULL. */
static inline ErgoptiLedger_Slot *ErgoptiLedger_Find(ErgoptiLedger *ledger, uint16_t sc)
{
	uint32_t index;
	for (index = 0; index < ERGOPTI_LEDGER_CAPACITY; ++index) {
		if (ledger->slots[index].state != 0 && ledger->slots[index].sc == sc)
			return &ledger->slots[index];
	}
	return NULL;
}

/** Finds or opens the slot of a key; NULL and one count when the ledger is full. */
static inline ErgoptiLedger_Slot *ErgoptiLedger_Open(ErgoptiLedger *ledger, uint16_t sc)
{
	ErgoptiLedger_Slot *slot = ErgoptiLedger_Find(ledger, sc);
	uint32_t index;
	if (slot != NULL)
		return slot;
	for (index = 0; index < ERGOPTI_LEDGER_CAPACITY; ++index) {
		if (ledger->slots[index].state == 0) {
			ledger->slots[index].sc = sc;
			ledger->slots[index].sequence = 0;
			return &ledger->slots[index];
		}
	}
	++ledger->overflowed;
	return NULL;
}

/** Whether a key is really or by its system alias down, without changing it. */
static inline bool ErgoptiLedger_IsDownAny(ErgoptiLedger *ledger, uint16_t sc)
{
	const ErgoptiLedger_Slot *slot = ErgoptiLedger_Find(ledger, sc);
	return slot != NULL
		&& (slot->state & (ERGOPTI_LEDGER_REAL_DOWN | ERGOPTI_LEDGER_SYSTEM_DOWN)) != 0;
}

/**
 * Whether a Delete going down now completes Ctrl+Alt+Del. The system answers it
 * with the secure desktop, so no hook sees the releases of the keys held. AltGr
 * counts: its fake LCtrl and its right Alt are that Ctrl and that Alt.
 */
static inline bool ErgoptiLedger_IsSecureAttention(ErgoptiLedger *ledger, uint16_t sc)
{
	return (sc == 0x53u || sc == 0x153u)
		&& (ErgoptiLedger_IsDownAny(ledger, 0x1Du) || ErgoptiLedger_IsDownAny(ledger, 0x11Du))
		&& (ErgoptiLedger_IsDownAny(ledger, 0x38u) || ErgoptiLedger_IsDownAny(ledger, 0x138u));
}

/** Numbers a new press; a Down on a key already down is its auto-repeat. */
static inline void ErgoptiLedger_MarkDown(ErgoptiLedger *ledger, ErgoptiLedger_Slot *slot)
{
	if ((slot->state & ERGOPTI_LEDGER_REAL_DOWN) == 0)
		slot->sequence = ++ledger->next_sequence;
	slot->state = (uint8_t)((slot->state | ERGOPTI_LEDGER_REAL_DOWN)
		& ~ERGOPTI_LEDGER_UP_OWED);
}

/**
 * Records an edge before it is delivered, so a criterion evaluated by the next
 * hook already reads it. A hardware release of a hidden key waits for its
 * disposition: only the owner knows whether a replay still owes it.
 *
 * @param ledger Ledger to update.
 * @param sc Key identity: low scan byte, 0x100 when extended.
 * @param key_up The edge is a release.
 * @param origin ErgoptiLedger_Classify result.
 */
static inline void ErgoptiLedger_ObserveBefore(
	ErgoptiLedger *ledger,
	uint16_t sc,
	bool key_up,
	ErgoptiLedger_Origin origin)
{
	ErgoptiLedger_Slot *slot;
	if (origin == ERGOPTI_LEDGER_ORIGIN_IGNORED)
		return;
	if (key_up) {
		slot = ErgoptiLedger_Find(ledger, sc);
		if (slot == NULL)
			return;
		if (origin == ERGOPTI_LEDGER_ORIGIN_SYSTEM)
			slot->state = (uint8_t)(slot->state & ~ERGOPTI_LEDGER_SYSTEM_DOWN);
		else if (origin == ERGOPTI_LEDGER_ORIGIN_REPLAY)
			slot->state = (uint8_t)(slot->state & ERGOPTI_LEDGER_SYSTEM_DOWN);
		else if ((slot->state & ERGOPTI_LEDGER_HIDDEN) == 0)
			slot->state = (uint8_t)(slot->state & ERGOPTI_LEDGER_SYSTEM_DOWN);
		return;
	}
	if (origin == ERGOPTI_LEDGER_ORIGIN_PHYSICAL && ErgoptiLedger_IsSecureAttention(ledger, sc)) {
		ErgoptiLedger_ReleaseAll(ledger);
		return;
	}
	slot = ErgoptiLedger_Open(ledger, sc);
	if (slot == NULL)
		return;
	if (origin == ERGOPTI_LEDGER_ORIGIN_SYSTEM) {
		slot->state = (uint8_t)(slot->state | ERGOPTI_LEDGER_SYSTEM_DOWN);
		return;
	}
	ErgoptiLedger_MarkDown(ledger, slot);
	if (origin == ERGOPTI_LEDGER_ORIGIN_REPLAY)
		slot->state = (uint8_t)(slot->state | ERGOPTI_LEDGER_HIDDEN);
}

/**
 * Records what the owner did with a hardware edge.
 *
 * @param ledger Ledger to update.
 * @param sc Key identity.
 * @param key_up The edge is a release.
 * @param disposition What the owner did with it.
 */
static inline void ErgoptiLedger_ObserveAfter(
	ErgoptiLedger *ledger,
	uint16_t sc,
	bool key_up,
	ErgoptiLedger_Disposition disposition)
{
	ErgoptiLedger_Slot *slot = ErgoptiLedger_Find(ledger, sc);
	if (slot == NULL)
		return;
	if (!key_up) {
		if (disposition != ERGOPTI_LEDGER_PASSED)
			slot->state = (uint8_t)(slot->state | ERGOPTI_LEDGER_HIDDEN);
		return;
	}
	if (disposition == ERGOPTI_LEDGER_CAPTURED
			&& (slot->state & ERGOPTI_LEDGER_HIDDEN) != 0)
		slot->state = (uint8_t)(slot->state | ERGOPTI_LEDGER_UP_OWED);
	else
		slot->state = (uint8_t)(slot->state & ERGOPTI_LEDGER_SYSTEM_DOWN);
}

/**
 * Reads one key.
 *
 * @param ledger Ledger to read; a release whose replay can no longer come retires.
 * @param sc Key identity.
 * @param replay_owed A terminal capture still holds edges to replay.
 * @param out_sequence Receives the press number, zero when the key is not down.
 * @return The public flags of the key.
 */
static inline uint32_t ErgoptiLedger_Query(
	ErgoptiLedger *ledger,
	uint16_t sc,
	bool replay_owed,
	uint64_t *out_sequence)
{
	ErgoptiLedger_Slot *slot = ErgoptiLedger_Find(ledger, sc);
	*out_sequence = 0;
	if (slot == NULL)
		return 0;
	if ((slot->state & ERGOPTI_LEDGER_UP_OWED) != 0 && !replay_owed)
		slot->state = (uint8_t)(slot->state & ERGOPTI_LEDGER_SYSTEM_DOWN);
	if ((slot->state & ERGOPTI_LEDGER_REAL_DOWN) != 0)
		*out_sequence = slot->sequence;
	return slot->state & ERGOPTI_LEDGER_PUBLIC_FLAGS;
}

#endif /* ERGOPTI_KEY_PRESS_LEDGER_H */
