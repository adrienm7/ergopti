--- tests/unit/platform/vision/test_png_codec.lua

--- ==============================================================================
--- MODULE: PNG Codec (gray)
--- DESCRIPTION:
--- Decodes PNGs built outside the codec (RGB, gray with alpha and palette, each
--- row under one of the five filters) to the shared BT.601 gray, round-trips a
--- gray image through the encoder, and refuses a PNG over the pixel bound or
--- that is not a PNG.
---
--- ROOT CAUSE ENCODED:
--- A workflow's image target is an embedded PNG and the Linux matcher takes a
--- gray image: nothing decoded one, so an image step could never match.
--- ==============================================================================

local helpers = require("tests.helpers")
local Base64 = require("core.lifecycle.engine.compat.base64")
local Codec = require("platform.vision.png_codec")

-- Generated by a separate Python encoder: 3 x 5 pixels, row y filtered with
-- filter y % 5; the expected gray is round((r*299 + g*587 + b*114) / 1000).
local CASES = {
	{ name = "RGB", png = "iVBORw0KGgoAAAANSUhEUgAAAAMAAAAFCAIAAAAPE8H1AAAAPUlEQVR4nAEyAM3/AKVNyhglMLsdbQETLN7D951YtqMCLEZB9fb26Wt2A7cQLc0r3gZuzQRK1S3evDdRDhkiXhWcM6E9PQAAAABJRU5ErkJggg==",
		gray = { 118, 34, 85, 57, 99, 145, 89, 88, 64, 114, 107, 146, 39, 222, 228 } },
	{ name = "gray with alpha", png = "iVBORw0KGgoAAAANSUhEUgAAAAMAAAAFCAQAAAAqeJ4pAAAALklEQVR4nAEjANz/AJl/XHwpmQH9r+jkQKkC2aXKutWbA6n9P3TmPATV/EbcwyNF4hLkI/LciAAAAABJRU5ErkJggg==",
		gray = { 153, 92, 41, 253, 229, 37, 214, 175, 250, 20, 160, 179, 233, 47, 242 } },
	{ name = "palette", png = "iVBORw0KGgoAAAANSUhEUgAAAAMAAAAFCAMAAAC3r6aQAAAACVBMVEUKFB7IZDIA/wCBUjsQAAAAG0lEQVR4nAXBAQEAMAyDMOju3zJPYFOZdeIrPhjGBBD3pl5NAAAAAElFTkSuQmCC",
		gray = { 18, 150, 150, 124, 150, 150, 150, 124, 124, 150, 124, 150, 124, 18, 124 } },
}

helpers.describe("png codec (workflow-screen)", function()
	for _, case in ipairs(CASES) do
		helpers.it("decodes a " .. case.name .. " PNG under every row filter (workflow-screen)", function()
			local image, reason = Codec.decode_gray(Base64.decode(case.png), 100)
			helpers.assert_true(image ~= nil, tostring(reason))
			helpers.assert_eq(image.width, 3)
			helpers.assert_eq(image.height, 5)
			helpers.assert_eq(table.concat(image.pixels, ","), table.concat(case.gray, ","))
		end)
	end

	helpers.it("round-trips a gray image through the encoder (workflow-screen)", function()
		local image = { width = 3, height = 2, pixels = { 0, 128, 255, 10, 20, 30 } }
		local back = assert(Codec.decode_gray(assert(Codec.encode_gray(image)), 100))
		helpers.assert_eq(table.concat(back.pixels, ","), "0,128,255,10,20,30")
	end)

	helpers.it("refuses a PNG over the pixel bound and a file that is no PNG (workflow-screen)", function()
		local _, over = Codec.decode_gray(Base64.decode(CASES[1].png), 14)
		helpers.assert_eq(over, "template_unreadable")
		local _, junk = Codec.decode_gray("not a png", 100)
		helpers.assert_eq(junk, "template_unreadable")
	end)
end)
