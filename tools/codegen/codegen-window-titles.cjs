// tools/codegen/codegen-window-titles.cjs

/**
 * Emits native title composers from the shared UI policy. An empty prefix
 * removes branding on every host without changing callers or translations.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '../..');
const SOURCE = 'static/ergopti_plus/_shared/ui/apps.manifest.json';
const LUA_OUTPUT = 'static/ergopti_plus/_shared/lua/window_titles.lua';
const AHK_OUTPUT = 'static/ergopti_plus/windows/_generated/window_titles.ahk';
const SWIFT_OUTPUT =
	'static/ergopti_plus/macos/launcher/Sources/ErgoptiPlus/WindowTitles.generated.swift';

/** Validate both fields, including intentionally empty strings. */
function validate(policy) {
	if (!policy || typeof policy.prefix !== 'string' || typeof policy.separator !== 'string')
		throw new TypeError('apps.manifest.json window_title requires string prefix and separator.');
	for (const value of [policy.prefix, policy.separator])
		if (/[\x00-\x1F\x7F\u2028\u2029]/.test(value) || !value.isWellFormed())
			throw new TypeError(
				'Window title policy must fit on one line using valid Unicode without control characters.'
			);
	return policy;
}

/** Quote one AHK expression without turning policy data into executable code. */
function ahkString(value) {
	return '"' + value.replaceAll('`', '``').replaceAll('"', '`"').replaceAll(';', '`;') + '"';
}

/** Build equivalent native host composers from one validated policy. */
function render(policy, titleKeys = {}) {
	validate(policy);
	for (const [app, key] of Object.entries(titleKeys)) {
		if (
			!/^[a-z][a-z0-9_]*$/.test(app) ||
			typeof key !== 'string' ||
			!/^[a-z][a-z0-9_.]*$/.test(key)
		)
			throw new TypeError(
				'Window title translation entries require canonical app IDs and locale keys.'
			);
	}
	const lua = `--- _shared/lua/window_titles.lua

--- Generated by tools/codegen/codegen-window-titles.cjs; do not edit.
--- Source: _shared/ui/apps.manifest.json window_title.
local M = {}
local PREFIX = ${JSON.stringify(policy.prefix)}
local SEPARATOR = ${JSON.stringify(policy.separator)}
local TITLE_KEYS = {
${Object.entries(titleKeys)
	.sort(([a], [b]) => a.localeCompare(b))
	.map(([app, key]) => `\t[${JSON.stringify(app)}] = ${JSON.stringify(key)},`)
	.join('\n')}
}

--- Compose a native caption from an already-translated, brandless label.
--- @param label string|nil
--- @return string
function M.compose(label)
\tif type(label) ~= "string" or label == "" then return PREFIX end
\tif PREFIX == "" then return label end
\treturn PREFIX .. SEPARATOR .. label
end

--- Returns the shared, brandless translation key for a supported UI app.
--- @param app_id string
--- @return string|nil
function M.key_for_app(app_id)
	return TITLE_KEYS[app_id]
end

return M
`;
	const ahk = `; _generated/window_titles.ahk

; Generated by tools/codegen/codegen-window-titles.cjs; do not edit.
; Source: _shared/ui/apps.manifest.json window_title.

/**
 * Composes a native caption from an already-translated, brandless label.
 * @param {string} Label - The window's translated name.
 * @returns {string} The shared-policy caption.
 */
WindowTitle(Label := "") {
\tPrefix := ${ahkString(policy.prefix)}
\tSeparator := ${ahkString(policy.separator)}
\tif Label == ""
\t\treturn Prefix
\tif Prefix == ""
\t\treturn Label
\treturn Prefix . Separator . Label
}
`;
	const swift = `// Sources/ErgoptiPlus/WindowTitles.generated.swift
// Generated by tools/codegen/codegen-window-titles.cjs; do not edit.
// Source: _shared/ui/apps.manifest.json window_title.

/// Native launcher captions use the same policy as all three runtime hosts.
enum WindowTitles {
	/// Composes a native caption from an already-translated, brandless label.
	static func compose(_ label: String? = nil) -> String {
		let prefix = ${JSON.stringify(policy.prefix)}
		let separator = ${JSON.stringify(policy.separator)}
		guard let label, !label.isEmpty else { return prefix }
		guard !prefix.isEmpty else { return label }
		return prefix + separator + label
	}
}
`;
	return { lua, ahk, swift };
}

/** Regenerate both outputs from the canonical UI manifest. */
function main(root = ROOT) {
	const manifest = JSON.parse(fs.readFileSync(path.join(root, SOURCE), 'utf8'));
	const titleKeys = {};
	if (!manifest.apps || typeof manifest.apps !== 'object' || Array.isArray(manifest.apps))
		throw new TypeError('apps.manifest.json requires an apps object.');
	for (const [app, entry] of Object.entries(manifest.apps)) {
		if (typeof entry.title_key !== 'string' || entry.title_key === '')
			throw new TypeError(`apps.manifest.json ${app} requires a non-empty title_key.`);
		titleKeys[app] = entry.title_key;
	}
	const outputs = render(manifest.window_title, titleKeys);
	for (const [file, content] of [
		[LUA_OUTPUT, outputs.lua],
		[AHK_OUTPUT, '\uFEFF' + outputs.ahk],
		[SWIFT_OUTPUT, outputs.swift]
	]) {
		const target = path.join(root, file);
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, content, 'utf8');
	}
}
module.exports = { render, main, SOURCE, LUA_OUTPUT, AHK_OUTPUT, SWIFT_OUTPUT };
if (require.main === module) main();
