// _shared/ui/changelog/release_body.js

/**
 * ==============================================================================
 * MODULE: Release Body Sections
 * DESCRIPTION:
 * Splits a GitHub release body into its sections (intro, changelog, downloads,
 * footer) so the in-app pages can show what changed before how to install it.
 * CI orders the body for github.com (downloads first, changelog folded), and a
 * page that renders the body verbatim inherits that order.
 *
 * FEATURES & RATIONALE:
 * 1. Explicit contract first: CI wraps each section in invisible HTML comment
 *    markers (<!-- ergopti:section=NAME --> … <!-- /ergopti:section -->). They
 *    must be read here, before the Markdown renderer strips every comment.
 * 2. Heuristics for every other body: releases published before the markers,
 *    and Atom-feed bodies (GitHub strips comments from rendered notes), are
 *    split on the headings and the changelog fold CI has always written.
 * 3. Pure text in, text out: no DOM, no HTML parsing, so the result goes
 *    through the same DOM-only renderer as any other release text.
 * 4. Cross-driver contract: the Windows native notes view ports the changelog
 *    extraction; both are pinned by _shared/tests/corpus/updater/
 *    release_body_vectors.json.
 * ==============================================================================
 */

(function (global) {
	'use strict';

	// Section names CI may emit, in the order it emits them. The CI workflow is
	// pinned to this list by tools/test/test-release-notes-assets-are-uploaded.cjs.
	var SECTION_NAMES = ['intro', 'downloads', 'changelog', 'footer'];

	var FENCE = /^ {0,3}(`{3,}|~{3,})/;
	var BLANK = /^\s*$/;
	var THEMATIC_BREAK = /^ {0,3}([-*_])(?:[ \t]*\1){2,}[ \t]*$/;
	var MARKER_OPEN = /^<!-- ergopti:section=([a-z]+) -->[ \t]*$/;
	var MARKER_CLOSE = /^<!-- \/ergopti:section -->[ \t]*$/;
	var DETAILS_OPEN = /^ {0,3}<details( open)?>[ \t]*$/;
	var DETAILS_CLOSE = /^ {0,3}<\/details>[ \t]*$/;
	var SUMMARY = /^ {0,3}<summary>(.*)<\/summary>[ \t]*$/;
	var H2 = /^ {0,3}## +(.*?)(?: +#+)? *$/;
	var TITLE_HEADING = /^ {0,3}## +Ergopti\b/;
	var CHANGELOG_HEADING = /^ {0,3}## +Changelog(?: +#+)? *$/;
	var DOWNLOADS_HEADING = /^ {0,3}## +Downloads(?: +#+)? *$/;
	var FOOTER_LINE = /^ {0,3}[_*]Generated by\b.*[_*][ \t]*$/;
	// "**[⬇️ Skip to downloads…](…#downloads-<tag>)**": a jump link that only
	// makes sense on github.com, where the downloads followed the changelog.
	var SKIP_LINK =
		/^ {0,3}\*\*\[[^\]]*\]\([^)\s]*#(?:user-content-)?downloads[A-Za-z0-9_-]*\)\*\*[ \t]*$/;
	var EMPTY_ANCHOR = /^ {0,3}<a (?:id|name)="[A-Za-z0-9_-]*"><\/a>[ \t]*$/;
	var TIMESTAMP_NOTE = /^ {0,3}> ?Timestamps are in\b/;

	// =========================================
	// =========================================
	// ======= 1/ Line Helpers =================
	// =========================================
	// =========================================

	/**
	 * Flags every line that belongs to a fenced code block, fences included,
	 * with the same opening and closing rule as the Markdown renderer.
	 * @param {string[]} lines
	 * @return {boolean[]}
	 */
	function _fenceMask(lines) {
		var mask = [];
		for (var i = 0; i < lines.length; i++) {
			var fence = FENCE.exec(lines[i]);
			mask[i] = !!fence;
			if (!fence) continue;
			var marker = fence[1];
			i++;
			while (i < lines.length && lines[i].trim().indexOf(marker) !== 0) {
				mask[i] = true;
				i++;
			}
			if (i < lines.length) mask[i] = true;
		}
		return mask;
	}

	/** Plain text of a fold summary: tags, emphasis markers and escapes removed. */
	function _summaryText(source) {
		return source
			.replace(/<[^>]*>/g, '')
			.replace(/[*_\\]/g, '')
			.trim();
	}

	/**
	 * Returns the index of the </details> closing the fold opened at start.
	 * @return {number} Closing index, or lines.length - 1 when unclosed.
	 */
	function _foldEnd(lines, mask, start) {
		var depth = 0;
		for (var i = start; i < lines.length; i++) {
			if (mask[i]) continue;
			if (DETAILS_OPEN.test(lines[i])) depth++;
			else if (DETAILS_CLOSE.test(lines[i]) && --depth === 0) return i;
		}
		return lines.length - 1;
	}

	/** Index of the first non-blank line at or after start, or -1. */
	function _nextContent(lines, start) {
		for (var i = start; i < lines.length; i++) if (!BLANK.test(lines[i])) return i;
		return -1;
	}

	/** True when the fold opened at index is the changelog fold. */
	function _isChangelogFold(lines, mask, index) {
		if (mask[index] || !DETAILS_OPEN.test(lines[index])) return false;
		var next = _nextContent(lines, index + 1);
		var summary = next === -1 ? null : SUMMARY.exec(lines[next]);
		return !!summary && /^changelog\b/i.test(_summaryText(summary[1]));
	}

	// =========================================
	// =========================================
	// ======= 2/ Section Parsers ==============
	// =========================================
	// =========================================

	/**
	 * Reads the CI section markers.
	 * @return {Object|null} Section name to lines, or null when the body carries
	 *   no valid marker structure (none at all, unknown or repeated name, nesting,
	 *   unclosed section, or content outside every section).
	 */
	function _parseMarked(lines, mask) {
		var sections = {};
		var current = null;
		var start = 0;
		var sawMarker = false;
		for (var i = 0; i < lines.length; i++) {
			var open = mask[i] ? null : MARKER_OPEN.exec(lines[i]);
			if (open) {
				sawMarker = true;
				if (current !== null || SECTION_NAMES.indexOf(open[1]) === -1 || sections[open[1]]) {
					return null;
				}
				current = open[1];
				start = i + 1;
				continue;
			}
			if (!mask[i] && MARKER_CLOSE.test(lines[i])) {
				sawMarker = true;
				if (current === null) return null;
				sections[current] = lines.slice(start, i);
				current = null;
				continue;
			}
			if (current === null && !BLANK.test(lines[i])) return null;
		}
		if (!sawMarker || current !== null) return null;
		return sections;
	}

	/**
	 * Splits an unmarked body on the headings and the changelog fold every CI
	 * release format has used.
	 * @return {Object|null} Section name to lines, or null when neither a
	 *   changelog nor a downloads section is recognisable.
	 */
	function _parseHeuristic(lines, mask) {
		var anchors = {};
		var foldEnd = -1;
		for (var i = 0; i < lines.length; i++) {
			if (mask[i]) continue;
			var line = lines[i];
			if (anchors.intro === undefined && TITLE_HEADING.test(line)) anchors.intro = i;
			if (anchors.downloads === undefined && DOWNLOADS_HEADING.test(line)) anchors.downloads = i;
			if (anchors.changelog === undefined) {
				if (CHANGELOG_HEADING.test(line)) {
					anchors.changelog = i;
				} else if (_isChangelogFold(lines, mask, i)) {
					anchors.changelog = i;
					foldEnd = _foldEnd(lines, mask, i);
				}
			}
		}
		if (anchors.changelog === undefined && anchors.downloads === undefined) return null;

		var last = _nextContentBackward(lines, lines.length - 1);
		if (last !== -1 && !mask[last] && FOOTER_LINE.test(lines[last])) {
			var rule = _nextContentBackward(lines, last - 1);
			anchors.footer = rule !== -1 && !mask[rule] && THEMATIC_BREAK.test(lines[rule]) ? rule : last;
		}

		var order = Object.keys(anchors).sort(function (a, b) {
			return anchors[a] - anchors[b];
		});
		var sections = { intro: lines.slice(0, anchors[order[0]]) };
		var leftover = [];
		order.forEach(function (name, index) {
			var end = index + 1 < order.length ? anchors[order[index + 1]] : lines.length;
			var span = lines.slice(anchors[name], end);
			if (name === 'changelog' && foldEnd !== -1 && foldEnd + 1 < end) {
				leftover = lines.slice(foldEnd + 1, end);
				span = lines.slice(anchors[name], foldEnd + 1);
			}
			sections[name] = (sections[name] || []).concat(span);
		});
		if (_nextContent(leftover, 0) !== -1) sections.footer = leftover.concat(sections.footer || []);
		return sections;
	}

	/** Index of the last non-blank line at or before start, or -1. */
	function _nextContentBackward(lines, start) {
		for (var i = start; i >= 0; i--) if (!BLANK.test(lines[i])) return i;
		return -1;
	}

	// =========================================
	// =========================================
	// ======= 3/ Section Cleanup ==============
	// =========================================
	// =========================================

	/** Drops leading and trailing blank lines and thematic breaks. */
	function _trim(lines) {
		var start = 0;
		var end = lines.length;
		while (start < end && (BLANK.test(lines[start]) || THEMATIC_BREAK.test(lines[start]))) start++;
		while (end > start && (BLANK.test(lines[end - 1]) || THEMATIC_BREAK.test(lines[end - 1])))
			end--;
		return lines.slice(start, end);
	}

	/** Removes the github.com-only lines: the jump link and empty anchors. */
	function _dropPageChrome(lines) {
		var mask = _fenceMask(lines);
		return lines.filter(function (line, i) {
			return mask[i] || !(SKIP_LINK.test(line) || EMPTY_ANCHOR.test(line));
		});
	}

	/** Removes a whole-section fold: <details>, its summary and </details>. */
	function _unwrapFold(lines) {
		var trimmed = _trim(lines);
		var mask = _fenceMask(trimmed);
		if (trimmed.length < 3 || !DETAILS_OPEN.test(trimmed[0])) return trimmed;
		if (_foldEnd(trimmed, mask, 0) !== trimmed.length - 1) return trimmed;
		if (!DETAILS_CLOSE.test(trimmed[trimmed.length - 1])) return trimmed;
		var summary = _nextContent(trimmed, 1);
		if (summary === -1 || !SUMMARY.test(trimmed[summary])) return trimmed;
		return trimmed.slice(summary + 1, trimmed.length - 1);
	}

	/** Drops the section's own heading when the page supplies its title. */
	function _dropHeading(lines, heading) {
		var trimmed = _trim(lines);
		return trimmed.length > 0 && heading.test(trimmed[0]) ? trimmed.slice(1) : trimmed;
	}

	// =========================================
	// =========================================
	// ======= 4/ Public API ===================
	// =========================================
	// =========================================

	/**
	 * Splits a release body into sections.
	 * @param {string} source - Untrusted release body (Markdown).
	 * @return {{format: string, title: string, intro: string, changelog: string,
	 *   downloads: string, footer: string}} format is "marked" (CI markers),
	 *   "legacy" (headings and folds) or "unknown", in which case the whole body
	 *   is the changelog and every other section is empty.
	 */
	function splitReleaseBody(source) {
		var text = (typeof source === 'string' ? source : '').replace(/\r\n?/g, '\n');
		var lines = text.split('\n');
		var mask = _fenceMask(lines);
		var format = 'marked';
		var sections = _parseMarked(lines, mask);
		if (!sections) {
			format = 'legacy';
			sections = _parseHeuristic(lines, mask);
		}
		if (!sections) {
			return {
				format: 'unknown',
				title: '',
				intro: '',
				changelog: _trim(lines).join('\n'),
				downloads: '',
				footer: ''
			};
		}

		var intro = _dropPageChrome(sections.intro || []);
		var changelog = _dropHeading(
			_unwrapFold(_dropPageChrome(sections.changelog || [])),
			CHANGELOG_HEADING
		);
		var downloads = _dropHeading(_dropPageChrome(sections.downloads || []), DOWNLOADS_HEADING);

		var title = '';
		intro = _trim(intro);
		if (intro.length > 0 && TITLE_HEADING.test(intro[0])) {
			title = H2.exec(intro[0])[1];
			intro = intro.slice(1);
		}
		// The timestamp note explains the changelog; legacy bodies put it in the
		// intro, next to the jump link.
		var introMask = _fenceMask(intro);
		var noteIndex = -1;
		intro.forEach(function (line, i) {
			if (noteIndex === -1 && !introMask[i] && TIMESTAMP_NOTE.test(line)) noteIndex = i;
		});
		changelog = _trim(changelog);
		if (noteIndex !== -1 && changelog.length > 0) {
			changelog = [intro[noteIndex], ''].concat(changelog);
			intro = intro.slice(0, noteIndex).concat(intro.slice(noteIndex + 1));
		}

		return {
			format: format,
			title: title,
			intro: _trim(intro).join('\n'),
			changelog: _trim(changelog).join('\n'),
			downloads: _trim(downloads).join('\n'),
			footer: _trim(_dropPageChrome(sections.footer || [])).join('\n')
		};
	}

	global.splitReleaseBody = splitReleaseBody;
	global.RELEASE_BODY_SECTIONS = SECTION_NAMES.slice();
})(window);
