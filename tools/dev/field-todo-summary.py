#!/usr/bin/env python3
# tools/dev/field-todo-summary.py

# ==============================================================================
# MODULE: Field report, per-TODO-point summary (macOS and Linux)
# DESCRIPTION:
# Turns one field report into one verdict per point of its TODO-tests-<os>.md section
# (« To confirm on the Mac », « To confirm on Linux »), so the coordinator can
# tick lines from the report alone. The points and the evidence that decides
# each are static/ergopti_plus/<os>/data/field_todo_coverage.json; the evidence
# is the field run's step results (field_run/NN_<step>.json, with each check's
# report steps), the collector's guided and probe steps (field_guided/, Linux,
# tools/dev/field-guided.py) and the collector's own steps (steps.txt).
#
# FEATURES & RATIONALE:
# 1. Nothing silently skipped: a step absent from the run is not_run with its
#    reason (signed_app steps need --installed), a report step missing from a
#    result is a failure, and a
#    point no run can test says why, read from the coverage table.
# 2. One verdict order for every point: fail, timeout, needs_person,
#    needs_typing, not_run, skip, pass; the worst check decides.
# 3. Only closed codes and report values leave the report folder: the inputs
#    are already the anonymized field run results.
# 4. --doc prints the coverage table docs/tooling/<os>-field-report-coverage.md
#    carries between its markers, and --check-doc fails when that copy is stale.
#
# USAGE:
#   python3 tools/dev/field-todo-summary.py [--os linux] --report <report folder> [--installed]
#   python3 tools/dev/field-todo-summary.py [--os linux] --doc
#   python3 tools/dev/field-todo-summary.py [--os linux] --check-doc
# ==============================================================================

import argparse
import glob
import json
import os
import re
import sys

REPO_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
# Per OS: the coverage table, the step declarations (the driver's field run and
# the collector's own guided and probe steps), the result folders of a report
# and the documentation that carries the generated table.
TARGETS = {
    "macos": {
        "section": "To confirm on the Mac",
        "coverage": "static/ergopti_plus/macos/data/field_todo_coverage.json",
        "specs": ["static/ergopti_plus/macos/data/field_run.json"],
        "results": ["field_run"],
        "doc": "docs/tooling/macos-field-report-coverage.md",
    },
    "linux": {
        "section": "To confirm on Linux",
        "coverage": "static/ergopti_plus/linux/data/field_todo_coverage.json",
        "specs": [
            "static/ergopti_plus/linux/data/field_run_steps.json",
            "static/ergopti_plus/linux/data/field_guided_steps.json",
        ],
        "results": ["field_run", "field_guided"],
        "doc": "docs/tooling/linux-field-report-coverage.md",
    },
}


def load_specs(target):
    """Every declared step of an OS, as one {"steps": [...]} declaration.

    A collector-side step (field_guided_steps.json) has a mode and no kind:
    it is given the kind its result carries, guided or probe.
    """
    steps = []
    for relative in target["specs"]:
        for step in load(os.path.join(REPO_ROOT, relative))["steps"]:
            if "kind" not in step:
                step = dict(step, kind="probe" if step.get("mode") == "probe" else "guided")
            steps.append(step)
    return {"steps": steps}


DOC_START = "<!-- coverage-table:start (generated by tools/dev/field-todo-summary.py --doc) -->"
DOC_END = "<!-- coverage-table:end -->"

# Worst first: the first verdict of this list any check gives is the point's.
ORDER = ["fail", "timeout", "needs_person", "needs_typing", "not_run", "skip", "pass"]
MARKS = {
    "pass": "✅",
    "fail": "❌",
    "timeout": "⏱️",
    "needs_person": "🙋",
    "needs_typing": "⌨️",
    "not_run": "⏸️",
    "skip": "⏭️",
    "not_testable": "🚫",
}


def load(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def leading_number(value):
    match = re.match(r"^(\d+(?:\.\d+)?)", str(value if value is not None else ""))
    if match is None:
        match = re.match(r"^[A-Za-z_]+:(\d+(?:\.\d+)?)", str(value if value is not None else ""))
    return float(match.group(1)) if match else None


def worst(verdicts):
    for verdict in ORDER:
        if verdict in verdicts:
            return verdict
    return "pass"


# =================================
# ======= 1/ Evidence reading =====
# =================================


def read_results(results_dir):
    """The step results of the run, by step id (the last attempt's copy)."""
    results = {}
    if results_dir and os.path.isdir(results_dir):
        for path in sorted(glob.glob(os.path.join(results_dir, "[0-9][0-9]_*.json"))):
            try:
                document = load(path)
            except (OSError, ValueError):
                continue
            if isinstance(document, dict) and isinstance(document.get("step"), str):
                results[document["step"]] = document
    return results


def read_collector_steps(steps_path):
    """The collector's own step exits, by step name."""
    exits = {}
    if steps_path and os.path.isfile(steps_path):
        with open(steps_path, encoding="utf-8", errors="replace") as handle:
            for line in handle:
                match = re.match(r"^(\S+)\s+exit=(\d+)\s*$", line)
                if match:
                    exits[match.group(1)] = int(match.group(2))
    return exits


def not_run_reason(step, installed):
    if step is None:
        return "undeclared_step"
    if step.get("signed_app") and not installed:
        return "needs_installed_run"
    return "absent_from_run"


def judge_check(check, spec_steps, results, collector, installed):
    """One check's verdict and its evidence text."""
    if "collector" in check:
        name = check["collector"]
        if name not in collector:
            return "not_run", f"{name}:absent_from_steps"
        code = collector[name]
        return ("pass" if code == 0 else "fail"), f"{name}:exit_{code}"
    step_id = check["step"]
    result = results.get(step_id)
    if result is None:
        return (
            "not_run",
            f"{step_id}:{not_run_reason(spec_steps.get(step_id), installed)}",
        )
    verdict = result.get("verdict", "fail")
    codes = [str(code) for code in result.get("codes") or []]
    evidence = f"{step_id}:{verdict}" + (f"({','.join(codes[:3])})" if codes else "")
    if verdict not in ("pass", "fail"):
        return (verdict if verdict in ORDER else "fail"), evidence
    report = result.get("report") if isinstance(result.get("report"), dict) else {}
    limit, floor = check.get("max"), check.get("min")

    def out_of_bounds(number):
        """The bound a count or duration breaks, as evidence text, or None."""
        if number is None:
            return "unreadable"
        if limit is not None and number > limit:
            return f">{limit}"
        if floor is not None and number < floor:
            return f"<{floor}"
        return None

    if "field" in check:
        value = leading_number(report.get(check["field"]))
        if value is None:
            return "fail", evidence + f" {check['field']}:missing"
        evidence += f" {check['field']}={report.get(check['field'])}"
        broken = out_of_bounds(value)
        if broken:
            return "fail", evidence + broken
        return verdict, evidence
    if not check.get("report"):
        return verdict, evidence
    steps = {item.get("id"): item for item in report.get("steps") or [] if isinstance(item, dict)}
    states = []
    parts = []
    for report_id in check["report"]:
        item = steps.get(report_id)
        if item is None:
            states.append("fail")
            parts.append(f"{report_id}=missing")
            continue
        state = item.get("state")
        value = item.get("value")
        parts.append(f"{report_id}={state}" + (f":{value}" if value is not None else ""))
        if state == "fail":
            states.append("fail")
        elif state == "skip":
            states.append("skip")
        elif (limit is not None or floor is not None) and out_of_bounds(leading_number(value)):
            states.append("fail")
            parts[-1] += out_of_bounds(leading_number(value))
        else:
            states.append("pass")
    return worst(states), f"{step_id}[{' '.join(parts)}]"


def summarize(coverage, spec, results, collector, installed):
    """One record per point: id, title, verdict, evidence, condition, not_testable."""
    spec_steps = {step["id"]: step for step in spec["steps"]}
    records = []
    for point in coverage["points"]:
        checks = point.get("checks") or []
        if not checks:
            verdict, evidence = "not_testable", []
        else:
            judged = [
                judge_check(check, spec_steps, results, collector, installed) for check in checks
            ]
            verdict = worst([item[0] for item in judged])
            evidence = [item[1] for item in judged]
        records.append(
            {
                "id": point["id"],
                "title": point["title"],
                "verdict": verdict,
                "evidence": evidence,
                "condition": point.get("condition"),
                "not_testable": point.get("not_testable"),
            }
        )
    return records


# ===============================
# ======= 2/ Rendering ==========
# ===============================


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(records, installed, section="To confirm on the Mac"):
    counts = {}
    for record in records:
        counts[record["verdict"]] = counts.get(record["verdict"], 0) + 1
    lines = [
        f"# TODO « {section} »: verdict per point",
        "",
        "Generated by `tools/dev/field-todo-summary.py` from this report's field run results and `steps.txt`"
        + f" (installed run: {'yes' if installed else 'no'}).",
        "Tick a TODO line (its `field-point` id) only on ✅ pass; a ✅ with a remainder still needs that remainder.",
        "",
        "Totals: "
        + ", ".join(
            f"{MARKS.get(name, '')} {name} {counts[name]}"
            for name in ORDER + ["not_testable"]
            if name in counts
        ),
        "",
        "| Point | Verdict | Evidence | Condition | Not field-testable |",
        "| --- | --- | --- | --- | --- |",
    ]
    for record in records:
        lines.append(
            "| `{}` {} | {} {} | {} | {} | {} |".format(
                record["id"],
                cell(record["title"]),
                MARKS.get(record["verdict"], ""),
                record["verdict"],
                cell("; ".join(record["evidence"]) or "—"),
                cell(record["condition"] or "—"),
                cell(record["not_testable"] or "—"),
            )
        )
    return "\n".join(lines) + "\n"


def mode_of(point, spec_steps):
    checks = point.get("checks") or []
    if not checks:
        return "not testable"
    modes = []
    for check in checks:
        step = spec_steps.get(check.get("step"), {})
        if step.get("kind") == "guided":
            modes.append(
                "guided, observed" if step.get("mode") == "observe" else "guided, attested"
            )
        else:
            modes.append("automatic")
    labels = [
        label for label in ("automatic", "guided, observed", "guided, attested") if label in modes
    ]
    if any(spec_steps.get(check.get("step"), {}).get("signed_app") for check in checks):
        labels.append("needs --installed")
    return " + ".join(labels)


def render_doc_table(coverage, spec):
    spec_steps = {step["id"]: step for step in spec["steps"]}
    lines = [
        DOC_START,
        "",
        "| Point | Checks | Mode | Condition | Not field-testable |",
        "| --- | --- | --- | --- | --- |",
    ]
    for point in coverage["points"]:
        names = []
        for check in point.get("checks") or []:
            if "collector" in check:
                names.append(f"`{check['collector']}` (collector)")
                continue
            name = f"`{check['step']}`"
            if check.get("report"):
                name += " (" + ", ".join(f"`{item}`" for item in check["report"]) + ")"
            if "field" in check:
                name += f" (`{check['field']}`)"
            if check.get("max") is not None:
                name += f" ≤ {check['max']}"
            if check.get("min") is not None:
                name += f" ≥ {check['min']}"
            names.append(name)
        lines.append(
            "| `{}` {} | {} | {} | {} | {} |".format(
                point["id"],
                cell(point["title"]),
                "; ".join(names) or "—",
                mode_of(point, spec_steps),
                cell(point.get("condition") or "—"),
                cell(point.get("not_testable") or "—"),
            )
        )
    lines += ["", DOC_END]
    return "\n".join(lines)


def normalized_table(text):
    """The block with each table row reduced to its trimmed cells.

    Prettier pads the cells of the committed copy to align the columns; only
    the cells' content is compared.
    """
    rows = []
    for line in text.split("\n"):
        line = line.strip()
        if not line:
            continue
        if line.startswith("|"):
            cells = [cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip("|"))]
            if all(re.fullmatch(r":?-+:?", cell) for cell in cells):
                cells = ["---"] * len(cells)
            rows.append("|".join(cells))
        else:
            rows.append(line)
    return rows


def doc_block(text):
    start, end = text.find(DOC_START), text.find(DOC_END)
    if start < 0 or end < start:
        return None
    return text[start : end + len(DOC_END)]


