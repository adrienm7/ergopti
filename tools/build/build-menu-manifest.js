#!/usr/bin/env node
// tools/build/build-menu-manifest.js
//
// Emits the shared tray-menu manifest JSON from the [menu.*] tables in the
// features manifest, so the menu tree has a single source of truth alongside
// the feature definitions instead of a separately hand-maintained JSON.
//
// Input:
//   static/ergopti_plus/_shared/modules/features/manifest.toml  ([menu.*] tables)
//
// Output:
//   static/ergopti_plus/_shared/modules/menu/menu_manifest.json
//
// Both drivers read the generated JSON at runtime unchanged. The emitted data
// is a verbatim projection of the [menu.*] tables (only the leading _comment
// header fields are added, and each `choice` row gains the `choices` of its
// enum feature), so behavior is identical to the previous
// hand-maintained file — guaranteed by the menu drift gate
// (tools/test/test-menu-manifest.cjs) and the build:domain regeneration check.
//
// Usage:
//   npm run build:menu
//   node ./tools/build/build-menu-manifest.js

import { parse as parseToml } from 'smol-toml';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import sharedPaths from '../lib/paths.cjs';

const { shared } = sharedPaths;
const __dirname = dirname(fileURLToPath(import.meta.url));

const MANIFEST_PATH = shared('modules/features/manifest.toml');
const OUT_PATH = shared('modules/menu/menu_manifest.json');

// Fixed header comments carried into the emitted JSON. The first line marks the
// file as generated; the other two document the runtime contract for readers.
const HEADER = {
	_comment:
		'GENERATED by tools/build/build-menu-manifest.js from ' +
		'_shared/modules/features/manifest.toml [menu.*]. Do not edit by hand — ' +
		'edit the manifest and run "npm run build:menu" (or build:domain).',
	_comment2:
		"platforms field: omit or 'both' = all platforms, 'ahk' = Windows only, 'hs' = macOS only.",
	_comment3:
		"item types: 'toggle' = a category's first-row checkbox (its master gate, one i18n key), " +
		"'feature' = manifest-path toggle, " +
		"'action' = stateless button, 'dynamic' = rendered by platform code, " +
		"'group' = named submenu, 'section_header' = disabled label, '---' = separator, " +
		"'list' = rows supplied at build time by a named provider, 'letter_picker' = " +
		'the A-Z chooser. The last two were in use and undocumented here, which matters ' +
		"because 'list' is the ONLY type that moves a row from the driver into the " +
		"renderer — 'dynamic' hands the rendering straight back to platform code. " +
		"'choice' = one enum feature (path) as one row with its values beneath it; its " +
		"'choices' are projected from the feature's enum_values by this generator.",
	_comment4:
		"unavailable (rows restricted by platforms only): 'hide' = not applicable where the row " +
		"is not declared, never drawn there and carrying no reason_key; 'grey' = not yet ported " +
		'there, drawn disabled with its label and its translated reason_key. A restricted row ' +
		'without the field is hidden, as before the field existed.'
};

const PLATFORMS = ['ahk', 'hs', 'linux'];

/**
 * Refuses an `unavailable` declaration the renderers cannot honour.
 *
 * The maintainer's two cases for a row a platform lacks: NOT APPLICABLE there
 * (`hide`: it makes no sense on that OS, so nothing is drawn and no reason is
 * owed) and NOT YET PORTED there (`grey`: the feature exists elsewhere, so the
 * row is drawn disabled with its translated reason, which needs a label and a
 * reason to draw).
 * @param {object} menu The parsed [menu] tables.
 */
function validateUnavailable(menu) {
	for (const [key, rows] of Object.entries(menu)) {
		if (!Array.isArray(rows)) continue;
		for (const row of rows) {
			if (!row || typeof row !== 'object' || row.unavailable === undefined) continue;
			const where = `menu.${key} row "${row.id || row.path || row.i18n || row.type}"`;
			if (row.unavailable !== 'hide' && row.unavailable !== 'grey')
				throw new Error(`${where}: unavailable must be "hide" or "grey"`);
			const restricted =
				Array.isArray(row.platforms) && PLATFORMS.some((p) => !row.platforms.includes(p));
			if (!restricted)
				throw new Error(`${where}: unavailable needs platforms that leave some platform out`);
			if (row.unavailable === 'hide' && row.reason_key !== undefined)
				throw new Error(`${where}: a hidden row carries no reason_key`);
			if (row.unavailable === 'grey') {
				if (typeof row.reason_key !== 'string' || row.reason_key === '')
					throw new Error(`${where}: a greyed row needs its reason_key`);
				if (typeof row.i18n !== 'string' || row.i18n === '')
					throw new Error(`${where}: a greyed row needs an i18n label`);
			}
		}
	}
}

/**
 * Projects each `choice` row's values from the enum feature its `path` names.
 *
 * A choice row is one setting with a fixed set of values, drawn as one row with
 * the values beneath it. The values belong to the feature (its `enum_values`),
 * so the row never lists them itself: each becomes `{ value, i18n }`, labelled
 * by the key `<row i18n>.<value>`. A row whose path is not an enum feature, that
 * lists its choices by hand, or that is shown on a platform the feature does not
 * declare fails the build instead of drawing a row no driver can store.
 * @param {object} menu The parsed [menu] tables, completed in place.
 * @param {string} raw The manifest source, for the feature entries.
 */
function projectChoices(menu, raw) {
	const flattened = parseToml(
		raw.replace(
			/^\[\[features\.([^\]]+)\]\]\r?$/gm,
			(_m, prefix) => `[[entries]]\npath_prefix = "${prefix}"`
		)
	);
	const enums = new Map();
	for (const entry of flattened.entries || []) {
		if (entry.type === 'enum') enums.set(`${entry.path_prefix}.${entry.id}`, entry);
	}
	for (const [key, rows] of Object.entries(menu)) {
		if (!Array.isArray(rows)) continue;
		for (const row of rows) {
			if (!row || typeof row !== 'object' || row.type !== 'choice') continue;
			const where = `menu.${key} choice "${row.id}"`;
			const feature = enums.get(row.path);
			if (!feature) throw new Error(`${where} names "${row.path}", which is no enum feature`);
			if (row.choices !== undefined)
				throw new Error(`${where} lists its choices by hand; they come from the feature`);
			if (typeof row.i18n !== 'string' || row.i18n === '')
				throw new Error(`${where} has no i18n key`);
			if (!Array.isArray(feature.platforms))
				throw new Error(`"${row.path}" must declare its platforms to back a choice row`);
			// A row with no `platforms` is shown by every driver.
			for (const platform of row.platforms || ['ahk', 'hs', 'linux']) {
				if (!feature.platforms.includes(platform)) {
					throw new Error(`${where} is shown on ${platform}, where "${row.path}" does not exist`);
				}
			}
			row.choices = feature.enum_values.map((value) => ({ value, i18n: `${row.i18n}.${value}` }));
		}
	}
}

function build() {
	const raw = readFileSync(MANIFEST_PATH, 'utf8');
	const parsed = parseToml(raw);
	if (!parsed.menu || typeof parsed.menu !== 'object') {
		throw new Error('manifest.toml is missing the [menu] tables — cannot emit menu_manifest.json');
	}

	projectChoices(parsed.menu, raw);
	validateUnavailable(parsed.menu);
	const out = { ...HEADER, ...parsed.menu };
	const json = JSON.stringify(out, null, '\t') + '\n';
	writeFileSync(OUT_PATH, json, 'utf8');
	console.log(
		`build-menu-manifest: wrote ${OUT_PATH} (${Object.keys(parsed.menu).length} top-level keys).`
	);
}

build();
