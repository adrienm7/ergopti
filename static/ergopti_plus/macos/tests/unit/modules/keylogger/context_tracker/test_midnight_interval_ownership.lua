--- tests/unit/modules/keylogger/context_tracker/test_midnight_interval_ownership.lua

--- ==============================================================================
--- MODULE: Midnight Foreground Interval Ownership Regression
--- DESCRIPTION:
--- Retried rollovers cannot invent pre-focus time or misread a DST wall label.
--- ==============================================================================

local helpers = require("tests.helpers")
local Fixture = require("tests.support.modules.keylogger.midnight_interval_fixture")

helpers.describe("midnight interval ownership", function()
	helpers.it("(midnight-interval-ownership) preserves the healthy accepted boundary", function()
		Fixture.run({}, function(state)
			state.advance(5); state.maintain(true)
			helpers.assert_eq(state.duration(), 5000)
			helpers.assert_eq(#state.rows, 1)
			helpers.assert_eq(state.rows[1].duration, 3600000)
			helpers.assert_eq(state.rows[1].timestamp, "2026-10-20 23:59:59.999")
			state.advance(61); state.maintain(true)
			helpers.assert_eq(state.duration(), 61000)
			helpers.assert_eq(state.rollover_calls, 1)
			helpers.assert_eq(#state.errors, 0)
		end)
	end)

	helpers.it("(midnight-interval-ownership) retries the same accepted boundary idempotently", function()
		Fixture.run({}, function(state)
			state.advance(5); state.maintain(false)
			state.advance(61); state.maintain(false); state.maintain(false)
			helpers.assert_eq(state.duration(), 61000)
			helpers.assert_eq(#state.rows, 1)
			state.advance(121); state.maintain(true)
			helpers.assert_eq(state.duration(), 121000)
			helpers.assert_eq(state.rollover_calls, 4)
			helpers.assert_eq(#state.rows, 1)
		end)
	end)

	for _, accepted in ipairs({ false, true }) do
		helpers.it("(midnight-interval-ownership) preserves a newer app on rollover accepted=" .. tostring(accepted), function()
			Fixture.run({}, function(state)
				state.advance(5); state.maintain(false)
				state.advance(60); state.activate("Terminal")
				helpers.assert_eq(state.duration(), 0)
				helpers.assert_eq(state.rows[2].duration, 60000)
				state.advance(61); state.maintain(accepted)
				helpers.assert_eq(state.duration(), 1000)
				helpers.assert_eq(state.core.active_app_name, "Terminal")
				helpers.assert_eq(#state.rows, 2)
				helpers.assert_eq(#state.errors, 0)
			end)
		end)
	end

	helpers.it("(midnight-interval-ownership) uses elapsed calendar time across spring forward", function()
		Fixture.run({ year = 2026, month = 3, day = 8, previous = { year = 2026, month = 3, day = 7 } }, function(state)
			state.advance(5); state.maintain(false)
			state.advance(7199, { hour = 1, min = 59, sec = 59, isdst = false }); state.maintain(false)
			helpers.assert_eq(state.duration(), 7199000)
			state.advance(7200, { hour = 3, min = 0, sec = 0, isdst = true }); state.maintain(false)
			helpers.assert_eq(state.duration(), 7200000)
			helpers.assert_eq(#state.rows, 1)
			helpers.assert_eq(state.rows[1].duration, 3600000)
			helpers.assert_eq(#state.errors, 0)
		end)
	end)

	helpers.it("(midnight-interval-ownership) never recredits the previous day across fall back", function()
		Fixture.run({ year = 2026, month = 11, day = 1, previous = { year = 2026, month = 10, day = 31 } }, function(state)
			state.advance(5); state.maintain(false)
			state.advance(7199, { hour = 1, min = 59, sec = 59, isdst = true }); state.maintain(false)
			helpers.assert_eq(state.duration(), 7199000)
			state.advance(7200, { hour = 1, min = 0, sec = 0, isdst = false }); state.maintain(false)
			helpers.assert_eq(state.duration(), 7200000)
			helpers.assert_eq(#state.rows, 1)
			state.advance(7201, { hour = 1, min = 0, sec = 1, isdst = false }); state.maintain(true)
			helpers.assert_eq(state.duration(), 7201000)
			helpers.assert_eq(#state.rows, 1)
			helpers.assert_eq(state.rows[1].duration, 3600000)
			helpers.assert_eq(#state.errors, 0)
		end)
	end)

	helpers.it("(midnight-interval-ownership) does not create an interval after public close", function()
		Fixture.run({}, function(state)
			state.advance(-1)
			helpers.assert_eq(state.tracker.close_active_app(), true)
			state.advance(5); state.maintain(false)
			helpers.assert_eq(state.tracker.get_active_app_snapshot(), nil)
			helpers.assert_eq(state.core.active_app_start, nil)
			helpers.assert_eq(#state.rows, 1)
			helpers.assert_eq(state.rows[1].duration, 3599000)
			helpers.assert_eq(state.rollover_calls, 1)
		end)
	end)

	helpers.it("(midnight-interval-ownership) retains the first focus after an earlier interval closed", function()
		Fixture.run({}, function(state)
			state.advance(-1); state.tracker.close_active_app()
			state.advance(5); state.maintain(false)
			state.advance(60); state.activate("Editor")
			state.advance(61); state.maintain(false)
			helpers.assert_eq(state.duration(), 1000)
			helpers.assert_eq(#state.rows, 1)
		end)
	end)

	helpers.it("(midnight-interval-ownership) restores both calendar functions after a scenario error", function()
		local date, time = os.date, os.time
		local ok, detail = pcall(function()
			Fixture.run({}, function(state)
				state.advance(5); state.maintain(false)
				error("controlled midnight interval fixture assertion")
			end)
		end)
		helpers.assert_eq(ok, false)
		helpers.assert_true(tostring(detail):find("controlled midnight interval fixture assertion", 1, true) ~= nil)
		helpers.assert_true(rawequal(os.date, date))
		helpers.assert_true(rawequal(os.time, time))
	end)
end)
