--- tests/unit/modules/gestures/actions/clipboard/fifo/test_search_handoff.lua
--- Search capture joins the actual queued native copy and preserves result ownership.
local helpers = require("tests.helpers")
local World = require("tests.support.modules.gestures.search_fifo_fixture")
helpers.describe("Search copy native FIFO handoff", function()
	helpers.it("keeps an empty FIFO search healthy", function()
		World.with_world({}, function(w)
			assert(w.start()); w.advance(1)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {1,1,1})
			helpers.assert_eq(w.urls, {"https://example.test/?q=SELECTED%20WORDS"})
			helpers.assert_true(w.clipboard() == w.original)
		end)
	end)
	helpers.it("does not capture before a real paced predecessor hands off the copy", function()
		World.with_world({backlog=true}, function(w)
			assert(w.start()); w.advance(0.21)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {0,0,0})
			helpers.assert_eq(#w.urls,0)
			w.advance(1)
			copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {1,1,1})
			helpers.assert_eq(#w.urls,1)
			helpers.assert_true(w.clipboard() == w.original)
			helpers.assert_eq(w.fixture.key_posts,42)
		end)
	end)
	helpers.it("preserves the full settle interval after a short queue", function()
		World.with_world({backlog=true,pairs=1}, function(w)
			assert(w.start()); w.advance(0.21)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {1,0,0})
			w.advance(1)
			helpers.assert_true(w.trace[3].at >= w.trace[2].at + 0.2)
			helpers.assert_eq(#w.urls,1)
		end)
	end)
	helpers.it("cleanup cancels only the queued Search and retains the predecessor", function()
		World.with_world({backlog=true}, function(w)
			assert(w.start()); w.advance(0.1)
			helpers.assert_eq(w.actions.force_cleanup("shortcut_bindings"),false)
			w.advance(1)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {0,1,0})
			helpers.assert_eq(#w.urls,0)
			helpers.assert_eq(w.fixture.key_posts,42)
			helpers.assert_true(w.clipboard() == w.original)
			helpers.assert_true(w.actions.force_cleanup("shortcut_bindings"))
		end)
	end)
	helpers.it("revokes a late capture after cleanup and leaves its successor intact", function()
		World.with_world({backlog=true,pairs=1}, function(w)
			assert(w.start())
			local old
			for _,timer in ipairs(w.fixture.timers) do if timer.delay == 0.2 then old = timer end end
			assert(old); w.advance(0.1)
			helpers.assert_true(w.actions.force_cleanup("shortcut_bindings"))
			helpers.assert_true(w.actions.resume_after_cleanup("shortcut_bindings"))
			assert(w.start()); old.callback(); w.advance(1)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads}, {2,2,1})
			helpers.assert_eq(#w.urls,1)
			helpers.assert_true(w.clipboard() == w.original)
		end)
	end)
	for _,text in ipairs({"USER COPY", "SELECTED WORDS"}) do
		helpers.it("keeps a later foreign generation during recovery: " .. text, function()
			World.with_world({backlog=true}, function(w)
				w.restore_refuses = true; assert(w.start()); w.advance(0.65)
				local copies, restores, reads = w.counts()
				helpers.assert_eq({copies,restores,reads},{1,1,1})
				w.restore_refuses = false; w.external(text); w.advance(1)
				copies, restores, reads = w.counts()
				helpers.assert_eq(restores,1)
				helpers.assert_eq(w.clipboard()["public.utf8-plain-text"],text)
			end)
		end)
	end
	helpers.it("keeps known-result recovery debt while changeCount is unavailable", function()
		World.with_world({backlog=true}, function(w)
			w.restore_refuses = true; assert(w.start()); w.advance(0.65)
			w.restore_refuses = false; w.count_unavailable = true; w.advance(1)
			local copies, restores = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,1)
			helpers.assert_eq(w.actions.force_cleanup("shortcut_bindings"),false)
			w.count_unavailable = false; w.external("NEW COPY")
			helpers.assert_true(w.actions.force_cleanup("shortcut_bindings"))
			helpers.assert_eq(w.clipboard()["public.utf8-plain-text"],"NEW COPY")
		end)
	end)
	helpers.it("retries restoration without dispatching another copy", function()
		World.with_world({backlog=true}, function(w)
			w.restore_refuses = true; assert(w.start()); w.advance(0.65)
			w.restore_refuses = false; w.advance(1)
			local copies, restores = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,2)
			helpers.assert_true(w.clipboard() == w.original)
		end)
	end)
	helpers.it("does not copy when its native capture timer cannot be acquired", function()
		World.with_world({}, function(w)
			w.fixture.fail_next_do_after = true; w.start(); w.advance(1)
			local copies, restores, reads = w.counts()
			helpers.assert_eq({copies,restores,reads},{0,1,0})
			helpers.assert_eq(#w.urls,0)
			helpers.assert_true(w.clipboard() == w.original)
		end)
	end)
end)
