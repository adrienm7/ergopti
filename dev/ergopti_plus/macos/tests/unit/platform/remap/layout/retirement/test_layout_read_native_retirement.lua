--- tests/unit/platform/remap/layout/retirement/test_layout_read_native_retirement.lua
--- A SIGTERM acceptance is not the exact native exit receipt of a layout read.
local helpers = require("tests.helpers")
local World = require("tests.support.platform.remap.layout_retirement_fixture")

helpers.describe("layout watcher joins native read retirement", function()
	helpers.it("stops cleanly after an acknowledged successful read", function()
		World.with_world({}, function(w)
			helpers.assert_true(w.start()); w.poll:fire()
			w.tasks[1]:finish(0)
			helpers.assert_true(w.watchers.stop_input_source_watcher())
			helpers.assert_eq(w.counts(), { native = 0, pins = 0, constructed = 1 })
		end)
	end)

	helpers.it("keeps a stopped watcher pending until its exact native exit", function()
		World.with_world({}, function(w)
			helpers.assert_true(w.start()); w.poll:fire()
			helpers.assert_eq(w.watchers.stop_input_source_watcher(), false)
			helpers.assert_eq(w.start(), false, "restart cannot replace the outstanding read owner")
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 1 })
			w.tasks[1]:finish(143)
			helpers.assert_true(w.watchers.stop_input_source_watcher())
			helpers.assert_true(w.start()); w.poll:fire()
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 2 })
		end)
	end)

	helpers.it("blocks the installed periodic poll while a timed-out native task retires", function()
		World.with_world({}, function(w)
			helpers.assert_true(w.start()); w.poll:fire()
			local old = w.tasks[1]
			w.timeout(); w.poll:fire()
			helpers.assert_eq(old.terminations, 1)
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 1 },
				"SIGTERM cannot authorize the next periodic task before exact exit")
			old:finish(143); w.poll:fire()
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 2 })
			old.callback(143, "", "")
			w.poll:fire()
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 2 },
				"a duplicate old terminal cannot clear the successor read")
		end)
	end)

	helpers.it("keeps repeated stop pending without signalling a second native task", function()
		World.with_world({}, function(w)
			helpers.assert_true(w.start()); w.poll:fire()
			helpers.assert_eq(w.watchers.stop_input_source_watcher(), false)
			helpers.assert_eq(w.watchers.stop_input_source_watcher(), false)
			helpers.assert_eq(w.tasks[1].terminations, 1)
			helpers.assert_eq(w.counts().pins, 1)
			w.tasks[1]:finish(143)
			helpers.assert_true(w.watchers.stop_input_source_watcher())
		end)
	end)

	helpers.it("accepts exact native completion delivered during termination", function()
		World.with_world({ complete_on_terminate = true }, function(w)
			helpers.assert_true(w.start()); w.poll:fire()
			helpers.assert_true(w.watchers.stop_input_source_watcher())
			helpers.assert_eq(w.counts(), { native = 0, pins = 0, constructed = 1 })
			helpers.assert_true(w.start()); w.poll:fire()
			helpers.assert_eq(w.counts(), { native = 1, pins = 1, constructed = 2 })
		end)
	end)
end)
