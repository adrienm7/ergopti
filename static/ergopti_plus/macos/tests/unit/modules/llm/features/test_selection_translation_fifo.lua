--- tests/unit/modules/llm/features/test_selection_translation_fifo.lua

--- ==============================================================================
--- MODULE: Selection Translation Final Publication
--- DESCRIPTION:
--- Delays the real Quartz broker after Text has admitted its native copy/paste.
--- Focus notifications and translation cancellation must revoke the queued key
--- payload without AX work on the input callback.
--- ==============================================================================

local helpers = require("tests.helpers")
local Fixture = require("tests.support.modules.llm.selection_translation_fixture")
local FIFO = require("tests.support.modules.llm.selection_translation_fifo")
local function seconds(key) return require("infra.timings").sec("debounce", key) end

local function accepted(world)
	helpers.assert_true(world.flow.run("en"))
	world.flush()
	helpers.assert_eq(#world.posts, 1)
	Fixture.answer(world.posts[1], "TRANSLATION: Translated")
	local candidate = assert(world.engine.consume(1))
	helpers.assert_true(candidate.on_accept(candidate.to_type))
	world.post_next()
	world.deliver()
	world.complete_handoff()
	world.fire(seconds("clipboard_copy_settle_ms"))
	world.fire(seconds("clipboard_paste_settle_ms"))
	world.post_next()
end

helpers.describe("selection translation final Quartz publication", function()
	helpers.it("publishes a healthy translation with a real classified destination (translation-fifo-positive)", function()
		FIFO.with_world(function(world)
		accepted(world)
		world.deliver()
		world.flush()
		helpers.assert_eq(#world.document, 1)
		helpers.assert_eq(world.document[1], "Translated")
		helpers.assert_eq(world.paste_focus, "7:101")
		helpers.assert_eq(world.selection, "Translated")
		helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)


	helpers.it("waits for a retained copy before reading its clipboard (translation-fifo-copy-delay)", function()
		FIFO.with_world(function(world)
		helpers.assert_true(world.flow.run("en"))
		world.advance(seconds("clipboard_copy_settle_ms"))
		world.flush()
		helpers.assert_eq(#world.posts, 1, "a healthy queued copy must finish before its selection is read")
		helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)

	helpers.it("keeps translated clipboard until a retained paste is handed off (translation-fifo-paste-delay)", function()
		FIFO.with_world(function(world)
		accepted(world)
		world.advance(seconds("clipboard_reselect_ms"))
		world.advance(seconds("clipboard_restore_ms"))
		world.flush()
		helpers.assert_eq(#world.document, 1)
		helpers.assert_eq(world.document[1], "Translated", "queued paste must not read the restored user clipboard")
		helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)

	helpers.it("revokes paste after its broker trigger was posted (translation-fifo-focus)", function()
		FIFO.with_world(function(world)
		accepted(world)
		world.native_destination.change_focus("8:202")
		world.deliver()
		helpers.assert_eq(#world.document, 0, "a queued Cmd+V must not be handed to another window")
		world.flush()
		helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)

	helpers.it("revokes paste across reset after its broker trigger was posted (translation-fifo-reset)", function()
		FIFO.with_world(function(world)
		accepted(world)
		world.flow.reset()
		world.deliver()
		helpers.assert_eq(#world.document, 0, "a reset must revoke already queued Cmd+V")
		world.flush()
		helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)
	helpers.it("retains clipboard grace after paste handoff and reset (translation-fifo-grace-reset)", function()
		FIFO.with_world(function(world)
			accepted(world)
			world.deliver()
			world.flow.reset()
			world.complete_handoff()
			helpers.assert_eq(world.clipboard, "Translated", "native paste grace survives business revocation")
			world.advance(seconds("clipboard_restore_ms") / 2)
			helpers.assert_eq(world.clipboard, "Translated")
			world.flush()
			helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
			helpers.assert_eq(#world.document, 1)
		end)
	end)

	helpers.it("retains clipboard grace after paste handoff and pause (translation-fifo-grace-pause)", function()
		FIFO.with_world(function(world)
			accepted(world)
			world.deliver()
			local text = require("modules.shortcuts.actions.text")
			helpers.assert_eq(text.pause_text_actions(), false)
			world.complete_handoff()
			helpers.assert_eq(world.clipboard, "Translated")
			helpers.assert_eq(text.resume_text_actions(), false, "paste grace still owns the exact clipboard")
			world.flush()
			helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
			helpers.assert_eq(text.resume_text_actions(), true)
			helpers.assert_eq(#world.document, 1)
		end)
	end)

	helpers.it("accepts a healthy answer after native classification TTL (translation-fifo-ttl)", function()
		FIFO.with_world(function(world)
			helpers.assert_true(world.flow.run("en"))
			world.flush()
			world.elapse(6)
			world.tick_classification()
			Fixture.answer(world.posts[1], "TRANSLATION: Translated")
			local candidate = assert(world.engine.consume(1))
			helpers.assert_true(candidate.on_accept(candidate.to_type))
			world.flush()
			helpers.assert_eq(world.document[1], "Translated")
			helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)

	helpers.it("refuses a stopped native destination tracker before copying (translation-fifo-unknown)", function()
		FIFO.with_world(function(world)
			world.native_destination.utils.stop()
			helpers.assert_eq(world.flow.run("en"), false)
			helpers.assert_eq(#world.quartz.triggers, 0)
			helpers.assert_eq(#world.posts, 0)
			helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
		end)
	end)

	helpers.it("settles the exact copy when native build reenters pause (translation-fifo-build-pause)", function()
		FIFO.with_world(function(world)
			world.flow.run("en")
			world.flush()
			local text = require("modules.shortcuts.actions.text")
			helpers.assert_true(world.pause_seen, "the real native event-construction boundary must run")
			helpers.assert_eq(#world.document, 0)
			helpers.assert_eq(#world.posts, 0)
			helpers.assert_eq(world.clipboard, Fixture.USER_CLIPBOARD)
			helpers.assert_eq(text.has_pending_text_action(), false)
			helpers.assert_eq(text.resume_text_actions(), true)
		end, function(world)
			local original = hs.eventtap.event.newKeyEvent
			hs.eventtap.event.newKeyEvent = function(...)
				if not world.pause_seen then
					world.pause_seen = true
					helpers.assert_eq(require("modules.shortcuts.actions.text").pause_text_actions(), false)
				end
				return original(...)
			end
		end)
	end)
end)
