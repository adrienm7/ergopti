// tools/codegen/codegen-secure-apps.cjs

/**
 * ==============================================================================
 * MODULE: Application Identity Data Generator
 * DESCRIPTION:
 * Projects the shared application-identity data into shared Lua data, so the
 * Lua drivers read it without filesystem work or path-port initialization:
 * _shared/data/secure_apps.json, the one list of password managers every
 * driver treats as a secure field (ADD-1), read on the focus path, and
 * _shared/data/linux_app_identities.json, the comm-to-WM-class aliases the
 * Linux exclusion-list conversion reads once (ADD-3).
 * ==============================================================================
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { shared } = require('../lib/paths.cjs');

/** Serializes JSON values without introducing Lua-incompatible Unicode escapes. */
function literal(value, depth = 0) {
	if (typeof value === 'string')
		return JSON.stringify(value).replace(/\\u([0-9a-f]{4})/gi, (_match, hex) => {
			const code = parseInt(hex, 16);
			return code < 256 ? `\\${String(code).padStart(3, '0')}` : String.fromCharCode(code);
		});
	if (typeof value === 'number' || typeof value === 'boolean') return String(value);
	const indent = '\t'.repeat(depth + 1);
	if (Array.isArray(value)) {
		if (value.length === 0) return '{}';
		return `{\n${value.map((item) => `${indent}${literal(item, depth + 1)},`).join('\n')}\n${'\t'.repeat(depth)}}`;
	}
	const entries = Object.entries(value).map(
		([key, item]) => `${indent}[${literal(key)}] = ${literal(item, depth + 1)},`
	);
	return `{\n${entries.join('\n')}\n${'\t'.repeat(depth)}}`;
}

/**
 * Writes one projection: the source's fields without its description.
 * Both paths are spelled at the call site so a move of either file rewrites
 * it with the file.
 * @param {string} source Absolute path of the JSON source.
 * @param {string} target Absolute path of the generated module.
 */
function project(source, target, pick) {
	const data = JSON.parse(fs.readFileSync(source, 'utf8'));
	const sharedPath = (p) => `_shared/${path.relative(shared(), p).split(path.sep).join('/')}`;
	const header = sharedPath(target);
	fs.writeFileSync(
		target,
		`--- ${header}\n\n` +
			'--- Generated by tools/codegen/codegen-secure-apps.cjs; do not edit.\n' +
			`--- Source: ${sharedPath(source)}.\n` +
			`return ${literal(pick(data))}\n`,
		'utf8'
	);
}

project(shared('data', 'secure_apps.json'), shared('lua', 'secure_apps_data.lua'), ({ apps }) => ({
	apps
}));
project(
	shared('data', 'linux_app_identities.json'),
	shared('lua', 'linux_app_identities_data.lua'),
	({ marker, aliases, same }) => ({
		marker,
		aliases,
		same
	})
);
console.log('[OK] Generated shared application identity data.');
