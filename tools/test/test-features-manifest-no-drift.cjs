// tools/test/test-features-manifest-no-drift.cjs

/**
 * ==============================================================================
 * MODULE: Generated Features Manifest — No Drift Guard
 * DESCRIPTION:
 * Regression guard for F-MED-31 — static/ergopti_plus/macos/_generated/features_manifest.lua
 * (and its sibling static/ergopti_plus/windows/_generated/features_manifest.ahk)
 * are git-tracked, NOT gitignored (a sibling test's doc-comment incorrectly
 * claimed otherwise — see the F-MED-31 fix to test-manifest-parity.cjs). CI
 * always regenerates-then-tests, so a stale hand-edit is invisible there — but
 * it ships to users unregenerated in any local build that never re-runs
 * `npm run build:manifest`, silently diverging from manifest.toml.
 *
 * ROOT CAUSE ENCODED:
 * build-features-manifest.js writes to hardcoded output paths (no output-dir
 * override), so this guard snapshots the committed file's bytes, runs the real
 * generator in place (exactly as `npm run build:manifest` / CI does), diffs the
 * regenerated bytes against the snapshot, and restores the original file
 * afterward regardless of outcome — the check never leaves the working tree
 * dirty, whether it passes or fails.
 *
 * FEATURES & RATIONALE:
 * 1. Byte-for-byte diff against the REAL generator, not a hand-rolled
 *    parse-and-compare — the strongest guarantee against drift, and exactly
 *    what a reviewer would run manually to double-check a suspicious diff.
 * 2. Guards both driver twins (macOS .lua and Windows .ahk) in one pass since
 *    a single generator invocation writes both.
 * 3. Snapshot/restore wraps the regeneration in try/finally so a crash mid-test
 *    (or a real drift found and left as a "fix" by a future run) cannot leave
 *    the repo in a modified state — restoring the pre-test bytes is always the
 *    last action.
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const GENERATOR = path.join(ROOT, 'tools/build/build-features-manifest.js');

const TARGETS = [
	'static/ergopti_plus/macos/_generated/features_manifest.lua',
	'static/ergopti_plus/windows/_generated/features_manifest.ahk'
];

const snapshots = new Map();
for (const rel of TARGETS) {
	snapshots.set(rel, fs.readFileSync(path.join(ROOT, rel)));
}

let regenerationFailed = false;
let regenerationError = null;

try {
	execFileSync('node', [GENERATOR], { cwd: ROOT, stdio: 'pipe' });
} catch (err) {
	regenerationFailed = true;
	regenerationError = err;
} finally {
	// Restore every target to its pre-test bytes, unconditionally, BEFORE any
	// assertion runs — a failing assertion below must never leave the repo
	// changed relative to how this test found it.
	const driftedFiles = [];
	for (const rel of TARGETS) {
		const absPath = path.join(ROOT, rel);
		const before = snapshots.get(rel);
		const after = fs.existsSync(absPath) ? fs.readFileSync(absPath) : null;
		if (after === null || !before.equals(after)) {
			driftedFiles.push(rel);
		}
		fs.writeFileSync(absPath, before);
	}
	// Stash the drift list on the outer scope for the report below.
	module.exports = { driftedFiles };
}

const { driftedFiles } = module.exports;

if (regenerationFailed) {
	console.error('\x1b[31m[ERROR] failed to run the features-manifest generator:\x1b[0m');
	console.error('  ' + (regenerationError && regenerationError.message));
	process.exit(1);
}

if (driftedFiles.length > 0) {
	console.error('\x1b[31m[ERROR] generated features manifest has drifted from manifest.toml:\x1b[0m');
	for (const f of driftedFiles) {
		console.error(`  - ${f} differs from what \`npm run build:manifest\` produces — ` +
			're-run the generator and commit the refreshed file (F-MED-31).');
	}
	process.exit(1);
}

console.log('\x1b[32m[OK] committed features_manifest.lua/.ahk match the live generator output (no drift, F-MED-31).\x1b[0m');
