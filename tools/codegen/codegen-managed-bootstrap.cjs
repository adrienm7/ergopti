// tools/codegen/codegen-managed-bootstrap.cjs
// Embeds the canonical private bootstrap policy in the signed native image.

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const shared = path.join(root, 'static/ergopti_plus/_shared/modules');
const output = path.join(
	root,
	'static/ergopti_plus/macos/launcher/Sources/ErgoptiPlus/ManagedBootstrapPolicy.generated.swift'
);

function strictJSON(bytes) {
	const source = bytes.toString('utf8');
	if (!Buffer.from(source).equals(bytes)) throw new Error('Policy is not UTF-8.');
	const value = JSON.parse(source);
	const tokens = source.match(
		/"(?:[^"\\]|\\.)*"|-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?|true|false|null|[{}\[\],:]/g
	);
	let at = 0;
	function read() {
		const opening = tokens[at++];
		if (opening === '{') {
			const seen = new Set();
			while (tokens[at] !== '}') {
				const key = JSON.parse(tokens[at++]);
				if (seen.has(key)) throw new Error('Duplicate policy field.');
				seen.add(key);
				at++;
				read();
				if (tokens[at] === ',') at++;
			}
			at++;
		} else if (opening === '[') {
			while (tokens[at] !== ']') {
				read();
				if (tokens[at] === ',') at++;
			}
			at++;
		}
	}
	read();
	return value;
}

function render(bootstrapBytes, proxyBytes) {
	const policy = strictJSON(bootstrapBytes);
	const proxy = strictJSON(proxyBytes);
	const fields = [
		'schema_version',
		'maximum_metadata_bytes',
		'hmac_domain',
		'trust_environment',
		'maximum_certificate_bytes',
		'maximum_certificate_files'
	];
	if (
		Object.keys(policy).sort().join() !== fields.sort().join() ||
		policy.schema_version !== 1 ||
		!Number.isSafeInteger(policy.maximum_metadata_bytes) ||
		policy.maximum_metadata_bytes <= 0 ||
		!Number.isSafeInteger(policy.maximum_certificate_bytes) ||
		policy.maximum_certificate_bytes <= 0 ||
		!Number.isSafeInteger(policy.maximum_certificate_files) ||
		policy.maximum_certificate_files <= 0 ||
		typeof policy.hmac_domain !== 'string' ||
		!/^[A-Z0-9_]+\n$/.test(policy.hmac_domain) ||
		!Array.isArray(policy.trust_environment) ||
		policy.trust_environment.length !== 2 ||
		proxy.schema_version !== 1 ||
		!Number.isSafeInteger(proxy.max_proxy_bytes) ||
		proxy.max_proxy_bytes <= 0
	) {
		throw new Error('Invalid bootstrap policy.');
	}
	for (const names of [
		policy.trust_environment,
		proxy.system_lookup_environment_exclusions,
		proxy.environment_bypass_precedence
	]) {
		if (
			!Array.isArray(names) ||
			names.length === 0 ||
			new Set(names).size !== names.length ||
			names.some((name) => typeof name !== 'string' || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(name))
		) {
			throw new Error('Invalid bootstrap environment names.');
		}
	}
	const names = [
		...proxy.system_lookup_environment_exclusions,
		...proxy.environment_bypass_precedence,
		...policy.trust_environment
	];
	if (new Set(names).size !== names.length)
		throw new Error('Overlapping bootstrap environment names.');
	const literal = (value) => JSON.stringify(value);
	return (
		'// Sources/ErgoptiPlus/ManagedBootstrapPolicy.generated.swift\n' +
		'// Generated by tools/codegen/codegen-managed-bootstrap.cjs; do not edit.\n' +
		'// Sources: _shared/modules/llm/managed_ollama_bootstrap.json and network/proxy_policy.json.\n\n' +
		'enum ManagedBootstrapPolicy {\n' +
		`\tstatic let maximumMetadataBytes = ${policy.maximum_metadata_bytes}\n` +
		`\tstatic let hmacDomain = ${literal(policy.hmac_domain)}\n` +
		`\tstatic let trustEnvironment = ${literal(policy.trust_environment)}\n` +
		`\tstatic let allowedEnvironment = ${literal(names)}\n` +
		`\tstatic let maximumProxyBytes = ${proxy.max_proxy_bytes}\n` +
		`\tstatic let maximumCertificateBytes = ${policy.maximum_certificate_bytes}\n` +
		`\tstatic let maximumCertificateFiles = ${policy.maximum_certificate_files}\n` +
		'}\n'
	);
}

function generate() {
	const text = render(
		fs.readFileSync(path.join(shared, 'llm/managed_ollama_bootstrap.json')),
		fs.readFileSync(path.join(shared, 'network/proxy_policy.json'))
	);
	if (process.argv.includes('--check')) {
		if (fs.readFileSync(output, 'utf8') !== text) throw new Error('Bootstrap policy drift.');
	} else fs.writeFileSync(output, text);
}

if (require.main === module) generate();
module.exports = { render };
