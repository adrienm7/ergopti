// tools/codegen/codegen-menu-section-header.cjs

/**
 * ==============================================================================
 * MODULE: Menu Section Header Format Generator
 * DESCRIPTION:
 * Projects the one section-header format of _shared/menu/data/section_header.json
 * into shared Lua data (menu.labels on macOS and Linux) and into the Windows
 * driver's generated constants (MenuSectionTitle), so no driver spells the
 * frame of a header itself.
 *
 * FEATURES & RATIONALE:
 * 1. The format holds exactly one {label}: a header with no title, or with it
 *    twice, would be drawn wrong in every menu at once.
 * 2. Only the text around the title is projected, so both readers concatenate
 *    and never run a pattern over a translated title.
 * ==============================================================================
 */
'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { REPO_ROOT, shared } = require('../lib/paths.cjs');

const PLACEHOLDER = '{label}';

/** Serializes a string as a Lua literal, escaping what Lua reads differently. */
function literal(text) {
	return JSON.stringify(text).replace(/\\u([0-9a-f]{4})/gi, (_match, hex) => {
		const code = parseInt(hex, 16);
		return code < 256 ? `\\${String(code).padStart(3, '0')}` : String.fromCharCode(code);
	});
}

/** Serializes a string as an AutoHotkey v2 double-quoted literal. */
function ahkLiteral(text) {
	assert(!/[\r\n]/.test(text), 'a section header frame is one line');
	return `"${text.replace(/`/g, '``').replace(/"/g, '`"')}"`;
}

const source = shared('menu', 'data', 'section_header.json');
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
assert.equal(typeof data.format, 'string', 'section_header.json: format is a string');
const parts = data.format.split(PLACEHOLDER);
assert.equal(parts.length, 2, `section_header.json: the format holds ${PLACEHOLDER} exactly once`);
const [prefix, suffix] = parts;

fs.writeFileSync(
	shared('menu', 'engine', 'section_header_data.lua'),
	'--- _shared/menu/engine/section_header_data.lua\n\n' +
		'--- Generated by tools/codegen/codegen-menu-section-header.cjs; do not edit.\n' +
		'--- Source: _shared/menu/data/section_header.json.\n' +
		`return {\n\tprefix = ${literal(prefix)},\n\tsuffix = ${literal(suffix)},\n}\n`,
	'utf8'
);
fs.writeFileSync(
	path.join(
		REPO_ROOT,
		'static',
		'ergopti_plus',
		'windows',
		'_generated',
		'menu_section_header.ahk'
	),
	'﻿; _generated/menu_section_header.ahk\n\n' +
		'; Generated by tools/codegen/codegen-menu-section-header.cjs; do not edit.\n' +
		'; Source: _shared/menu/data/section_header.json.\n\n' +
		'#Requires AutoHotkey v2.0\n\n' +
		`global MENU_SECTION_HEADER_PREFIX := ${ahkLiteral(prefix)}\n` +
		`global MENU_SECTION_HEADER_SUFFIX := ${ahkLiteral(suffix)}\n`,
	'utf8'
);
console.log('[OK] Generated shared menu section header format.');
