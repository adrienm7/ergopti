describe("Shared asynchronous pause ownership",function()
	local function actor_fixture()
		local now,records,failures=0,{},{}
		local actor=require("keylogger.physical_lifecycle_observation").new("pause",function() now=now+1;return now end,function(reason) failures[#failures+1]=reason end)
		local owner={}
		local token=actor.bind(owner,100,function(record) records[#records+1]=record;return true end)
		return actor,records,owner,token,failures
	end
	local function snapshot(paused,released)
		return function() return {paused=paused,transition_generation=2,admission_released=released,settled=true} end
	end
	it("async pending writer stays denied until its exact finish",function()
		local actor,records=actor_fixture()
		local ticket=actor.begin("pause")
		denied(records)
		helpers.assert_eq(actor.finish({},snapshot(true,false),true),false)
		helpers.assert_eq(actor.finish(ticket,snapshot(true,false),true),true)
		helpers.assert_eq(last(records).complete,true)
		helpers.assert_eq(last(records).allowed,false)
	end)
	it("resume cannot complete before exact admission release",function()
		local actor,records=actor_fixture()
		local ticket=actor.begin("resume")
		actor.finish(ticket,snapshot(false,false),true)
		denied(records)
	end)
	it("foreign target or unset settlement cannot complete",function()
		local actor,records=actor_fixture()
		local ticket=actor.begin("pause")
		actor.finish(ticket,snapshot(false,true),true);denied(records)
		ticket=actor.begin("resume")
		actor.finish(ticket,function() return {paused=false,transition_generation=2,admission_released=true,settled=false} end,true)
		denied(records)
	end)
	it("old owner finish skips all snapshot queries after replacement",function()
		local actor,records,owner,token=actor_fixture()
		local ticket=actor.begin("pause")
		actor.unbind(owner,token)
		local replacement={}
		helpers.assert_true(actor.bind(replacement,100,function(record) records[#records+1]=record;return true end)~=nil)
