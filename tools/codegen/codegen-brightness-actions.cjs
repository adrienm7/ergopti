/**
 * ==============================================================================
 * MODULE: Native Brightness Data Generator
 * DESCRIPTION:
 * Projects canonical native encodings into shared Lua data, avoiding filesystem
 * work and path-port initialization inside keyboard and gesture callbacks.
 * ==============================================================================
 */
'use strict';

const fs = require('fs');
const { shared } = require('../lib/paths.cjs');

/** Serializes JSON values without introducing Lua-incompatible Unicode escapes. */
function literal(value, depth = 0) {
	if (typeof value === 'string')
		return JSON.stringify(value).replace(/\\u([0-9a-f]{4})/gi, (_match, hex) => {
			const code = parseInt(hex, 16);
			return code < 256 ? `\\${String(code).padStart(3, '0')}` : String.fromCharCode(code);
		});
	if (typeof value === 'number' || typeof value === 'boolean') return String(value);
	if (value === null) return 'nil';
	const indent = '\t'.repeat(depth + 1);
	const entries = Object.entries(value).map(
		([key, item]) => `${indent}[${literal(key)}] = ${literal(item, depth + 1)},`
	);
	return `{\n${entries.join('\n')}\n${'\t'.repeat(depth)}}`;
}

const source = shared('modules', 'actions', 'brightness.json');
const target = shared('lua', 'brightness_actions_data.lua');
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
fs.writeFileSync(
	target,
	'--- _shared/lua/brightness_actions_data.lua\n\n' +
		'--- Generated by tools/codegen/codegen-brightness-actions.cjs; do not edit.\n' +
		'--- Source: _shared/modules/actions/brightness.json.\n' +
		`return ${literal(data)}\n`,
	'utf8'
);
console.log('[OK] Generated shared native brightness data.');
