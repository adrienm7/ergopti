"""Project immutable vendor catalogue data into the read-only report's two-file roster."""

from pathlib import Path
import hashlib
import re

SOURCE = Path(__file__).parent / "fixtures/vhd-daemon-report-reference-source.swift.txt"
OUTPUT = Path(__file__).parents[2] / (
    "static/ergopti_plus/macos/launcher/Sources/ErgoptiPlus/"
    "OwnedVirtualHIDDaemonReportReference.swift"
)
SOURCE_SHA256 = "224f9583a53ee5c08681f1814737e69203b699092663030e5e05b06feabf65b4"
DAEMON = (
    "/Library/Application Support/org.pqrs/Karabiner-DriverKit-VirtualHIDDevice/"
    "Applications/Karabiner-VirtualHIDDevice-Daemon.app"
)
LEAVES = (
    DAEMON + "/Contents/Info.plist",
    DAEMON + "/Contents/MacOS/Karabiner-VirtualHIDDevice-Daemon",
)


def generate(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("original immutable daemon catalogue differs")
    rows = []
    for path in LEAVES:
        pattern = re.escape('  "' + path[1:] + '": (false, ') + r'(\d+), "([0-9a-f]{64})"\),'
        matches = re.findall(pattern, source.decode("utf-8"))
        if len(matches) != 1:
            raise ValueError("daemon catalogue leaf is not unique")
        size, digest = matches[0]
        rows.append(f'\t\t"{path[1:]}": (false, {size}, "{digest}"),')
    return (
        "// Generated by tools/build/generate_vhd_daemon_report_reference.py. Do not edit.\n"
        f"// Immutable original catalogue SHA256: {SOURCE_SHA256}\n"
        "enum OwnedVirtualHIDDaemonReportReference {\n"
        f'\tstatic let daemon = "{DAEMON}"\n'
        f'\tstatic let daemonExecutable = "{LEAVES[1]}"\n'
        "\tstatic let entries: [String: (directory: Bool, bytes: Int, hash: String)] = [\n"
        + "\n".join(rows)
        + "\n\t]\n}\n"
    ).encode("utf-8")


if __name__ == "__main__":
    OUTPUT.write_bytes(generate(SOURCE.read_bytes()))
