// tools/codegen/codegen-file-system-ports.cjs

/**
 * ==============================================================================
 * MODULE: FileSystem Port Spec Generator
 * DESCRIPTION:
 * Projects the method names of _shared/lua/file_system/ports.lua into a generated
 * AutoHotkey table, because AutoHotkey cannot load the Lua spec. The Windows
 * file-system owner checks itself against that table when it loads.
 *
 * FEATURES & RATIONALE:
 * 1. Only names are projected: the signatures stay in the spec, for people.
 * 2. A spec the parser cannot read fails here: no section, no method.
 * ==============================================================================
 */

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { REPO_ROOT, shared } = require('../lib/paths.cjs');

const TARGET = path.join(
	REPO_ROOT,
	'static',
	'ergopti_plus',
	'windows',
	'_generated',
	'file_system_ports.ahk'
);

/**
 * Reads the two method tables of the spec.
 * @param {string} text ports.lua source.
 * @returns {{contract: string[], capabilities: Record<string, string[]>}}
 */
function parseSpec(text) {
	const section = (name) => {
		const match = text.match(new RegExp(`^M\\.${name} = \\{\\n([\\s\\S]*?)^\\}$`, 'm'));
		assert(match, `ports.lua has no ${name} table`);
		const groups = {};
		for (const group of match[1].matchAll(/^\t(\w+) = \{\n([\s\S]*?)^\t\},?$/gm)) {
			groups[group[1]] = [...group[2].matchAll(/^\t\t(\w+) = "/gm)].map((m) => m[1]).sort();
			assert(groups[group[1]].length > 0, `${group[1]} declares no method`);
		}
		return groups;
	};
	const { FileSystem: contract } = section('CONTRACTS');
	assert(contract, 'ports.lua has no FileSystem contract');
	return { contract, capabilities: section('CAPABILITIES') };
}

/** The generated AutoHotkey source. */
function render({ contract, capabilities }) {
	const list = (names) => `[${names.map((name) => JSON.stringify(name)).join(', ')}]`;
	const rows = Object.keys(capabilities)
		.sort()
		.map((name) => `\t${JSON.stringify(name)}, ${list(capabilities[name])}`);
	return (
		'﻿; _generated/file_system_ports.ahk\n\n' +
		'; Generated by tools/codegen/codegen-file-system-ports.cjs; do not edit.\n' +
		'; Source: _shared/lua/file_system/ports.lua.\n\n' +
		'#Requires AutoHotkey v2.0\n\n' +
		`global FILE_SYSTEM_PORT_CONTRACT := ${list(contract)}\n\n` +
		`global FILE_SYSTEM_PORT_CAPABILITIES := Map(\n${rows.join(',\n')}\n)\n`
	);
}

if (require.main === module) {
	const spec = parseSpec(fs.readFileSync(shared('lua', 'file_system', 'ports.lua'), 'utf8'));
	fs.writeFileSync(TARGET, render(spec), 'utf8');
	console.log('[OK] Generated the Windows file-system port table.');
}

module.exports = { parseSpec, render, TARGET };
