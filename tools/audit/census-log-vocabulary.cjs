// tools/audit/census-log-vocabulary.cjs

/**
 * ==============================================================================
 * MODULE: Log Vocabulary Census
 * DESCRIPTION:
 * Counts every `reason`, `phase`, `[TAG]` and evidence-record field literal in
 * driver source, per value and per driver, and writes the result as data to
 * docs/audits/2026-10-24-log-vocabulary-census.json.
 *
 * The cross-OS parity audit (K11) estimated "about 189 reason, 56 phase and 62
 * [TAG] literals" and listed the evidence-record field names as not censused.
 * A closed enum cannot be declared from an estimate: this census is the
 * measured starting point, and the closed vocabulary in
 * _shared/modules/logger/vocabulary.json is seeded from it.
 *
 * It is a measurement, not a generator: re-running it must never widen the
 * closed vocabulary, which only a deliberate edit can do.
 *
 * USAGE:
 *   node tools/audit/census-log-vocabulary.cjs           print the summary
 *   node tools/audit/census-log-vocabulary.cjs --write   also rewrite the data file
 * ==============================================================================
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const Scan = require('../lib/log-vocabulary-scan.cjs');
const { allOutputs } = require('../build/generators.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const VOCABULARY = 'static/ergopti_plus/_shared/modules/logger/vocabulary.json';
const OUTPUT = 'docs/audits/2026-10-24-log-vocabulary-census.json';
const DRIVERS = ['windows', 'macos', 'linux', '_shared'];

/** The driver tree a repository path belongs to. */
function driverOf(file) {
	const segment = file.split('/')[2];
	if (!DRIVERS.includes(segment)) throw new Error(`${file}: outside the four driver trees`);
	return segment;
}

/**
 * Builds the census from a scan.
 * @returns {object} The data written to OUTPUT.
 */
function census(root = ROOT) {
	const vocabulary = JSON.parse(fs.readFileSync(path.join(root, VOCABULARY), 'utf8'));
	const { hits, missingFormatters } = Scan.scanTree(root, {
		generated: new Set(allOutputs()),
		formatters: vocabulary.evidence_record_formatters
	});
	if (missingFormatters.length > 0)
		throw new Error(`declared evidence formatter(s) not found: ${missingFormatters.join(', ')}`);
	const out = {
		_comment:
			'GENERATED by tools/audit/census-log-vocabulary.cjs --write: a measurement of hand-typed log vocabulary in driver source (tests, vendored and generated files excluded). Not a source of truth; the closed enums live in _shared/modules/logger/vocabulary.json.',
		kinds: {}
	};
	for (const kind of Scan.KINDS) {
		const own = hits.filter((h) => h.kind === kind);
		const values = {};
		const free = {};
		for (const h of own) {
			if (h.free) {
				free[h.file] = (free[h.file] || 0) + 1;
				continue;
			}
			const entry = (values[h.value] ||= { count: 0, drivers: {} });
			entry.count++;
			const driver = driverOf(h.file);
			entry.drivers[driver] = (entry.drivers[driver] || 0) + 1;
		}
		const sortedValues = {};
		for (const v of Object.keys(values).sort()) sortedValues[v] = values[v];
		const sortedFree = {};
		for (const f of Object.keys(free).sort()) sortedFree[f] = free[f];
		out.kinds[kind] = {
			literals: own.length,
			distinct_values: Object.keys(values).length,
			in_more_than_one_driver: Object.values(values).filter(
				(v) => Object.keys(v.drivers).length > 1
			).length,
			files: new Set(own.map((h) => h.file)).size,
			free_form_literals: own.filter((h) => h.free).length,
			values: sortedValues,
			free_form_by_file: sortedFree
		};
	}
	return out;
}

function main() {
	const data = census();
	for (const kind of Scan.KINDS) {
		const k = data.kinds[kind];
		console.log(
			`${kind}: ${k.literals} literal(s), ${k.distinct_values} distinct code-shaped value(s) ` +
				`(${k.in_more_than_one_driver} in two or more drivers), ${k.free_form_literals} free-form, ` +
				`${k.files} file(s)`
		);
	}
	if (process.argv.includes('--write')) {
		fs.writeFileSync(path.join(ROOT, OUTPUT), JSON.stringify(data, null, '\t') + '\n', 'utf8');
		console.log(`wrote ${OUTPUT}`);
	}
}

if (require.main === module) main();

module.exports = { VOCABULARY, OUTPUT, census };
