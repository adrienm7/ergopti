--- Drives actual pause writers with independent before/after receipt expectations.
--- Native APIs are adversarial doubles; this does not prove installed macOS input.
local helpers = require("tests.helpers")
local fixture = require("tests.support.pause_transaction_fixture")
local describe, it = helpers.describe, helpers.it
local function last(records) return records[#records] end

local function with_context(options, callback)
	options = options or {}
	return helpers.with_stub_scope({"keylogger.physical_lifecycle_observation","adapters.physical_observation_clock"},function()
		return fixture.with_context(options,function(script,ctx)
			local reads,records,owner,token=0,{},{}
			hs.timer.absoluteTime=function() reads=reads+1; return reads end
			ctx.clock_reads=function() return reads end
			ctx.observe_records=records
			ctx.observe_owner=owner
			if options.unbound ~= true then
				token=script.bind_physical_pause_observer(owner,options.capacity or 100,function(record,observed_token)
					records[#records+1]=record
					if options.receive then return options.receive(script,ctx,record,observed_token) end
					return true
				end)
				helpers.assert_true(token~=nil)
			end
			return callback(script,ctx,records,owner,token)
		end)
	end)
end
local function commit_pause(script,ctx)
	helpers.assert_eq(script.pause_all(),true)
	ctx.fire_deferred()
	ctx.pause_callback(true,"paused")
end
local function commit_resume(script,ctx)
	helpers.assert_eq(script.resume_all(),true)
	ctx.fire_deferred()
	ctx.resume_callback(true,"resumed")
end
local function denied(records)
	helpers.assert_eq(last(records).allowed,false)
	helpers.assert_eq(last(records).complete,false)
end

