# ======= 3/ Entry =========
# ==========================


def main(argv):
    parser = argparse.ArgumentParser(
        description="One verdict per TODO « To confirm on the Mac » point."
    )
    parser.add_argument(
        "--report", help="The field report folder (field_run/ and steps.txt inside)."
    )
    parser.add_argument("--installed", action="store_true", help="The run was --installed.")
    parser.add_argument("--os", choices=sorted(TARGETS), default="macos", help="The report's OS.")
    parser.add_argument(
        "--doc", action="store_true", help="Print the documentation's coverage table."
    )
    parser.add_argument(
        "--check-doc", action="store_true", help="Fail when the documentation's table is stale."
    )
    args = parser.parse_args(argv)
    target = TARGETS[args.os]
    coverage, spec = load(os.path.join(REPO_ROOT, target["coverage"])), load_specs(target)
    if args.doc:
        print(render_doc_table(coverage, spec))
        return 0
    if args.check_doc:
        with open(os.path.join(REPO_ROOT, target["doc"]), encoding="utf-8") as handle:
            block = doc_block(handle.read())
        if block is None or normalized_table(block) != normalized_table(
            render_doc_table(coverage, spec)
        ):
            print(
                f"{target['doc']}: the coverage table is stale; "
                f"regenerate it with tools/dev/field-todo-summary.py --os {args.os} --doc.",
                file=sys.stderr,
            )
            return 1
        return 0
    if not args.report:
        parser.error("--report, --doc or --check-doc is required")
    records = summarize(
        coverage,
        spec,
        {
            step: result
            for folder in target["results"]
            for step, result in read_results(os.path.join(args.report, folder)).items()
        },
        read_collector_steps(os.path.join(args.report, "steps.txt")),
        args.installed,
    )
    markdown = render_markdown(records, args.installed, target["section"])
    with open(os.path.join(args.report, "todo_summary.md"), "w", encoding="utf-8") as handle:
        handle.write(markdown)
    with open(os.path.join(args.report, "todo_summary.json"), "w", encoding="utf-8") as handle:
        json.dump(
            {
                "schema": 1,
                "installed": args.installed,
                "points": records,
            },
            handle,
            ensure_ascii=False,
            indent="\t",
        )
        handle.write("\n")
    for record in records:
        print(
            f"{MARKS.get(record['verdict'], '')} {record['verdict']:<13} {record['id']}"
            + (
                f"  (not field-testable: {record['not_testable']})"
                if record["verdict"] == "not_testable"
                else ""
            )
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
