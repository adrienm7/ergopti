// tools/test/test-proxy-policy-single-source.cjs

/**
 * ==============================================================================
 * MODULE: Proxy Policy Single-Source Ratchet
 * DESCRIPTION:
 * _shared/modules/network/proxy_policy.json is the one declaration of the
 * proxy environment precedence. Lua, Python and PowerShell read it at
 * runtime; Go and Swift get generated copies (codegen-managed-bootstrap.cjs,
 * drift-checked). This gate finds every remaining hand-typed copy of the
 * HTTPS precedence in production source, in any syntax, and:
 *   1. refuses a copy that is not in KNOWN_COPIES (a new hand-typed copy);
 *   2. refuses a known copy whose order differs from the JSON, so a change of
 *      the canonical precedence cannot leave a driver behind silently;
 *   3. refuses a KNOWN_COPIES entry whose copy is gone (the ratchet shrinks).
 * ==============================================================================
 */

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const POLICY = 'static/ergopti_plus/_shared/modules/network/proxy_policy.json';

// Each remaining copy, how many times the file spells it, and why it is not
// generated yet. Remove an entry when its copy is replaced by the JSON.
const KNOWN_COPIES = new Map([
	[
		'static/ergopti_plus/windows/adapters/http_client.ahk',
		{
			count: 2,
			reason:
				'curl relay inheritance check; the file is pinned by the sealed key-combination cohort inputs'
		}
	],
	[
		'static/ergopti_plus/macos/adapters/release_stage.sh',
		{ count: 1, reason: 'POSIX shell parameter expansion before any JSON reader is available' }
	],
	[
		'static/ergopti_plus/macos/modules/llm/network-retry.sh',
		{
			count: 2,
			reason:
				'POSIX shell parameter expansion and relay presence check before any JSON reader is available'
		}
	],
	[
		'static/ergopti_plus/macos/modules/llm/network_env.lua',
		{ count: 1, reason: 'emits the shell admission guard that network-retry.sh evaluates' }
	]
]);

const SOURCE_EXTENSIONS = new Set([
	'.ahk',
	'.lua',
	'.py',
	'.go',
	'.swift',
	'.sh',
	'.ps1',
	'.js',
	'.cjs'
]);

/**
 * Finds the proxy variable names a line spells, in order of appearance.
 * @param {string} line
 * @returns {string[]}
 */
function proxyNames(line) {
	return [
		...line.matchAll(
			/(?<![A-Za-z0-9_])(https?_proxy|HTTPS?_PROXY|all_proxy|ALL_PROXY)(?![A-Za-z0-9_])/g
		)
	].map((match) => match[1]);
}

/**
 * Lists the hand-typed policy copies of one file's text. A line naming the four
 * https names is a copy: with an http name too it is the "any relay variable
 * set" inventory (compared as a set with system_lookup_environment_exclusions),
 * otherwise it is the https precedence (compared in order).
 * @param {string} text
 * @returns {{kind: string, names: string[]}[]}
 */
function copiesIn(text) {
	const copies = [];
	for (const line of text.split('\n')) {
		const names = proxyNames(line);
		if (
			!['https_proxy', 'HTTPS_PROXY', 'all_proxy', 'ALL_PROXY'].every((name) =>
				names.includes(name)
			)
		)
			continue;
		const any = names.includes('http_proxy') || names.includes('HTTP_PROXY');
		copies.push({ kind: any ? 'set' : 'precedence', names });
	}
	return copies;
}

const policy = JSON.parse(fs.readFileSync(path.join(ROOT, POLICY), 'utf8'));
const canonical = {
	precedence: policy.environment_precedence.https.join(','),
	set: [...policy.system_lookup_environment_exclusions].sort().join(',')
};
// A wholly generated file says so in its header; a file a generator only
// patches in place (network-retry.sh) is hand-written and stays scanned.
const isGenerated = (text) =>
	/AUTO-GENERATED|Generated by|do not edit/i.test(text.split('\n').slice(0, 5).join('\n'));
const tracked = execFileSync('git', ['ls-files', '-z', '--', 'static'], {
	cwd: ROOT,
	encoding: 'utf8'
})
	.split('\0')
	.filter(Boolean)
	.filter((file) => SOURCE_EXTENSIONS.has(path.extname(file)))
	.filter((file) => !/(^|\/)tests?\//.test(file) && !/_test\.(go|py)$/.test(file))
	.filter((file) => fs.existsSync(path.join(ROOT, file)));

// The detector itself must see a copy in every syntax it claims to cover.
assert.equal(
	copiesIn('Names := ["https_proxy", "HTTPS_PROXY", "all_proxy", "ALL_PROXY"]').length,
	1
);
assert.equal(
	copiesIn('x="${https_proxy:-${HTTPS_PROXY:-${all_proxy:-${ALL_PROXY:-}}}}"').length,
	1
);
assert.equal(copiesIn('names = ("https_proxy", "all_proxy")').length, 0);
assert.equal(
	copiesIn(
		'[ -z "${HTTPS_PROXY:-}${https_proxy:-}${HTTP_PROXY:-}${ALL_PROXY:-}${all_proxy:-}" ]'
	)[0].kind,
	'set'
);

const found = new Map();
const problems = [];
for (const file of tracked) {
	const text = fs.readFileSync(path.join(ROOT, file), 'utf8');
	if (isGenerated(text)) continue;
	const copies = copiesIn(text);
	if (copies.length === 0) continue;
	found.set(file, copies.length);
	const known = KNOWN_COPIES.get(file);
	if (!known) {
		problems.push(`${file}: a new hand-typed proxy precedence; read ${POLICY} or generate it`);
		continue;
	}
	if (copies.length !== known.count)
		problems.push(`${file}: ${copies.length} copies, expected ${known.count}`);
	for (const copy of copies) {
		const spelled = (copy.kind === 'set' ? [...copy.names].sort() : copy.names).join(',');
		if (spelled !== canonical[copy.kind]) {
			problems.push(
				`${file}: ${copy.kind} ${spelled} differs from ${POLICY} (${canonical[copy.kind]})`
			);
		}
	}
}
for (const file of KNOWN_COPIES.keys()) {
	if (!found.has(file)) problems.push(`${file}: its copy is gone; remove it from KNOWN_COPIES`);
}
assert.deepEqual(problems, [], problems.join('\n'));

console.log(
	`[OK] proxy policy single source: ${tracked.length} production files scanned, ${KNOWN_COPIES.size} pinned copies follow ${POLICY}.`
);
