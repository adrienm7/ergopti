// tools/codegen/codegen-keystats-roi-case.cjs

/**
 * ==============================================================================
 * MODULE: Measured Windows ROI Lowercase Projection
 * DESCRIPTION:
 * Projects the qualified Windows StrLower observations into the Lua ROI owner.
 * General Unicode casing deliberately keeps its separate, complete semantics.
 * A changed Unicode source or host version requires fresh native qualification,
 * instead of silently extending an older Windows profile to unmeasured letters.
 * ==============================================================================
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '../..');
const SOURCE = 'static/ergopti_plus/_shared/data/keystats_roi_lowercase.json';
const UNICODE_SOURCE = 'static/ergopti_plus/_shared/lua/unicode_case/data.lua';
const LUA_OUTPUT = 'static/ergopti_plus/_shared/lua/keystats/roi_case.lua';
const CORPUS_OUTPUT =
	'static/ergopti_plus/_shared/tests/corpus/keystats/roi_lowercase_vectors.json';

/** Builds only the profile whose full candidate set was observed on Windows. */
function project(profile, unicodeBytes) {
	const qualification = profile.qualification;
	if (
		!qualification ||
		process.version !== qualification.node_version ||
		process.versions.unicode !== qualification.unicode_version
	) {
		throw new Error('ROI casing requires its qualified Node and Unicode versions.');
	}
	if (
		crypto.createHash('sha256').update(unicodeBytes).digest('hex') !==
		qualification.unicode_source_sha256
	) {
		throw new Error('The Unicode source changed; requalify the Windows ROI casing profile.');
	}
	const retained = new Set();
	let previous = -1;
	for (const range of profile.retained_ranges) {
		if (
			!Array.isArray(range) ||
			range.length !== 2 ||
			!range.every(Number.isSafeInteger) ||
			range[0] < 0 ||
			range[0] <= previous ||
			range[0] > range[1] ||
			(range[0] <= 0xdfff && range[1] >= 0xd800) ||
			range[1] > 0x10ffff
		) {
			throw new Error('ROI retained ranges must be sorted, disjoint scalar intervals.');
		}
		for (let codepoint = range[0]; codepoint <= range[1]; codepoint++) retained.add(codepoint);
		previous = range[1];
	}
	if (retained.size !== qualification.retained_scalars)
		throw new Error('The retained scalar receipt changed.');
	const vectors = [];
	const mappings = new Map();
	for (let codepoint = 0; codepoint <= 0x10ffff; codepoint++) {
		if (codepoint >= 0xd800 && codepoint <= 0xdfff) continue;
		const input = String.fromCodePoint(codepoint);
		const unicodeLower = input.toLowerCase();
		if (unicodeLower === input) {
			if (retained.has(codepoint))
				throw new Error('An unmeasured scalar entered the retained ranges.');
			continue;
		}
		const expected =
			retained.has(codepoint) || unicodeLower.length !== input.length ? input : unicodeLower;
		vectors.push([input, expected]);
		if (expected !== input) mappings.set(input, expected);
	}
	if (vectors.length !== qualification.scalar_candidates)
		throw new Error('The measured ROI candidate census changed.');
	for (const [input, expected] of profile.context_vectors) {
		const projected = Array.from(input, (character) => mappings.get(character) ?? character).join(
			''
		);
		if (projected !== expected)
			throw new Error('The measured contextual Windows case no longer agrees.');
	}
	return { mappings, vectors, qualification };
}

/** Produces both runtime data and the corpus replayed by the three drivers. */
function render(profile, unicodeBytes) {
	const { mappings, vectors, qualification } = project(profile, unicodeBytes);
	const label = `AutoHotkey ${qualification.ahk_version}, Windows ${qualification.windows_version}, language ${qualification.language}`;
	const lua =
		'--- _shared/lua/keystats/roi_case.lua\n\n' +
		'--- Generated by tools/codegen/codegen-keystats-roi-case.cjs; do not edit.\n' +
		'--- Source: _shared/data/keystats_roi_lowercase.json and its qualified native receipts.\n' +
		`return {\n\tprofile = ${JSON.stringify(label)},\n\tlower = {\n` +
		[...mappings]
			.map(([input, expected]) => `\t\t[${JSON.stringify(input)}] = ${JSON.stringify(expected)},`)
			.join('\n') +
		'\n\t},\n}\n';
	const corpus = {
		_generated: 'tools/codegen/codegen-keystats-roi-case.cjs; do not edit',
		qualification,
		vectors,
		context_vectors: profile.context_vectors
	};
	// Keep each two-string vector on one line, as the repository JSON formatter does.
	const json =
		JSON.stringify(corpus, null, '\t').replace(
			/\[\n\s*("[^\n]*"),\n\s*("[^\n]*")\n\s*\]/g,
			'[$1, $2]'
		) + '\n';
	return { [LUA_OUTPUT]: lua, [CORPUS_OUTPUT]: json };
}

if (require.main === module) {
	const profile = JSON.parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
	const outputs = render(profile, fs.readFileSync(path.join(ROOT, UNICODE_SOURCE)));
	for (const [file, body] of Object.entries(outputs)) {
		if (process.argv.includes('--check')) {
			if (fs.readFileSync(path.join(ROOT, file), 'utf8') !== body)
				throw new Error(`Stale ROI casing projection: ${file}`);
		} else fs.writeFileSync(path.join(ROOT, file), body);
	}
	console.log('[OK] Trigger ROI casing matches the qualified Windows profile.');
}

module.exports = { project, render };
