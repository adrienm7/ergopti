// tools/codegen/codegen-adapter-errors.cjs

/**
 * ==============================================================================
 * MODULE: Adapter Error Taxonomy Generator
 * DESCRIPTION:
 * Projects the `adapter_errors` section of _shared/modules/logger/vocabulary.json
 * into _shared/lua/adapter_errors.lua: one strict constant per reason or phase id
 * that adapter code produces and other code matches on. A matcher compares a
 * constant, never a sentence, so rewording a message cannot silently break the
 * branch that reads it.
 *
 * FEATURES & RATIONALE:
 * 1. Closed: every id must be a member of the closed `reason` or `phase` enum of
 *    the same file (the enums the logger gate enforces), code-shaped, sorted and
 *    described. The description is developer text; words a user reads come from
 *    the locales, never from here.
 * 2. Strict: the generated table refuses an unknown name, so a misspelt constant
 *    fails at the first access instead of reading as nil.
 * 3. Deterministic: sorted by id, no timestamp.
 * ==============================================================================
 */
'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const { shared } = require('../lib/paths.cjs');

const VOCABULARY = shared('modules', 'logger', 'vocabulary.json');
const TARGET = shared('lua', 'adapter_errors.lua');
const CODE_SHAPED = /^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$/;

/** The constant name of an id: upper case, separators folded to underscores. */
function constantName(id) {
	return id.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
}

/**
 * Validates the section against the closed enums.
 * @param {object} vocabulary Parsed vocabulary.json.
 * @returns {Array<[string, {kind: string, description: string}]>} Sorted entries.
 */
function entries(vocabulary) {
	const section = vocabulary.adapter_errors;
	assert(section && typeof section === 'object', 'vocabulary.json holds no adapter_errors');
	const ids = Object.keys(section);
	assert(ids.length > 0, 'adapter_errors is empty');
	const names = new Set();
	ids.forEach((id, index) => {
		const entry = section[id];
		assert(CODE_SHAPED.test(id), `adapter_errors.${id}: not code-shaped`);
		if (index > 0)
			assert(ids[index - 1] < id, `adapter_errors must be sorted (${ids[index - 1]} before ${id})`);
		assert(
			['reason', 'phase'].includes(entry.kind),
			`adapter_errors.${id}: kind is reason or phase`
		);
		assert(
			typeof entry.description === 'string' && entry.description.trim() !== '',
			`adapter_errors.${id}: a description is required`
		);
		assert(
			Array.isArray(vocabulary[entry.kind]) && vocabulary[entry.kind].includes(id),
			`adapter_errors.${id}: not a member of the closed ${entry.kind} enum`
		);
		const name = constantName(id);
		assert(!names.has(name), `adapter_errors.${id}: folds to the constant ${name} twice`);
		names.add(name);
	});
	return Object.entries(section);
}

/**
 * The Lua module text.
 * @param {Array<[string, {kind: string, description: string}]>} items Validated entries.
 * @returns {string}
 */
function emitLua(items) {
	const body = items
		.map(
			([id, { kind, description }]) =>
				`\t-- ${kind}: ${description}\n\t${constantName(id)} = "${id}",`
		)
		.join('\n');
	return (
		'--- _shared/lua/adapter_errors.lua\n\n' +
		'--- Generated by tools/codegen/codegen-adapter-errors.cjs; do not edit.\n' +
		'--- Source: _shared/modules/logger/vocabulary.json (adapter_errors).\n' +
		'--- The closed reason and phase ids adapter code produces and other code matches on.\n' +
		'--- A name the table does not hold raises instead of reading as nil.\n' +
		'local ids = {\n' +
		body +
		'\n}\n\n' +
		'return setmetatable({}, {\n' +
		'\t__index = function(_, name)\n' +
		'\t\tlocal id = ids[name]\n' +
		'\t\tif id == nil then error("adapter_errors has no constant " .. tostring(name), 2) end\n' +
		'\t\treturn id\n' +
		'\tend,\n' +
		'\t__newindex = function() error("adapter_errors is read-only", 2) end,\n' +
		'\t__metatable = false,\n' +
		'})\n'
	);
}

if (require.main === module) {
	const items = entries(JSON.parse(fs.readFileSync(VOCABULARY, 'utf8')));
	fs.writeFileSync(TARGET, emitLua(items), 'utf8');
	console.log(`[OK] Generated ${items.length} adapter error id(s).`);
}

module.exports = { VOCABULARY, TARGET, constantName, entries, emitLua };
