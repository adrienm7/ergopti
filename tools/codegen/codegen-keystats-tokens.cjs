// tools/codegen/codegen-keystats-tokens.cjs

/**
 * ==============================================================================
 * MODULE: Keystats Token Data Generator
 * DESCRIPTION:
 * Projects _shared/metrics/data/keystats_tokens.json, the one marker list of the n-gram
 * encoding, into the Lua walker, the AHK walker and the metrics dashboard, so
 * the three cannot spell a marker differently again ([PGUP] against [PAGEUP]).
 * ==============================================================================
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SOURCE = path.join(ROOT, 'static/ergopti_plus/_shared/metrics/data/keystats_tokens.json');
const LUA = 'static/ergopti_plus/_shared/metrics/engine/privacy/tokens_data.lua';
const AHK = 'static/ergopti_plus/windows/_generated/keystats_tokens.ahk';
const JS = 'static/ergopti_plus/_shared/ui/metrics_typing/_generated/keystats_tokens.js';
const NOTICE = 'Generated by tools/codegen/codegen-keystats-tokens.cjs; do not edit.';

const data = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

/** One marker a string can carry unescaped in Lua, AHK and JavaScript alike. */
function quoted(marker) {
	if (!/^\[[A-Z0-9]+\]$/.test(marker)) throw new Error(`Invalid marker spelling: ${marker}`);
	return `"${marker}"`;
}

function lua() {
	const markers = data.markers.map((marker) => `\t\t${quoted(marker)},`).join('\n');
	const aliases = Object.entries(data.aliases)
		.map(([alias, canonical]) => `\t\t[${quoted(alias)}] = ${quoted(canonical)},`)
		.join('\n');
	return (
		`--- _shared/metrics/engine/privacy/tokens_data.lua\n\n--- ${NOTICE}\n` +
		`--- Source: _shared/metrics/data/keystats_tokens.json.\n` +
		`return {\n\tversion = ${data.version},\n\tliteral_bracket = "${data.literal_bracket}",\n` +
		`\tmarkers = {\n${markers}\n\t},\n\taliases = {\n${aliases}\n\t},\n}\n`
	);
}

function ahk() {
	const markers = data.markers.map((marker) => `\t\t${quoted(marker)}, true`).join(',\n');
	const aliases = Object.entries(data.aliases)
		.map(([alias, canonical]) => `\t\t${quoted(alias)}, ${quoted(canonical)}`)
		.join(',\n');
	return (
		`﻿; windows/_generated/keystats_tokens.ahk\n\n; ${NOTICE}\n` +
		`; Source: _shared/metrics/data/keystats_tokens.json.\n\n` +
		`global KEYSTATS_TOKEN_VERSION := ${data.version}\n` +
		`global KEYSTATS_LITERAL_BRACKET := "${data.literal_bracket}"\n\n` +
		`; A function, so the tables exist however early a walker include runs.\n` +
		`KeystatsTokenMarkers() {\n\tstatic Markers := Map(\n${markers}\n\t)\n\treturn Markers\n}\n\n` +
		`KeystatsTokenAliases() {\n\tstatic Aliases := Map(\n${aliases}\n\t)\n\treturn Aliases\n}\n`
	);
}

function javascript() {
	const markers = data.markers.map((marker) => `\t${quoted(marker)}`).join(',\n');
	return (
		`// _shared/ui/metrics_typing/_generated/keystats_tokens.js\n\n// ${NOTICE}\n` +
		`// Source: _shared/metrics/data/keystats_tokens.json.\n\n` +
		`const KEYSTATS_LITERAL_BRACKET = "${data.literal_bracket}";\n` +
		`const KEYSTATS_MARKERS = new Set([\n${markers}\n]);\n`
	);
}

const outputs = { [LUA]: lua(), [AHK]: ahk(), [JS]: javascript() };

if (process.argv.includes('--check')) {
	const stale = Object.keys(outputs).filter(
		(file) => fs.readFileSync(path.join(ROOT, file), 'utf8') !== outputs[file]
	);
	if (stale.length > 0) {
		console.error(`Stale keystats token data: ${stale.join(', ')}.`);
		process.exit(1);
	}
	console.log('[OK] Keystats token data is current.');
} else {
	for (const [file, content] of Object.entries(outputs))
		fs.writeFileSync(path.join(ROOT, file), content, 'utf8');
	console.log('[OK] Generated keystats token data.');
}
