--- _shared/lua/manifest_reader.lua

--- ==============================================================================
--- MODULE: Features Manifest Reader (Shared)
--- DESCRIPTION:
--- The runtime API over the generated `_generated/features_manifest.lua`
--- (`npm run build:manifest`, from the single source of truth at
--- `_shared/modules/features/manifest.toml`) that the macOS and Linux drivers
--- bind in infra/manifest_reader.lua. The AutoHotkey twin is
--- `windows/infra/manifest_reader.ahk`.
---
--- FEATURES & RATIONALE:
--- 1. Fail fast: a missing or malformed manifest, or a lookup for an unknown
---    path, raises rather than returning nil. The manifest is committed and
---    regenerated by the build, so a miss is a real misconfiguration, and a
---    privacy toggle that silently read nil would disable the filter it names.
--- 2. O(1) lookups through a path index built once at load.
--- 3. A driver whose defaults depend on its machine (the macOS model backend)
---    passes two hooks that resolve a platform default before a value that
---    includes it is read; metadata accessors resolve nothing. Without hooks
---    every accessor answers from the manifest as generated.
--- 4. The path of the generated file is supplied by the driver binding, which
---    knows where it lives relative to itself.
--- ==============================================================================

local ConfigDefaults = require("config_defaults")

local M = {}




-- =============================================
-- =============================================
-- ======= 1/ Public API =======================
-- =============================================
-- =============================================

--- Loads the generated manifest and returns the reader bound to it.
--- @param ports table {
---   logger = table with done, log = string namespace,
---   manifest_path = string absolute path of _generated/features_manifest.lua,
---   resolve_path = function(reader, path|nil)|nil: resolves a platform default
---     before the value at `path` (nil: every value) is read,
---   resolve_scope = function(reader, scope, direct_only)|nil: the same for a scope }
--- @return table reader
function M.new(ports)
	assert(type(ports) == "table" and type(ports.logger) == "table" and type(ports.log) == "string"
		and type(ports.manifest_path) == "string", "a manifest reader needs a logger, a log namespace and a manifest path")
	assert(ports.resolve_path == nil or type(ports.resolve_path) == "function", "resolve_path must be a function")
	assert(ports.resolve_scope == nil or type(ports.resolve_scope) == "function", "resolve_scope must be a function")

	local chunk, load_err = loadfile(ports.manifest_path)
	if not chunk then
		error("[manifest_reader] cannot load generated manifest (" .. tostring(load_err)
			.. ") — run `npm run build:manifest`.")
	end
	local ok, manifest = pcall(chunk)
	if not ok or type(manifest) ~= "table" or type(manifest.features) ~= "table" then
		error("[manifest_reader] generated manifest did not return a valid table: " .. tostring(manifest))
	end
	local defaults = ConfigDefaults.new(manifest)

	-- Path index built once at load for O(1) lookups.
	local path_index = {}
	for _, entry in ipairs(manifest.features) do path_index[entry.path] = entry end

	ports.logger.done(ports.log, "Features manifest loaded (v%s, %d feature(s)).",
		tostring(manifest.version), #manifest.features)

	local reader = {
		-- Whether reads resolve a machine-dependent default first (contracts gate on it).
		resolves_platform_defaults = ports.resolve_path ~= nil or ports.resolve_scope ~= nil,
	}

	local function resolve_path(path)
		if ports.resolve_path then ports.resolve_path(reader, path) end
	end
	local function resolve_scope(scope, direct_only)
		if ports.resolve_scope then ports.resolve_scope(reader, scope, direct_only) end
	end

	--- Manifest format version string (e.g. "2.0.0").
	--- @return string
	function reader.version() return manifest.version end

	--- Flat array of feature entries (path / id / section / default / type / ...).
	--- @return table
	function reader.features()
		resolve_path(nil)
		return manifest.features
	end

	--- Returns the manifest entry for a canonical feature path, or nil when absent.
	--- @param path string The canonical dotted path (e.g. the menu/config key).
	--- @return table|nil
	function reader.find_entry_by_path(path)
		resolve_path(path)
		return path_index[path]
	end

	--- Returns declaration metadata without resolving a platform default.
	--- Type admission does not need the backend or any hardware-derived value.
	--- @param path string Canonical feature path.
	--- @return table|nil entry Published declaration, or nil when unknown.
	function reader.find_declared_entry_by_path(path) return path_index[path] end

	--- Returns the declared entries of one section, in manifest order, without
	--- resolving a platform default.
	--- @param section string Exact dotted section (e.g. "shortcuts.caps_word.pointer").
	--- @return table entries Dense array of published declarations.
	function reader.declared_section_entries(section)
		local entries = {}
		for _, entry in ipairs(manifest.features) do
			if entry.section == section then entries[#entries + 1] = entry end
		end
		return entries
	end

	--- Returns the raw declaration of a configuration scope (hooks read it).
	--- @param scope string
	--- @return table
	function reader.scope_declaration(scope)
		return assert(manifest.scopes[scope], "unknown configuration scope")
	end

	--- Returns the default value declared for a feature path. FAIL-FAST when the
	--- path is unknown, so a renamed or removed feature surfaces loudly instead
	--- of silently defaulting to nil.
	--- @param path string
	--- @return any The declared default (primitive or table).
	function reader.default_for(path)
		resolve_path(path)
		return defaults.default_for(path)
	end

	--- Returns a detached recommended value; never used as an absence fallback.
	--- @param path string Canonical feature path.
	--- @return any value
	function reader.recommended_for(path)
		resolve_path(path)
		return defaults.recommended_for(path)
	end

	--- @return boolean declared Whether a path has a manifest-owned neutral value.
	function reader.has_default(path) return defaults.has_default(path) end

	--- Returns a detached nested document containing every neutral manifest value.
	--- @return table defaults
	function reader.document_defaults()
		resolve_path(nil)
		return defaults.document_defaults()
	end

	--- Returns the manifest-owned configuration scopes.
	--- @return table scopes
	function reader.scopes() return defaults.scopes() end

	--- Produces an explicit set or delete operation relative to neutral absence.
	--- @param path string Canonical feature path.
	--- @param value any Desired value.
	--- @return table operation
	function reader.sparse_operation(path, value)
		resolve_path(path)
		return defaults.operation(path, value)
	end

	--- Produces selected recommended writes or neutral deletions.
	--- @param scope string Scope identifier.
	--- @param mode string `recommended` or `clear`.
	--- @param owned_paths table|nil Explicit runtime-owned paths.
	--- @param owners table|nil Exact host parameter validators.
	--- @return table operations
	function reader.scope_operations(scope, mode, owned_paths, owners)
		resolve_scope(scope)
		return defaults.scope_operations(scope, mode, owned_paths, owners)
	end

	--- Collects dynamic paths from explicit runtime owners for one scope.
	--- @param scope string Scope identifier.
	--- @param providers table Named callbacks returning owned path arrays.
	--- @param owners table|nil Exact host parameter validators.
	--- @return table paths
	function reader.scope_inventory(scope, providers, owners) return defaults.scope_inventory(scope, providers, owners) end

	--- Separates config operations from required external preset owners.
	--- @param scope string Scope identifier.
	--- @param mode string Recommended restoration or clear.
	--- @param owned_paths table|nil Explicit runtime-owned paths.
	--- @param owners table|nil Exact host parameter validators.
	--- @return table plan
	function reader.scope_plan(scope, mode, owned_paths, owners)
		resolve_scope(scope)
		return defaults.scope_plan(scope, mode, owned_paths, owners)
	end

	--- The direct (non-included) operations of a scope.
	function reader.direct_scope_operations(scope, mode, owned_paths, owners)
		resolve_scope(scope, true)
		return defaults.direct_scope_operations(scope, mode, owned_paths, owners)
	end

	--- The direct (non-included) plan of a scope.
	function reader.direct_scope_plan(scope, mode, owned_paths, owners)
		resolve_scope(scope, true)
		return defaults.direct_scope_plan(scope, mode, owned_paths, owners)
	end

	--- Every feature this driver does NOT have, with whatever explains each one.
	--- The generator filters `features` per platform, so the absences ship as
	--- their own table: without it the driver cannot know a feature exists.
	--- @return table Array of { path, section, description_key, reason_key, platforms }.
	function reader.unavailable() return manifest.unavailable or {} end

	--- Splits the absences into the ones that say why and the ones that do not.
	--- @return table explained Absences carrying a reason_key.
	--- @return table silent Absences carrying none.
	function reader.coverage_gaps()
		local explained, silent = {}, {}
		for _, entry in ipairs(reader.unavailable()) do
			if type(entry.reason_key) == "string" and entry.reason_key ~= "" then
				explained[#explained + 1] = entry
			else
				silent[#silent + 1] = entry
			end
		end
		return explained, silent
	end

	return reader
end

return M
