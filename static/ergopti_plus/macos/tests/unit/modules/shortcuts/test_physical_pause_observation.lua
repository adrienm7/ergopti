helpers.describe("actual pause subscriber refusal interface", function()
	local function observe_refusal(mode, callback)
		return with_context({ unbound = true }, function(script, ctx)
			local owner, records, count, token, scope = {}, {}, 0, nil, nil
			local facts = {}
			local reason
			token, reason, scope = script.bind_physical_pause_observer(owner, mode == "budget" and 1 or 100,
				function(record)
					records[#records + 1] = record
					if record.source == "binding" then return true end
					if mode == "throw" then error("Actual receiver refused") end
					return false
				end, function(refusal_reason, exact_token)
					count = count + 1
					facts.reason, facts.token = refusal_reason, exact_token
					facts.current = scope.current(owner, exact_token)
					facts.detached = scope.detach(owner, exact_token)
					facts.inside_retired = scope.retired(owner, exact_token)
				end)
			helpers.assert_true(token ~= nil); helpers.assert_eq(reason, nil)
			callback(script, ctx, owner, token, scope, facts, records, function() return count end)
		end)
	end
	local function check_actual_pause(mode)
		observe_refusal(mode, function(script, ctx, owner, token, scope, facts, records, count)
			helpers.assert_eq(script.pause_all(), true)
			-- Inspect observations outside both protected receiver/refusal callbacks.
			helpers.assert_eq(count(), 1)
			helpers.assert_true(rawequal(facts.token, token))
			helpers.assert_eq(facts.reason, mode == "budget" and "Lifecycle receipt budget exhausted" or "Lifecycle subscriber refused receipt")
			helpers.assert_eq(facts.current, false)
			helpers.assert_eq(facts.detached, true)
			helpers.assert_eq(facts.inside_retired, false)
			helpers.assert_eq(scope.retired(owner, token), false)
			ctx.fire_deferred(); ctx.pause_callback(true, "paused")
			helpers.assert_eq(scope.retired(owner, token), true)
			helpers.assert_eq(ctx.calls.input_drain, 1); helpers.assert_eq(ctx.calls.admission_acquire, 1)
			helpers.assert_eq(ctx.calls.karabiner_pause, 1)
			helpers.assert_true(helpers.deep_equal(ctx.pause_listener, { true }))
			commit_resume(script, ctx)
			helpers.assert_eq(count(), 1)
			helpers.assert_true(helpers.deep_equal(ctx.pause_listener, { true, false }))
			script.stop()
		end)
	end
	helpers.it("forwards exact budget refusal after revocation and retains the actual pending writer", function()
		check_actual_pause("budget")
	end)
	helpers.it("forwards exact receiver refusal without changing native pause/resume effects", function()
		check_actual_pause("reject")
	end)
	helpers.it("forwards contained receiver throws once and retains outer completion debt", function()
		check_actual_pause("throw")
	end)
	helpers.it("bootstrap refusal keeps original token reason and scope after a successor binds", function()
		with_context({ unbound = true }, function(script, ctx)
			local owner, next_owner, observed_token, count = {}, {}, nil, 0
			local facts = {}
			local token, reason, scope = script.bind_physical_pause_observer(owner, 20, function(_, exact)
				observed_token = exact; return false
			end, function(refusal_reason, exact)
				count = count + 1; facts.reason, facts.token = refusal_reason, exact
				facts.detached = script.unbind_physical_pause_observer(owner, exact)
