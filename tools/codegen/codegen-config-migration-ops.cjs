// tools/codegen/codegen-config-migration-ops.cjs

/**
 * ==============================================================================
 * MODULE: Config Migration Op Table Codegen
 * DESCRIPTION:
 * Emits the required and optional fields of each config-migration op for the
 * Windows interpreter from the closed op set documented at the top of
 * _shared/core/config_schema/migrations.toml.
 *
 * WHY THE SOURCE IS THE REGISTRY'S HEADER COMMENT:
 * The closed set is spelled there as `{ op = "name", field, optional? }` lines,
 * and config_migrate.ahk carried a second, hand-written copy of it. A real TOML
 * table would be read and validated by all three interpreters at every boot, and
 * each refuses an unknown registry table on purpose (the shared defect corpus
 * pins it). The comment costs no driver anything, so behaviour stays identical.
 * A line outside the grammar fails the generator instead of being skipped.
 *
 * USAGE:  node tools/codegen/codegen-config-migration-ops.cjs
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const SP = path.join(ROOT, 'static', 'ergopti_plus');
const SOURCE = path.join(SP, '_shared/core/config_schema/migrations.toml');
const TARGET = path.join(SP, 'windows/_generated/config_migration_ops.ahk');

const OP_OPENING = '#   { op = "';
const FIELD_PATTERN = /^([a-z][a-z0-9_]*)(\?|\s*=\s*.+)?$/;

/**
 * Splits text on the commas outside any bracket pair.
 * @param {string} text - An op declaration without its outer braces.
 * @returns {string[]}
 */
function splitTopLevel(text) {
	const parts = [];
	let depth = 0;
	let current = '';
	for (const character of text) {
		if (character === '[' || character === '{') depth++;
		if (character === ']' || character === '}') depth--;
		if (character === ',' && depth === 0) {
			parts.push(current.trim());
			current = '';
		} else current += character;
	}
	parts.push(current.trim());
	return parts;
}

/**
 * Reads the closed op set out of the registry's header comment. Field order is
 * the declared order, which decides the field a refusal names first.
 * @param {string} source - Exact text of migrations.toml.
 * @returns {Object<string, {required: string[], optional: string[]}>}
 */
function parseOpFields(source) {
	const lines = source.split(/\r?\n/);
	const ops = {};
	for (let index = 0; index < lines.length; index++) {
		if (!lines[index].startsWith(OP_OPENING)) continue;
		let declaration = lines[index].slice(1).trim();
		while (!declaration.endsWith('}')) {
			index++;
			if (index >= lines.length || !lines[index].startsWith('#     '))
				throw new Error(`unterminated op declaration: ${declaration}`);
			declaration += ' ' + lines[index].slice(1).trim();
		}
		const [opening, ...fields] = splitTopLevel(declaration.slice(1, -1));
		const name = /^op = "([a-z][a-z0-9_]*)"$/.exec(opening);
		if (!name) throw new Error(`malformed op name: ${declaration}`);
		if (Object.hasOwn(ops, name[1])) throw new Error(`op declared twice: ${name[1]}`);
		const entry = { required: [], optional: [] };
		for (const field of fields) {
			const match = FIELD_PATTERN.exec(field);
			if (!match) throw new Error(`malformed field '${field}' of op ${name[1]}`);
			(match[2] === '?' ? entry.optional : entry.required).push(match[1]);
		}
		if (entry.required.length === 0) throw new Error(`op ${name[1]} declares no required field`);
		ops[name[1]] = entry;
	}
	if (Object.keys(ops).length === 0) throw new Error('migrations.toml declares no op');
	return ops;
}

/**
 * An AHK v2 array literal of plain identifiers.
 * @param {string[]} names
 * @returns {string}
 */
function ahkNames(names) {
	return '[' + names.map((name) => `"${name}"`).join(', ') + ']';
}

/**
 * The generated AHK file.
 * @param {Object<string, {required: string[], optional: string[]}>} ops
 * @returns {string}
 */
function emitAhk(ops) {
	const rows = Object.entries(ops).map(
		([name, entry]) => `\t\t"${name}", [${ahkNames(entry.required)}, ${ahkNames(entry.optional)}]`
	);
	return (
		'﻿; _generated/config_migration_ops.ahk\n' +
		'\n' +
		'; Generated by tools/codegen/codegen-config-migration-ops.cjs; do not edit.\n' +
		'; Source: the closed op set in _shared/core/config_schema/migrations.toml.\n' +
		'\n' +
		'; Required and optional fields of each op of the closed set.\n' +
		'ConfigMigrateOpFieldsData() {\n' +
		'\tstatic Fields := Map(\n' +
		rows.join(',\n') +
		'\n\t)\n' +
		'\treturn Fields\n' +
		'}\n'
	);
}

if (require.main === module) {
	const ops = parseOpFields(fs.readFileSync(SOURCE, 'utf8'));
	fs.writeFileSync(TARGET, emitAhk(ops), 'utf8');
	console.log(`[OK] config migration op table generated: ${Object.keys(ops).length} op(s).`);
}

module.exports = { parseOpFields };
