/**
 * ==============================================================================
 * MODULE: Trigger ROI Policy Projection
 * DESCRIPTION:
 * Projects the Windows ROI owner's policy into Lua. Windows remains the source
 * of the existing thresholds; a changed or malformed declaration fails the
 * build instead of silently giving another driver different metrics.
 * ==============================================================================
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '../..');
const SOURCE = 'static/ergopti_plus/windows/modules/keystats/keystats_trigger_roi.ahk';
const OUTPUT = 'static/ergopti_plus/_shared/metrics/engine/privacy/roi_policy_core.lua';
const KEYS = [
	'MIN_WORD_LEN',
	'REPEAT_THRESHOLD',
	'MAX_TRACKED_WORDS',
	'PRUNE_TARGET_WORDS',
	'MAX_INPROGRESS_WORD_LEN',
	'ROI_SNAPSHOT_EVERY',
	'HALFLIFE_CHECK_MS',
	'HALFLIFE_WARN_DAYS'
];

/** Validates the complete Windows policy before projecting its integer values. */
function render(source) {
	const body = source.match(/^class KLRoiConst \{\r?\n([\s\S]*?)^\}/m)?.[1];
	if (!body) throw new Error('The Windows KLRoiConst owner is missing.');
	const values = new Map();
	for (const line of body.split('\n')) {
		const code = line.split(';')[0].trim();
		if (!code) continue;
		const field = code.match(/^static ([A-Z_]+)\s*:=\s*([1-9][0-9]*)$/);
		if (!field || !KEYS.includes(field[1]) || values.has(field[1])) {
			throw new Error(`Unsupported ROI policy declaration: ${code}`);
		}
		values.set(field[1], Number(field[2]));
	}
	if (
		values.size !== KEYS.length ||
		[...values.values()].some((value) => !Number.isSafeInteger(value))
	) {
		throw new Error('The Windows ROI policy is incomplete or outside the integer range.');
	}
	if (
		values.get('PRUNE_TARGET_WORDS') >= values.get('MAX_TRACKED_WORDS') ||
		values.get('MIN_WORD_LEN') > values.get('MAX_INPROGRESS_WORD_LEN')
	) {
		throw new Error('The Windows ROI bounds are inconsistent.');
	}
	return (
		'--- _shared/metrics/engine/privacy/roi_policy_core.lua\n\n' +
		'--- Generated by tools/codegen/codegen-keystats-roi-policy.cjs; do not edit.\n' +
		'--- Source: windows/modules/keystats/keystats_trigger_roi.ahk, KLRoiConst.\n' +
		'return {\n' +
		KEYS.map((key) => `\t${key.toLowerCase()} = ${values.get(key)},`).join('\n') +
		'\n}\n'
	);
}

if (require.main === module) {
	const result = render(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
	if (process.argv.includes('--check')) {
		if (fs.readFileSync(path.join(ROOT, OUTPUT), 'utf8') !== result) {
			throw new Error('The generated Lua ROI policy is stale.');
		}
	} else fs.writeFileSync(path.join(ROOT, OUTPUT), result);
	console.log('[OK] Trigger ROI policy matches Windows.');
}

module.exports = { render };
