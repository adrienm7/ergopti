		actor.finish(ticket,function() queries=queries+1;return {} end,true)
		helpers.assert_eq(queries,0);helpers.assert_eq(last(records).source,"binding")
		local new_ticket=actor.begin("resume")
		actor.finish(new_ticket,snapshot(false,true),true)
		helpers.assert_eq(last(records).complete,true)
	end)
	it("async writer reentry retires current completion",function()
		local actor,records,_,_,failures=actor_fixture()
		local ticket=actor.begin("pause")
		actor.begin("resume")
		actor.finish(ticket,snapshot(true,false),true)
		denied(records);helpers.assert_eq(#failures,1)
	end)
	it("missing pause facts cannot complete and never permit history",function()
		local actor,records=actor_fixture()
		local ticket=actor.begin("pause")
		actor.finish(ticket,function() return {transition_generation=2,admission_released=false,settled=true} end,true)
		denied(records);helpers.assert_eq(last(records).fields_complete,false)
	end)
end)

