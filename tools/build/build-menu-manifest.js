#!/usr/bin/env node
// tools/build/build-menu-manifest.js
//
// Emits the shared tray-menu manifest JSON from the [menu.*] tables in the
// features manifest, so the menu tree has a single source of truth alongside
// the feature definitions instead of a separately hand-maintained JSON.
//
// Input:
//   static/ergopti_plus/_shared/modules/features/manifest.toml  ([menu.*] tables)
//   static/ergopti_plus/_shared/modules/updater/channels.json  (registry choices)
//   static/ergopti_plus/_shared/ui/update_channels.js  (canonical channel validator)
//   static/ergopti_plus/_shared/modules/updater/defaults.json  (cadence registry)
//   static/ergopti_plus/_shared/modules/updater/schedule.js  (canonical timing validator)
//
// Output:
//   static/ergopti_plus/_shared/modules/menu/menu_manifest.json
//
// Both drivers read the generated JSON at runtime unchanged. The emitted data
// is a verbatim projection of the [menu.*] tables (only the leading _comment
// header fields are added, and each `choice` row gains the `choices` of its
// enum feature or registered settings owner), so behavior is identical to the previous
// hand-maintained file — guaranteed by the menu drift gate
// (tools/test/test-menu-manifest.cjs) and the build:domain regeneration check.
//
// Usage:
//   npm run build:menu
//   node ./tools/build/build-menu-manifest.js

import { parse as parseToml } from 'smol-toml';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { runInNewContext } from 'vm';
import sharedPaths from '../lib/paths.cjs';
import menuAvailability from '../lib/menu-row-availability.cjs';
import { createRequire } from 'node:module';
import { validateTiming } from '../../static/ergopti_plus/_shared/modules/updater/schedule.js';

const require = createRequire(import.meta.url);
const { shared } = sharedPaths;
const __dirname = dirname(fileURLToPath(import.meta.url));

const MANIFEST_PATH = shared('modules/features/manifest.toml');
const OUT_PATH = shared('modules/menu/menu_manifest.json');

// Fixed header comments carried into the emitted JSON. The first line marks the
// file as generated; the other two document the runtime contract for readers.
const HEADER = {
	_comment:
		'GENERATED by tools/build/build-menu-manifest.js from ' +
		'_shared/modules/features/manifest.toml [menu.*]. Do not edit by hand — ' +
		'edit the manifest and run "npm run build:menu" (or build:domain).',
	_comment2:
		"platforms field: omit or 'both' = all platforms, 'ahk' = Windows only, 'hs' = macOS only.",
	_comment3:
		"item types: 'toggle' = a category's first-row checkbox (its master gate, one i18n key), " +
		"'feature' = manifest-path toggle, " +
		"'action' = stateless button, 'dynamic' = rendered by platform code, " +
		"'group' = named submenu, 'include' = reused child-template section, " +
		"'native_content' = completed native objects ordered by an admitted composition, " +
		"'label' = inert provider-template caption, 'section_header' = disabled header, '---' = separator, " +
		"'list' = rows supplied at build time by a named provider, 'letter_picker' = " +
		'the A-Z chooser. The last two were in use and undocumented here, which matters ' +
		"because 'list' is the ONLY type that moves provider DATA from the driver into the " +
		"renderer — 'dynamic' hands the rendering straight back to platform code. " +
		"'choice' = one enum feature (path) as one row with its values beneath it; its " +
		"'choices' are projected from the feature's enum_values or registered owner by this generator.",
	_comment4:
		"unavailable (rows restricted by platforms only): 'hide' = not applicable where the row " +
		"is not declared, never drawn there and carrying no reason_key; 'grey' = not yet ported " +
		'there, drawn disabled with its label and its translated reason_key. A restricted row ' +
		'without the field is hidden, as before the field existed. A top-level disabled = true ' +
		'presentation uses its i18n label and reason_key without constructing the component. disabled_reason_key (command/check ' +
		'rows or identified labelled groups with disabled_when): why disabled_when greys the row where it is drawn, rendered ' +
		"like a 'grey' row: « label — head of the reason », with nothing to run."
};

const PLATFORMS = ['ahk', 'hs', 'linux'];

/**
 * Refuses a greyed-row declaration the renderers cannot honour.
 *
 * One rule for a row greyed with a reason: it is drawn disabled as « label —
 * head of the reason » (the translated reason's text before its first colon),
 * with nothing to run, so it needs an i18n label and a reason key. The two
 * cases differ only in how the condition is evaluated:
 *   - a platform lacks the row: NOT APPLICABLE there (`unavailable = "hide"`:
 *     nothing is drawn and no reason is owed) or NOT YET PORTED there
 *     (`unavailable = "grey"`: greyed with its `reason_key`);
 *   - its `disabled_when` greys it where it is drawn: greyed with its
 *     `disabled_reason_key`, read on `command`/`check` rows and identified labelled groups. `reason_key` cannot carry
 *     that reason too, since a restricted row keeps it for the platforms it
 *     leaves out (the health check reads it there).
 * @param {object} menu The parsed [menu] tables.
 */
function validateGreyedRows(menu) {
	menuAvailability.validateMenuAvailability(menu);
}

/** Refuses effects or ambiguous fields in an existing provider's inert status. */
function validateProviderStatus(menu) {
	for (const [key, rows] of Object.entries(menu)) {
		if (!Array.isArray(rows)) continue;
		for (const row of rows) {
			if (row.status_rows === undefined) continue;
			const where = `menu.${key} row "${row.id || row.type}"`;
			if (
				!['dynamic', 'list'].includes(row.type) ||
				typeof row.id !== 'string' ||
				row.id === '' ||
				!row.status_rows ||
				typeof row.status_rows !== 'object' ||
				Array.isArray(row.status_rows) ||
				Object.keys(row.status_rows).length === 0
			)
				throw new Error(
					`${where}: status_rows needs an existing provider identity and named status`
				);
			for (const [status, declaration] of Object.entries(row.status_rows)) {
				if (status === '' || !Array.isArray(declaration) || declaration.length === 0)
					throw new Error(`${where}: provider status needs nonempty inert rows`);
				for (const item of declaration) {
					const label = item?.type === 'label' && typeof item.i18n === 'string' && item.i18n !== '';
					if (
						!item ||
						typeof item !== 'object' ||
						Array.isArray(item) ||
						(item.type !== '---' && !label) ||
						Object.keys(item).some((field) => field !== 'type' && !(label && field === 'i18n'))
					)
						throw new Error(
							`${where}: provider status admits only inert separators and translated labels`
						);
				}
			}
		}
	}
}

/** Validates the child-template composition and caption-reader vocabulary. */
function validateChildTemplates(menu) {
	let english;
	menuAvailability.validateChildTemplates(menu, (key) => {
		if (english === undefined) {
			english = JSON.parse(readFileSync(shared('data/locales/en.json'), 'utf8'));
			if (!english || typeof english !== 'object' || Array.isArray(english))
				throw new Error('canonical English captions must be a table');
		}
		return Object.hasOwn(english, key) ? english[key] : undefined;
	});
}

/** Projects the updater's actual validated registry without inventing a feature enum. */
function updaterChannelChoices() {
	const source = shared('modules/updater/channels.json');
	const matcher = shared('ui/update_channels.js');
	const window = {};
	runInNewContext(readFileSync(matcher, 'utf8'), { window }, { filename: matcher });
	const registry = window.createUpdateChannels(JSON.parse(readFileSync(source, 'utf8')));
	return Array.from(registry.ids, (value) => ({
		value,
		i18n: registry.channel(value).menuLabelKey,
		current_i18n: registry.channel(value).labelKey
	}));
}

/** Projects the cadence owner's validated numeric values and translated labels. */
function updaterIntervalChoices() {
	const timing = JSON.parse(readFileSync(shared('modules/updater/defaults.json'), 'utf8')).timing;
	validateTiming(timing);
	return timing.check_interval_presets.map((preset) => ({
		value: preset.seconds,
		i18n: `menu.about.frequency.${preset.code}`
	}));
}

/** Projects signed display offsets from their numeric feature catalogue. */
function indentationChoices(feature) {
	const values = feature?.choice_values;
	if (
		feature?.type !== 'number' ||
		!Array.isArray(values) ||
		values.length < 2 ||
		values.some(
			(value, index) =>
				!Number.isSafeInteger(value) || (index > 0 && value !== values[index - 1] + 1)
		) ||
		!values.includes(feature.default) ||
		!values.includes(feature.recommended)
	)
		throw new Error(
			'llm.indentation: numeric choices need ordered integral values containing the defaults'
		);
	return values.map((value) => ({
		value,
		i18n:
			value === 0
				? 'menu.llm.indent_none'
				: Math.abs(value) === 1
					? 'menu.llm.indent_space'
					: 'menu.llm.indent_spaces',
		label_prefix: value === 0 ? '' : `${value > 0 ? '+' : ''}${value} `
	}));
}

const CHOICE_REGISTRIES = {
	'karabiner.runtime': {
		path: 'karabiner.runtime',
		source: () => require('../lib/karabiner-runtime-setting.cjs').runtimeSetting(),
		project: (setting) => {
			return setting.enum_values.map((value) => ({
				value,
				i18n: `${setting.description_key}.${value}`
			}));
		}
	},
	'llm.indentation': { path: 'llm.display.pred_indent', project: indentationChoices },
	'updater.channels': { path: 'updater.channel', project: updaterChannelChoices },
	'updater.check_intervals': {
		path: 'updater.check_interval_seconds',
		project: updaterIntervalChoices
	}
};

/**
 * Projects each `choice` row's values from its enum feature or registered settings owner.
 *
 * A choice row is one setting with a fixed set of values, drawn as one row with
 * the values beneath it. The values belong to the feature (its `enum_values`),
 * so a declared ordered subset must be validated against that enum. Each
 * translated leaf becomes `{ value, i18n }`, labelled
 * by the key `<row i18n>.<value>`, or by an explicit `choice_label_prefix` for
 * established label keys. The logger alone may expose its existing technical
 * tokens with source-owned emoji; these are not untranslated natural language.
 * `show_current_choice` lets the shared renderer fill
 * a declared placeholder (default {1}) from the selected label.
 * Registered updater choices carry distinct short and full locale keys.
 * A row whose path is not an enum feature, that lists its choices by hand, or
 * that is shown on a platform the feature does not
 * declare fails the build instead of drawing a row no driver can store.
 * @param {object} menu The parsed [menu] tables, completed in place.
 * @param {string} raw The manifest source, for the feature entries.
 */
function projectChoices(menu, raw) {
	const flattened = parseToml(
		raw.replace(
			/^\[\[features\.([^\]]+)\]\]\r?$/gm,
			(_m, prefix) => `[[entries]]\npath_prefix = "${prefix}"`
		)
	);
	const enums = new Map();
	const numeric = new Map();
	for (const entry of flattened.entries || []) {
		if (entry.type === 'enum') enums.set(`${entry.path_prefix}.${entry.id}`, entry);
		if (entry.type === 'number') numeric.set(`${entry.path_prefix}.${entry.id}`, entry);
	}
	for (const [key, rows] of Object.entries(menu)) {
		if (!Array.isArray(rows)) continue;
		for (const row of rows) {
			if (!row || typeof row !== 'object' || row.type !== 'choice') continue;
			const where = `menu.${key} choice "${row.id}"`;
			let projectedRegistry;
			let feature = enums.get(row.path);
			if (row.choice_registry !== undefined) {
				const registry = CHOICE_REGISTRIES[row.choice_registry];
				if (!registry || row.path !== registry.path)
					throw new Error(`${where}: unknown choice_registry or registry-owned path`);
				if (row.choice_values !== undefined || row.choice_label_prefix !== undefined)
					throw new Error(`${where}: registry choices own their values, order and label keys`);
				const declaration = registry.source ? registry.source() : numeric.get(row.path);
				projectedRegistry = registry.project(declaration);
				feature = {
					enum_values: projectedRegistry.map((entry) => entry.value),
					platforms: registry.source ? declaration.platforms : PLATFORMS
				};
			}
			if (!feature) throw new Error(`${where} names "${row.path}", which is no enum feature`);
			if (row.choices !== undefined)
				throw new Error(`${where} lists its choices by hand; they come from the feature`);
			if (typeof row.i18n !== 'string' || row.i18n === '')
				throw new Error(`${where} has no i18n key`);
			if (!Array.isArray(feature.platforms))
				throw new Error(`"${row.path}" must declare its platforms to back a choice row`);
			// A row with no `platforms` is shown by every driver.
			for (const platform of row.platforms || ['ahk', 'hs', 'linux']) {
				if (!feature.platforms.includes(platform)) {
					throw new Error(`${where} is shown on ${platform}, where "${row.path}" does not exist`);
				}
			}
			const prefix = row.choice_label_prefix;
			if (prefix !== undefined && (typeof prefix !== 'string' || prefix === ''))
				throw new Error(`${where}: choice_label_prefix must be a non-empty locale-key prefix`);
			if (row.show_current_choice !== undefined && typeof row.show_current_choice !== 'boolean')
				throw new Error(`${where}: show_current_choice must be a boolean`);
			if (
				row.current_choice_placeholder !== undefined &&
				(typeof row.current_choice_placeholder !== 'string' ||
					row.show_current_choice !== true ||
					!/^\{(?:[1-9]\d*|[a-z][a-z0-9_]*)\}$/.test(row.current_choice_placeholder))
			)
				throw new Error(
					`${where}: current_choice_placeholder needs one token and show_current_choice`
				);
			if (
				row.current_choice_suffix !== undefined &&
				row.current_choice_placeholder !== undefined &&
				row.current_choice_placeholder !== '{1}'
			)
				throw new Error(`${where}: current_choice_suffix uses the {1} placeholder`);
			const values = row.choice_values === undefined ? feature.enum_values : row.choice_values;
			if (
				!Array.isArray(values) ||
				values.length < 2 ||
				new Set(values).size !== values.length ||
				values.some((value) => !feature.enum_values.includes(value))
			)
				throw new Error(
					`${where}: choice_values must be a unique enum subset with at least two values`
				);
			const technical = row.choice_label_kind === 'log_level_token';
			if (row.choice_label_kind !== undefined && (!technical || row.path !== 'script.log_level'))
				throw new Error(`${where}: choice_label_kind is reserved for the logger's enum tokens`);
			const icons = row.choice_icons;
			if (technical) {
				if (
					prefix !== undefined ||
					!icons ||
					typeof icons !== 'object' ||
					Array.isArray(icons) ||
					Object.keys(icons).length !== values.length ||
					values.some(
						(value) =>
							!Object.hasOwn(icons, value) ||
							typeof icons[value] !== 'string' ||
							!/^\p{Extended_Pictographic}\uFE0F?$/u.test(icons[value])
					)
				)
					throw new Error(`${where}: choice_icons must name every selected log token exactly once`);
			} else if (icons !== undefined) {
				throw new Error(`${where}: choice_icons belongs to log_level_token only`);
			}
			if (
				row.current_choice_suffix !== undefined &&
				(typeof row.current_choice_suffix !== 'string' ||
					row.show_current_choice !== true ||
					(row.current_choice_suffix.match(/\{1\}/g) || []).length !== 1 ||
					/[\p{L}\p{N}\r\n\t]/u.test(row.current_choice_suffix.replace('{1}', '')))
			)
				throw new Error(
					`${where}: current_choice_suffix needs punctuation, one {1} and show_current_choice`
				);
			row.choices =
				projectedRegistry ||
				values.map((value) =>
					technical
						? { value, label: `${icons[value]} ${value}` }
						: { value, i18n: prefix === undefined ? `${row.i18n}.${value}` : `${prefix}${value}` }
				);
			delete row.choice_registry;
			delete row.choice_values;
			delete row.choice_label_kind;
			delete row.choice_icons;
			// The compiler consumes this source metadata; native readers use only
			// the projected labels and must not carry a competing prefix policy.
			delete row.choice_label_prefix;
		}
	}
}

function build() {
	const raw = readFileSync(MANIFEST_PATH, 'utf8');
	const parsed = parseToml(raw);
	if (!parsed.menu || typeof parsed.menu !== 'object') {
		throw new Error('manifest.toml is missing the [menu] tables — cannot emit menu_manifest.json');
	}

	projectChoices(parsed.menu, raw);
	validateGreyedRows(parsed.menu);
	validateChildTemplates(parsed.menu);
	validateProviderStatus(parsed.menu);
	const out = { ...HEADER, ...parsed.menu };
	const json = JSON.stringify(out, null, '\t') + '\n';
	writeFileSync(OUT_PATH, json, 'utf8');
	console.log(
		`build-menu-manifest: wrote ${OUT_PATH} (${Object.keys(parsed.menu).length} top-level keys).`
	);
}

build();
