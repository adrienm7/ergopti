// tools/codegen/codegen-key-names.cjs

/**
 * ==============================================================================
 * MODULE: Key Name Table Generator
 * DESCRIPTION:
 * Projects `_shared/layouts/data/keycodes/key_names.json` (the one table naming a key
 * or modifier in visible text) to `_shared/platform/input/keycodes/key_names_data.lua` and
 * `windows/_generated/key_names.ahk`, so no driver parses JSON to name a key,
 * and to `_shared/ui/_generated/key_names.js` for the web pages.
 *
 * FEATURES & RATIONALE:
 * 1. Fails on an alias naming no key, an alias shadowing a key id, a platform
 *    the table does not declare, or a locale key outside `key_name.*`.
 * 2. The Windows projection resolves the `windows` column, so the AutoHotkey
 *    accessor reads one locale key per id.
 * 3. Output is deterministic and carries no timestamp, so the drift gate holds.
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const { shared } = require('../lib/paths.cjs');

const data = JSON.parse(
	fs.readFileSync(shared('layouts', 'data', 'keycodes', 'key_names.json'), 'utf8')
);
const PLATFORMS = data.platforms;
// The four modifier glyphs macOS prints on its keys and in its menus.
const MACOS_SYMBOLS = ['⌃', '⇧', '⌥', '⌘'];
const ids = Object.keys(data.keys);

for (const id of ids) {
	const entry = data.keys[id];
	if (!/^[a-z][a-z_]*$/.test(id)) throw new Error(`key id "${id}" is not lower snake_case`);
	if (!/^key_name\.[a-z_]+$/.test(entry.i18n)) throw new Error(`${id}: i18n "${entry.i18n}"`);
	for (const [platform, key] of Object.entries(entry.platforms || {})) {
		if (!PLATFORMS.includes(platform)) throw new Error(`${id}: unknown platform ${platform}`);
		if (!/^key_name\.[a-z_]+$/.test(key)) throw new Error(`${id}: ${platform} i18n "${key}"`);
	}
	if (entry.macos_symbol !== undefined && !MACOS_SYMBOLS.includes(entry.macos_symbol))
		throw new Error(`${id}: macos_symbol "${entry.macos_symbol}" is not one of ${MACOS_SYMBOLS}`);
}
for (const [alias, id] of Object.entries(data.aliases)) {
	if (!data.keys[id]) throw new Error(`alias "${alias}" names no key ("${id}")`);
	if (data.keys[alias]) throw new Error(`alias "${alias}" shadows a key id`);
}
const physical = data.physical;
if (!physical || !/^key_name\.[a-z_]+$/.test(physical.numpad))
	throw new Error('physical.numpad must name a key_name.* template');
for (const [code, legend] of Object.entries(physical.legends || {}))
	if (!/^[A-Z][A-Za-z]+$/.test(code) || typeof legend !== 'string' || legend === '')
		throw new Error(`physical legend "${code}" must be a W3C code with a nonempty legend`);

/** @param {string} value @returns {string} A double-quoted literal (JSON and Lua agree on ASCII). */
const quote = (value) => JSON.stringify(value);

/**
 * The locale key one platform shows for one id.
 * @param {string} id Key id.
 * @param {string} platform Platform name.
 * @returns {string}
 */
const keyFor = (id, platform) => (data.keys[id].platforms || {})[platform] || data.keys[id].i18n;

const lua = [
	'--- _shared/platform/input/keycodes/key_names_data.lua',
	'',
	'--- Generated by tools/codegen/codegen-key-names.cjs; do not edit.',
	'--- Source: _shared/layouts/data/keycodes/key_names.json.',
	'return {',
	`\tplatforms = { ${PLATFORMS.map(quote).join(', ')} },`,
	'\tkeys = {',
	...ids.map((id) => {
		const fields = PLATFORMS.map((p) => `${p} = ${quote(keyFor(id, p))}`);
		return `\t\t${id} = { ${fields.join(', ')} },`;
	}),
	'\t},',
	'\tmacos_symbols = {',
	...ids
		.filter((id) => typeof data.keys[id].macos_symbol === 'string')
		.map((id) => `\t\t${id} = ${quote(data.keys[id].macos_symbol)},`),
	'\t},',
	'\taliases = {',
	// Bracketed: `return` is a spelling of Enter and a Lua keyword.
	...Object.entries(data.aliases).map(([alias, id]) => `\t\t[${quote(alias)}] = ${quote(id)},`),
	'\t},',
	'\tphysical = {',
	`\t\tnumpad = ${quote(physical.numpad)},`,
	'\t\tlegends = {',
	...Object.entries(physical.legends).map(([code, legend]) => `\t\t\t${code} = ${quote(legend)},`),
	'\t\t},',
	'\t},',
	'}',
	''
].join('\n');
fs.writeFileSync(shared('platform', 'input', 'keycodes', 'key_names_data.lua'), lua, 'utf8');

const WINDOWS = 'windows';
/**
 * An AutoHotkey double-quoted literal: its escape is the backtick, so a
 * backslash stays itself and a backquote legend doubles.
 * @param {string} value @returns {string}
 */
const ahkQuote = (value) => '"' + value.replace(/`/g, '``').replace(/"/g, '`"') + '"';
const ahk = [
	'﻿; _generated/key_names.ahk',
	'',
	'; Generated by tools/codegen/codegen-key-names.cjs; do not edit.',
	'; Source: _shared/layouts/data/keycodes/key_names.json, the windows column.',
	'',
	'KeyNamesData() {',
	'\tstatic Data := Map(',
	'\t\t"keys", Map(',
	ids.map((id) => `\t\t\t${quote(id)}, ${quote(keyFor(id, WINDOWS))}`).join(',\n'),
	'\t\t),',
	'\t\t"aliases", Map(',
	Object.entries(data.aliases)
		.map(([alias, id]) => `\t\t\t${quote(alias)}, ${quote(id)}`)
		.join(',\n'),
	'\t\t),',
	`\t\t"numpad", ${ahkQuote(physical.numpad)},`,
	'\t\t"legends", Map(',
	Object.entries(physical.legends)
		.map(([code, legend]) => `\t\t\t${ahkQuote(code)}, ${ahkQuote(legend)}`)
		.join(',\n'),
	'\t\t)',
	'\t)',
	'\treturn Data',
	'}',
	''
].join('\n');
fs.writeFileSync(shared('..', 'windows', '_generated', 'key_names.ahk'), ahk, 'utf8');
const js = [
	'// _shared/ui/_generated/key_names.js',
	'',
	'// Generated by tools/codegen/codegen-key-names.cjs; do not edit.',
	'// Source: _shared/layouts/data/keycodes/key_names.json. Read through _shared/ui/key_names.js.',
	'',
	'const KEY_NAMES_DATA = Object.freeze({',
	`\tplatforms: Object.freeze([${PLATFORMS.map(quote).join(', ')}]),`,
	'\tkeys: Object.freeze({',
	ids
		.map((id) => {
			const fields = PLATFORMS.map((p) => `${p}: ${quote(keyFor(id, p))}`);
			return `\t\t${id}: Object.freeze({ ${fields.join(', ')} })`;
		})
		.join(',\n'),
	'\t}),',
	'\taliases: Object.freeze({',
	Object.entries(data.aliases)
		.map(([alias, id]) => `\t\t${quote(alias)}: ${quote(id)}`)
		.join(',\n'),
	'\t})',
	'});',
	''
].join('\n');
fs.writeFileSync(shared('ui', '_generated', 'key_names.js'), js, 'utf8');
console.log('[OK] Generated the key name table.');
