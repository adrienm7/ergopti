// tools/build/gen-metrics-category-aliases.cjs

/**
 * ==============================================================================
 * MODULE: Metrics Default-Category Alias Generator
 * DESCRIPTION:
 * Emits _shared/data/metrics_general_category_aliases.json — every localised
 * spelling of the metrics "General" category, in every shipped locale.
 *
 * WHY THIS FILE HAS TO EXIST:
 * The metrics app picker persists a user's category choice into
 * app_categories.json, and the DEFAULT it writes for an uncategorised app is
 * i18n.get("metrics_apps.general_category") — a localised string. So the file on
 * disk records the language that was active when it was written. A user who
 * switches from French to German gets "Allgemein" as the new default while their
 * file still holds "Général", and the picker then shows TWO general categories
 * where there should be one, with the old one demoted to a stray user category.
 *
 * Recognising the old spelling is the fix, and that needs the full set. Reading
 * 21 locale files at runtime to rebuild it on every render is not an option on a
 * UI path, and hand-copying them into the code is how the list goes stale the
 * next time a locale is added or a translation is corrected. So it is generated,
 * and test-metrics-category-ids.cjs fails if the committed file disagrees with
 * the locales.
 *
 * USAGE:
 *     node tools/build/gen-metrics-category-aliases.cjs
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const LOCALES_DIR = path.join(ROOT, 'static', 'ergopti_plus', '_shared', 'data', 'locales');
const OUT = path.join(ROOT, 'static', 'ergopti_plus', '_shared', 'data', 'metrics_general_category_aliases.json');

const KEY = 'metrics_apps.general_category';

/**
 * Reads one locale's value for KEY, tolerating both the flat and the nested
 * shape the locale files may use.
 * @param {object} json Parsed locale file.
 * @returns {string|undefined} The translated label.
 */
function valueFor(json) {
	if (typeof json[KEY] === 'string') return json[KEY];
	const [head, tail] = KEY.split('.');
	return json[head] && typeof json[head][tail] === 'string' ? json[head][tail] : undefined;
}

/**
 * Collects the label for every locale, keyed by locale code.
 * @returns {Record<string, string>} Locale code → label.
 */
function collect() {
	const out = {};
	for (const f of fs.readdirSync(LOCALES_DIR).sort()) {
		if (!f.endsWith('.json')) continue;
		const code = f.replace(/\.json$/, '');
		const v = valueFor(JSON.parse(fs.readFileSync(path.join(LOCALES_DIR, f), 'utf8')));
		if (v) out[code] = v;
	}
	return out;
}

module.exports = { collect, KEY, OUT };

if (require.main === module) {
	const byLocale = collect();
	const aliases = [...new Set(Object.values(byLocale))].sort();
	const doc = {
		_comment:
			'AUTO-GENERATED by tools/build/gen-metrics-category-aliases.cjs. Every localised ' +
			'spelling of the metrics default category. app_categories.json stores this value ' +
			'verbatim, so a user who switches language has an older spelling on disk; all of ' +
			'these must resolve to the same category or their overrides are orphaned.',
		key: KEY,
		by_locale: byLocale,
		aliases,
	};
	fs.mkdirSync(path.dirname(OUT), { recursive: true });
	fs.writeFileSync(OUT, JSON.stringify(doc, null, '\t') + '\n', 'utf8');
	console.log(`[gen] ${aliases.length} distinct spelling(s) across ${Object.keys(byLocale).length} locale(s) → ${path.relative(ROOT, OUT)}`);
}
