// tools/codegen/codegen-slot-roles.cjs

/**
 * ==============================================================================
 * MODULE: Slot Role Table Generator
 * DESCRIPTION:
 * Projects `_shared/modules/actions/slot_roles.json` (the neutral keyboard-slot
 * grammar of PAR-41) to `_shared/lua/shortcuts/slot_roles_data.lua`, so the Lua
 * drivers resolve a role to their own modifier without reading JSON inside a
 * keyboard callback.
 *
 * FEATURES & RATIONALE:
 * 1. Fails on a role that is missing for a driver or has no reason when absent.
 * 2. Output is deterministic and carries no timestamp, so the drift gate holds.
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const { shared } = require('../lib/paths.cjs');

const DRIVERS = ['windows', 'macos', 'linux'];

const data = JSON.parse(fs.readFileSync(shared('modules', 'actions', 'slot_roles.json'), 'utf8'));

/** @param {string} value @returns {string} A Lua double-quoted string literal. */
const quote = (value) => JSON.stringify(value);

const order = data.modifier_order;
if (new Set(order).size !== order.length) throw new Error('modifier_order repeats a role');
const roles = order.map((name) => {
	const role = data.roles[name];
	if (!role) throw new Error(`role "${name}" is in modifier_order but not in roles`);
	for (const driver of DRIVERS) {
		if (!(driver in role)) throw new Error(`role "${name}" does not answer for ${driver}`);
		if (role[driver] === null && typeof role.absent_reason !== 'string') {
			throw new Error(`role "${name}" is absent on ${driver} without an absent_reason`);
		}
	}
	const fields = DRIVERS.filter((d) => role[d] !== null).map((d) => `${d} = ${quote(role[d])}`);
	return `\t\t${name} = { ${fields.join(', ')} },`;
});
if (Object.keys(data.roles).length !== order.length)
	throw new Error('roles holds a role missing from modifier_order');

const absent = order
	.filter((name) => data.roles[name].absent_reason)
	.map((name) => `\t\t${name} = ${quote(data.roles[name].absent_reason)},`);

/** Role combinations of one driver, in the data's order, each with its prefix. */
const families = DRIVERS.flatMap((driver) =>
	(data.families[driver] || []).map((roles) => {
		const ranks = roles.map((r) => order.indexOf(r));
		if (ranks.some((r) => r < 0)) throw new Error(`${driver} family names an unknown role`);
		if (ranks.some((r, i) => i > 0 && r <= ranks[i - 1]))
			throw new Error(`${driver} family ${roles} is misordered`);
		for (const role of roles) {
			if (data.roles[role][driver] === null)
				throw new Error(`${driver} family uses ${role}, absent there`);
		}
		return `\t\t{ driver = ${quote(driver)}, prefix = ${quote(roles.join('_') + '_')}, roles = { ${roles.map(quote).join(', ')} } },`;
	})
);
const extraKeys = DRIVERS.flatMap((driver) =>
	(data.extra_keys[driver] || []).map(
		(key) =>
			`\t\t{ driver = ${quote(driver)}, id = ${quote(key.id)}, label = ${quote(key.label)}, chord_key = ${quote(key.chord_key)} },`
	)
);

const lua = [
	'--- _shared/lua/shortcuts/slot_roles_data.lua',
	'',
	'--- Generated by tools/codegen/codegen-slot-roles.cjs; do not edit.',
	'--- Source: _shared/modules/actions/slot_roles.json.',
	'return {',
	`\tmodifier_order = { ${order.map(quote).join(', ')} },`,
	'\troles = {',
	...roles,
	'\t},',
	'\tabsent_reason = {',
	...absent,
	'\t},',
	'\tfamilies = {',
	...families,
	'\t},',
	'\textra_keys = {',
	...extraKeys,
	'\t},',
	'}',
	''
].join('\n');

fs.writeFileSync(shared('lua', 'shortcuts', 'slot_roles_data.lua'), lua, 'utf8');
console.log('[OK] Generated the neutral slot role table.');
