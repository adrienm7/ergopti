/** Emits the shared personal-source descriptor contract for both runtime languages. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '../..');
const SOURCE = 'static/ergopti_plus/_shared/modules/hotstrings/personal_files.json';
const LUA_OUTPUT = 'static/ergopti_plus/_shared/lua/hotstrings/personal_files.lua';
const AHK_OUTPUT = 'static/ergopti_plus/windows/_generated/personal_file_descriptors.ahk';

/** The versioned identity policy is deliberately narrower than arbitrary path text. */
function validate(policy) {
	if (
		!policy ||
		policy.version !== 1 ||
		!/^[a-z][a-z0-9_-]*:$/.test(policy.namespace) ||
		policy.component_separator !== ':' ||
		policy.extension !== '.toml' ||
		policy.additional_default_enabled !== true ||
		policy.additional_priority_tier !== 'package' ||
		policy.additional_default_delay_seconds !== 0 ||
		!Number.isSafeInteger(policy.additional_scan_max_depth) ||
		policy.additional_scan_max_depth < 1 ||
		!/^\.[a-z]+-$/.test(policy.backup_infix) ||
		typeof policy.label_separator !== 'string' ||
		/[\x00-\x1f\x7f]/.test(policy.label_separator) ||
		!policy.label_separator.isWellFormed()
	)
		throw new TypeError('Invalid personal-file descriptor policy.');
	if (
		Object.keys(policy).sort().join(',') !==
		'additional_default_delay_seconds,additional_default_enabled,additional_priority_tier,additional_scan_max_depth,backup_infix,component_separator,extension,label_separator,namespace,version'
	)
		throw new TypeError('Unknown personal-file descriptor policy field.');
	return policy;
}

/** Emit native syntax with one policy and identical reversible byte identities. */
function render(policy) {
	validate(policy);
	let lua = String.raw`--- _shared/lua/hotstrings/personal_files.lua

--- Generated by tools/codegen/codegen-personal-file-descriptors.cjs; do not edit.
--- Source: _shared/modules/hotstrings/personal_files.json.
local M = {}
local Utf8 = require("compat.utf8")
local NAMESPACE = @NAMESPACE@
local SEPARATOR = @SEPARATOR@
local LABEL_SEPARATOR = @LABEL_SEPARATOR@
local EXTENSION = @EXTENSION@
local BACKUP_INFIX = @BACKUP_INFIX@

-- Adoption policy is separate from the exact three-field provenance descriptor.
M.additional_default_enabled = @DEFAULT_ENABLED@
M.additional_priority_tier = @PRIORITY_TIER@
M.additional_default_delay_seconds = @DEFAULT_DELAY@
M.additional_scan_max_depth = @SCAN_DEPTH@

--- Recognise the copies that configuration writers leave beside their source
--- (<stem>.backup-<stamp>.toml). Every driver writes them into the scanned
--- hotstrings folder, so discovery must never load one as a hotstring source.
--- @param name any File name or path.
--- @return boolean
function M.is_backup(name)
	if type(name) ~= "string" then return false end
	local lower = (name:match("([^/\\]+)$") or ""):lower()
	if #lower <= #EXTENSION or lower:sub(-#EXTENSION) ~= EXTENSION then return false end
	local stem, start, from = lower:sub(1, -#EXTENSION - 1), nil, 1
	while true do
		local found = stem:find(BACKUP_INFIX, from, true)
		if not found then break end
		start, from = found, found + 1
	end
	if not start or start == 1 then return false end
	return stem:sub(start + #BACKUP_INFIX):find("^[%d%-]+$") ~= nil
end

--- Preserve actual filename components, independent of labels or activation groups.
--- @param components table Dense relative filename components, including .toml.
--- @return table descriptor Fresh id, components and label fields.
function M.describe(components)
	assert(type(components) == "table" and #components > 0, "invalid personal-file components")
	local count, copied, encoded, labels = 0, {}, {}, {}
	for key in pairs(components) do
		assert(type(key) == "number" and key % 1 == 0 and key >= 1 and key <= #components,
			"invalid personal-file component array")
		count = count + 1
	end
	assert(count == #components, "sparse personal-file components")
	for index, component in ipairs(components) do
		assert(type(component) == "string" and component ~= "" and component ~= "." and component ~= ".."
			and not component:find("/", 1, true) and not component:find("\0", 1, true)
			and Utf8.len(component) ~= nil, "invalid personal-file component")
		copied[index], labels[index] = component, component
		encoded[index] = component:gsub(".", function(byte) return string.format("%02x", byte:byte()) end)
	end
	local last = copied[#copied]
	assert(last:sub(-#EXTENSION):lower() == EXTENSION,
		"personal source is not a TOML filename")
	labels[#labels] = last:sub(1, -#EXTENSION - 1)
	return { id = NAMESPACE .. table.concat(encoded, SEPARATOR), components = copied,
		label = table.concat(labels, LABEL_SEPARATOR) }
end

--- Decode only canonical identities; aliases, malformed UTF-8 and traversal refuse.
--- @param id any Canonical identity.
--- @return table|nil components Fresh exact components, or nil on refusal.
function M.components(id)
	if type(id) ~= "string" or id:sub(1, #NAMESPACE) ~= NAMESPACE then return nil end
	local body, decoded = id:sub(#NAMESPACE + 1), {}
	if body == "" or body:sub(1, 1) == SEPARATOR or body:sub(-1) == SEPARATOR
		or body:find(SEPARATOR .. SEPARATOR, 1, true) then return nil end
	for part in body:gmatch("[^:]+") do
		if #part % 2 ~= 0 or part:find("[^0-9a-f]") then return nil end
		decoded[#decoded + 1] = part:gsub("..", function(hex) return string.char(tonumber(hex, 16)) end)
	end
	local ok, descriptor = pcall(M.describe, decoded)
	if not ok or descriptor.id ~= id then return nil end
	return descriptor.components
end

--- Reject forged ids, borrowed labels and extra descriptor fields before transport.
--- @param descriptor any Candidate descriptor.
--- @return boolean
function M.is_descriptor(descriptor)
	if type(descriptor) ~= "table" then return false end
	local count = 0
	for key in pairs(descriptor) do
		if key ~= "id" and key ~= "components" and key ~= "label" then return false end
		count = count + 1
	end
	if count ~= 3 then return false end
	local ok, expected = pcall(M.describe, descriptor.components)
	return ok and expected.id == descriptor.id and expected.label == descriptor.label
end

--- Neutral activation policy for exact canonical file/section preference paths.
--- Classification is not admission to a native capability or source mutation.
--- @param path any Semantic path, with quoted dotted section components.
--- @return boolean|nil
function M.preference_default(path)
	local parts = require("toml_codec.key_path").parse(path, true)
	if not parts or parts[1] ~= "hotstrings" then return nil end
	if #parts == 3 and parts[2] == "groups" and M.components(parts[3]) then
		return M.additional_default_enabled
	end
	if #parts == 4 and parts[2] == "modules" and M.components(parts[3]) and parts[4] ~= "" then
		return M.additional_default_enabled
	end
	return nil
end

--- Own the snapshot so callers cannot mutate another source's provenance.
--- @param descriptor table Valid descriptor.
--- @return table copy
function M.copy(descriptor)
	assert(M.is_descriptor(descriptor), "invalid personal-file descriptor")
	return M.describe(descriptor.components)
end

return M
`;
	let ahk = String.raw`; _generated/personal_file_descriptors.ahk

; Generated by tools/codegen/codegen-personal-file-descriptors.cjs; do not edit.
; Source: _shared/modules/hotstrings/personal_files.json.

/** Additional-file policy applies only after explicit native owner adoption. */
PersonalFileDefaultEnabled() => @DEFAULT_ENABLED@
PersonalFilePriorityTier() => @PRIORITY_TIER@
PersonalFileDefaultDelay() => @DEFAULT_DELAY@
PersonalFileScanMaxDepth() => @SCAN_DEPTH@

/**
 * Recognises the copies configuration writers leave beside their source
 * (<stem>.backup-<stamp>.toml). They sit in the scanned hotstrings folder, so
 * discovery must never load one as a hotstring source.
 * @param {String} Name File name or path.
 * @returns {Integer} True for a writer backup.
 */
PersonalFileIsBackup(Name) {
	if !(Name is String)
		return false
	SplitPath(Name, &Leaf)
	Extension := @EXTENSION@, Infix := @BACKUP_INFIX@
	if StrLen(Leaf) <= StrLen(Extension) || StrLower(SubStr(Leaf, -StrLen(Extension))) != Extension
		return false
	Stem := SubStr(Leaf, 1, StrLen(Leaf) - StrLen(Extension))
	Position := InStr(Stem, Infix, false, -1)
	if Position <= 1
		return false
	return RegExMatch(SubStr(Stem, Position + StrLen(Infix)), "^[0-9-]+$") ? true : false
}

/** Builds an exact relative personal-source identity without choosing a runtime group. */
PersonalFileDescribe(Components) {
	if !(Components is Array) || Components.Length == 0
		throw TypeError("Invalid personal-file components.")
	Copied := [], Encoded := [], Labels := []
	for _, Component in Components {
		if !(Component is String) || Component == "" || Component == "." || Component == ".." || InStr(Component, "/")
			throw TypeError("Invalid personal-file component.")
		Size := StrPut(Component, "UTF-8")
		Bytes := Buffer(Size, 0)
		StrPut(Component, Bytes, "UTF-8")
		if !(StrGet(Bytes, "UTF-8") == Component)
			throw TypeError("Invalid personal-file Unicode.")
		Hex := ""
		loop Size - 1
			Hex .= Format("{:02x}", NumGet(Bytes, A_Index - 1, "UChar"))
		Copied.Push(Component)
		Encoded.Push(Hex)
		Labels.Push(Component)
	}
	Last := Copied[Copied.Length]
	Extension := @EXTENSION@
	if StrLower(SubStr(Last, -StrLen(Extension))) != Extension
		throw TypeError("Personal source is not a TOML filename.")
	Labels[Labels.Length] := SubStr(Last, 1, StrLen(Last) - StrLen(Extension))
	Identity := @NAMESPACE@, Label := ""
	for Position, Hex in Encoded
		Identity .= (Position > 1 ? @SEPARATOR@ : "") . Hex
	for Position, Part in Labels
		Label .= (Position > 1 ? @LABEL_SEPARATOR@ : "") . Part
	return Map("id", Identity, "components", Copied, "label", Label)
}

/** Returns exact components only for canonical reversible descriptor identities. */
PersonalFileComponents(Identity) {
	Namespace := @NAMESPACE@
	if !(Identity is String) || !(SubStr(Identity, 1, StrLen(Namespace)) == Namespace)
		return 0
	Body := SubStr(Identity, StrLen(Namespace) + 1)
	if Body == "" || SubStr(Body, 1, 1) == @SEPARATOR@ || SubStr(Body, -1) == @SEPARATOR@ || InStr(Body, @SEPARATOR@ . @SEPARATOR@)
		return 0
	Decoded := []
	for _, Part in StrSplit(Body, @SEPARATOR@) {
		if Mod(StrLen(Part), 2) || RegExMatch(Part, "[^0-9a-f]")
			return 0
		Bytes := Buffer(StrLen(Part) // 2 + 1, 0)
		loop StrLen(Part) // 2
			NumPut("UChar", Integer("0x" . SubStr(Part, A_Index * 2 - 1, 2)), Bytes, A_Index - 1)
		Decoded.Push(StrGet(Bytes, "UTF-8"))
	}
	try {
		Descriptor := PersonalFileDescribe(Decoded)
		if !(Descriptor["id"] == Identity)
			return 0
		return Descriptor["components"]
	} catch {
		return 0
	}
}

/** Validates the exact descriptor shape rather than trusting supplied ids or labels. */
PersonalFileDescriptorValid(Descriptor) {
	if !(Descriptor is Map) || Descriptor.Count != 3 || !Descriptor.Has("id") || !Descriptor.Has("components") || !Descriptor.Has("label")
		return false
	for DescriptorKey in Descriptor {
		if !(DescriptorKey == "id") && !(DescriptorKey == "components") && !(DescriptorKey == "label")
			return false
	}
	if !(Descriptor["id"] is String) || !(Descriptor["label"] is String) || !(Descriptor["components"] is Array)
		return false
	try {
		Expected := PersonalFileDescribe(Descriptor["components"])
		return Expected["id"] == Descriptor["id"] && Expected["label"] == Descriptor["label"]
	} catch {
		return false
	}
}

/** Neutral policy classifies an exact canonical path; it never adopts a capability. */
PersonalFilePreferenceDefault(Path) {
	try Parts := TOML_ParseKeyPath(Path, true)
	catch
		return ""
	if Parts.Length < 3 || Parts[1] != "hotstrings" || !PersonalFileComponents(Parts[3])
		return ""
	if (Parts.Length == 3 && Parts[2] == "groups")
		|| (Parts.Length == 4 && Parts[2] == "modules" && Parts[4] != "")
		return PersonalFileDefaultEnabled()
	return ""
}

/** Returns an independent owned snapshot for each producer and consumer. */
PersonalFileDescriptorCopy(Descriptor) {
	if !PersonalFileDescriptorValid(Descriptor)
		throw TypeError("Invalid personal-file descriptor.")
	return PersonalFileDescribe(Descriptor["components"])
}
`;
	for (const [token, value] of Object.entries({
		NAMESPACE: policy.namespace,
		SEPARATOR: policy.component_separator,
		LABEL_SEPARATOR: policy.label_separator,
		EXTENSION: policy.extension,
		BACKUP_INFIX: policy.backup_infix,
		PRIORITY_TIER: policy.additional_priority_tier
	})) {
		lua = lua.replaceAll('@' + token + '@', JSON.stringify(value));
		const ahkValue =
			'"' + value.replaceAll('`', '``').replaceAll('"', '`"').replaceAll(';', '`;') + '"';
		ahk = ahk.replaceAll('@' + token + '@', ahkValue);
	}
	for (const [token, value] of Object.entries({
		DEFAULT_ENABLED: policy.additional_default_enabled,
		DEFAULT_DELAY: policy.additional_default_delay_seconds,
		SCAN_DEPTH: policy.additional_scan_max_depth
	})) {
		lua = lua.replaceAll('@' + token + '@', String(value));
		ahk = ahk.replaceAll('@' + token + '@', value === true ? 'true' : String(value));
	}
	return { lua, ahk };
}

/** Regenerate owned outputs in the selected repository or private policy fixture. */
function main(root = ROOT) {
	const policy = JSON.parse(fs.readFileSync(path.join(root, SOURCE), 'utf8'));
	const outputs = render(policy);
	for (const [file, content] of [
		[LUA_OUTPUT, outputs.lua],
		[AHK_OUTPUT, '\uFEFF' + outputs.ahk]
	]) {
		fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
		fs.writeFileSync(path.join(root, file), content, 'utf8');
	}
}
module.exports = { render, main, SOURCE, LUA_OUTPUT, AHK_OUTPUT };
if (require.main === module) main();
