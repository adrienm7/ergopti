#!/usr/bin/env bash
# tools/build/build-linux-driver.sh
#
# Assembles the Linux driver into a distributable bundle and runs a smoke test.
#
# This script is run by CI (build-linux job) after all validations pass. It:
#   1. Copies the linux driver sources + _shared/ tree into build/linux/
#   2. Copies kanata.kbd and install.sh
#   3. Resolves the Lua module search path and generates a wrapper script
#   4. Verifies all required files exist (integrity check)
#   5. Runs a smoke test: luajit ergopti_hotstrings.lua --help (exit 0 check)
#
# The output at build/linux/ is a self-contained directory that mirrors the
# installed structure under ~/.local/lib/ergopti/.
#
# Usage:
#   bash tools/build/build-linux-driver.sh
#
#   bash tools/build/build-linux-driver.sh --skip-smoke
#     (skip the smoke test — useful when LuaJIT is unavailable)

set -euo pipefail

SKIP_SMOKE=false
while [[ $# -gt 0 ]]; do
	case "$1" in
		--skip-smoke) SKIP_SMOKE=true; shift ;;
		*) echo "Unknown option: $1"; exit 1 ;;
	esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd -P)"

# ----------------------------------------------------------------------------
# Portable recursive copy with exclusions (rsync when available, cp -r fallback).
# Usage: copy_tree <src_dir/> <dst_dir/> [--exclude pattern ...]
# ----------------------------------------------------------------------------
copy_tree() {
	local src="$1"; shift
	local dst="$1"; shift
	local excludes=("$@")

	if command -v rsync >/dev/null 2>&1; then
		local rsync_args=(-a)
		for pat in "${excludes[@]}"; do
			rsync_args+=(--exclude="$pat")
		done
		rsync "${rsync_args[@]}" "$src" "$dst"
	else
		# Fallback: cp -r + manual exclusion removal.
		cp -r "$src"* "$dst" 2>/dev/null || cp -r "$src". "$dst" 2>/dev/null || true
		for pat in "${excludes[@]}"; do
			# Remove files/dirs matching the exclude patterns after copy.
			# Patterns like 'tests' match directory names at any level.
			if [[ "$pat" != *'*'* ]]; then
				find "$dst" -name "$pat" -type d -exec rm -rf {} + 2>/dev/null || true
			else
				# Pattern with wildcard (e.g. 'ui/*'): strip the wildcard part.
				local base="${pat%/*}"
				local glob="${pat##*/}"
				if [ -d "$dst/$base" ]; then
					find "$dst/$base" -maxdepth 1 -name "$glob" -exec rm -rf {} + 2>/dev/null || true
				fi
			fi
		done
	fi
}

LINUX_SRC="${REPO_ROOT}/static/ergopti_plus/linux"
SHARED_SRC="${REPO_ROOT}/static/ergopti_plus/_shared"
KANATA_SRC="${REPO_ROOT}/static/ergopti_plus/linux/platform/remap/data/kanata.kbd"
BUILD_DIR="${REPO_ROOT}/build/linux"

echo "=== Ergopti Linux driver assembly ==="
echo "  Source  : ${LINUX_SRC}"
echo "  Shared  : ${SHARED_SRC}"
echo "  Build   : ${BUILD_DIR}"
echo ""

# ============================================================================
# 1. Clean and create build directory
# ============================================================================
rm -rf "${BUILD_DIR}"
mkdir -p "${BUILD_DIR}/linux"
mkdir -p "${BUILD_DIR}/_shared"

# ============================================================================
# 2. Copy driver sources (exclude tests, vendor, _generated)
# ============================================================================
echo "--- Copying Linux driver sources ---"

copy_tree "${LINUX_SRC}/" "${BUILD_DIR}/linux/" --exclude vendor --exclude _generated

# Restore generated files specifically (config template is generated by build:domain)
mkdir -p "${BUILD_DIR}/linux/_generated"
if [ -f "${LINUX_SRC}/_generated/config_template.toml" ]; then
	cp "${LINUX_SRC}/_generated/config_template.toml" "${BUILD_DIR}/linux/_generated/"
fi

# ============================================================================
# 3. Copy shared tree (exclude tests, ui, corpus)
# ============================================================================
echo "--- Copying _shared tree ---"

copy_tree "${SHARED_SRC}/" "${BUILD_DIR}/_shared/" --exclude 'ui/*' --exclude corpus

# But keep the UI host_bridge.js and i18n.js (needed by webkit_host)
for f in host_bridge.js i18n.js dom_utils.js apps.manifest.json; do
	if [ -f "${SHARED_SRC}/ui/${f}" ]; then
		mkdir -p "${BUILD_DIR}/_shared/ui"
		cp "${SHARED_SRC}/ui/${f}" "${BUILD_DIR}/_shared/ui/"
	fi
done

# ============================================================================
# 4. Copy kanata config and install script
# ============================================================================
echo "--- Copying kanata config ---"

cp "${KANATA_SRC}" "${BUILD_DIR}/kanata.kbd"
cp "${LINUX_SRC}/install.sh" "${BUILD_DIR}/install.sh"
chmod +x "${BUILD_DIR}/install.sh"

# ============================================================================
# 5. Generate wrapper script
# ============================================================================
echo "--- Generating wrapper script ---"

DRIVER_ROOT='${HOME}/.local/lib/ergopti/linux'
SHARED_LUA='${HOME}/.local/lib/ergopti/_shared/lua'

mkdir -p "${BUILD_DIR}/bin"
cat > "${BUILD_DIR}/bin/ergopti-hotstrings" << WRAPPER
#!/usr/bin/env bash
# Auto-generated by build-linux-driver.sh — do not edit manually.
set -euo pipefail

# Resolve the installed location relative to this script.
WRAPPER_DIR="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd -P)"
INSTALL_ROOT="\$(cd "\${WRAPPER_DIR}/.." && pwd -P)"

DRIVER_ROOT="\${INSTALL_ROOT}/linux"
SHARED_LUA="\${INSTALL_ROOT}/_shared/lua"

export LUA_PATH="\${DRIVER_ROOT}/?.lua;\${DRIVER_ROOT}/?/init.lua;\${SHARED_LUA}/?.lua;\${SHARED_LUA}/?/init.lua;;"

if command -v luajit >/dev/null 2>&1; then
	exec luajit "\${DRIVER_ROOT}/ergopti_hotstrings.lua" "\$@"
elif command -v lua5.4 >/dev/null 2>&1; then
	exec lua5.4 "\${DRIVER_ROOT}/ergopti_hotstrings.lua" "\$@"
elif command -v lua >/dev/null 2>&1; then
	exec lua "\${DRIVER_ROOT}/ergopti_hotstrings.lua" "\$@"
else
	echo "Error: No Lua runtime found (luajit, lua5.4, or lua)." >&2
	exit 1
fi
WRAPPER
chmod +x "${BUILD_DIR}/bin/ergopti-hotstrings"

# ============================================================================
# 6. Integrity check — verify all required files exist
# ============================================================================
echo ""
echo "--- Integrity check ---"

REQUIRED_FILES=(
	"linux/ergopti_hotstrings.lua"
	"linux/modules/hotstrings/engine.lua"
	"linux/modules/hotstrings/loader.lua"
	"linux/modules/hotstrings/injector.lua"
	"linux/modules/hotstrings/input_reader.lua"
	"linux/modules/hotstrings/device_finder.lua"
	"linux/modules/keylogger/metrics_collector.lua"
	"linux/adapters/http_client.lua"
	"linux/adapters/tray_menu.lua"
	"linux/infra/locale.lua"
	"linux/infra/i18n.lua"
	"linux/infra/timings.lua"
	"linux/ui/webkit_host.lua"
	"linux/tests/run.lua"
	"linux/tests/helpers.lua"
	"_shared/lua/hotstring_engine/init.lua"
	"_shared/lua/keylogger/utils.lua"
	"_shared/lua/keylogger/metrics.lua"
	"_shared/lua/keylogger/aggregator_helpers.lua"
	"_shared/lua/llm/prompt_builder.lua"
	"linux/infra/llm_bridge.lua"
	"_shared/lua/tray/protocol.lua"
	"_shared/lua/compat/utf8.lua"
	"_shared/lua/keymap/terminators.lua"
	"_shared/lua/keymap/terminators_catalogue.lua"
	"_shared/lua/keycodes/evdev.lua"
	"_shared/lua/updater/version.lua"
	"_shared/lua/json.lua"
	"_shared/data/keycodes/evdev.json"
	"_shared/data/locales/fr.json"
	"_shared/data/locales/en.json"
	"_shared/modules/timings/constants.toml"
	"_shared/modules/llm/defaults.json"
	"_shared/modules/llm/profiles.json"
	"_shared/modules/features/manifest.schema.json"
	"_shared/modules/menu/menu_manifest.json"
	"_shared/modules/hotstrings/defaults.toml"
	"_shared/ui/host_bridge.js"
	"_shared/ui/i18n.js"
	"kanata.kbd"
	"install.sh"
	"bin/ergopti-hotstrings"
)

MISSING=0
for f in "${REQUIRED_FILES[@]}"; do
	if [ ! -f "${BUILD_DIR}/${f}" ]; then
		echo "  MISSING: ${f}"
		MISSING=$((MISSING + 1))
	fi
done

if [ $MISSING -gt 0 ]; then
	echo ""
	echo "ERROR: ${MISSING} required file(s) missing from build."
	exit 1
fi

FILE_COUNT=$(find "${BUILD_DIR}" -type f | wc -l)
echo "  OK — all ${#REQUIRED_FILES[@]} required files present (${FILE_COUNT} total files)."

# ============================================================================
# 7. Smoke test — verify the assembled driver boots without crashing
# ============================================================================
if [ "$SKIP_SMOKE" = true ]; then
	echo ""
	echo "--- Smoke test SKIPPED (--skip-smoke) ---"
	echo ""
	echo "=== Linux driver assembled successfully ==="
	echo "  Output: ${BUILD_DIR}/"
	exit 0
fi

echo ""
echo "--- Smoke test ---"

# Find an available Lua runtime
LUA_BIN=""
for candidate in luajit lua5.4 lua; do
	if command -v "$candidate" >/dev/null 2>&1; then
		LUA_BIN="$candidate"
		break
	fi
done

if [ -z "$LUA_BIN" ]; then
	echo "WARNING: No Lua runtime found — skipping smoke test."
	echo "  Install luajit or lua5.4 to enable this check."
else
	echo "  Lua runtime: ${LUA_BIN} ($(${LUA_BIN} -v 2>&1 || true))"

	# Set up LUA_PATH so requires resolve from the build directory.
	# On Windows, Lua's package.path expects backslashes — use forward slashes
	# in the template and let Lua handle normalization via the inline -e script
	# (which constructs package.path programmatically, avoiding shell escaping).
	BUILD_DIR_FWD="${BUILD_DIR}"  # already forward-slash from bash on Windows

	# Helper: runs a Lua one-liner with the build directory on package.path.
	# Passes the build root as the first argument so Lua can resolve paths
	# portably regardless of OS path separator conventions.
	_lua_with_path() {
		local lua_code="$1"
		${LUA_BIN} -e "
			local build_dir = '${BUILD_DIR_FWD}'
			-- Normalize to the OS path separator (Lua package.config).
			local sep = package.config:sub(1,1)
			if sep == '\\\\' then build_dir = build_dir:gsub('/', '\\\\') end
			local driver_root = build_dir .. sep .. 'linux'
			local shared_lua  = build_dir .. sep .. '_shared' .. sep .. 'lua'
			package.path = driver_root .. sep .. '?.lua;' ..
			               driver_root .. sep .. '?' .. sep .. 'init.lua;' ..
			               shared_lua  .. sep .. '?.lua;' ..
			               shared_lua  .. sep .. '?' .. sep .. 'init.lua;' ..
			               (package.path or '')
			${lua_code}
		" 2>&1
	}

	# Test 1: --help must exit 0
	echo "  Test: --help exits 0..."
	if ${LUA_BIN} "${BUILD_DIR}/linux/ergopti_hotstrings.lua" --help >/dev/null 2>&1; then
		echo "    OK — --help exits 0"
	else
		echo "    FAIL — --help exited non-zero"
		exit 1
	fi

	# On real Linux (CI), also verify the engine and shared modules load.
	# Skip on Windows/MSYS — Git Bash paths (/d/...) are incompatible with
	# Lua's package.path which expects Windows-style (d:\...).
	if [[ "$(uname -s 2>/dev/null || echo '')" == Linux ]]; then
		# Test 2: require the engine module (validates package.path)
		echo "  Test: require('modules.hotstrings.engine')..."
		if _lua_with_path "
			local engine = require('modules.hotstrings.engine')
			local e = engine.new()
			assert(e ~= nil, 'engine.new() returned nil')
			assert(type(e.on_char) == 'function', 'on_char is not a function')
			assert(type(e.load_mappings) == 'function', 'load_mappings is not a function')
			print('OK')
		"; then
			echo "    OK — engine module loads and instantiates"
		else
			echo "    FAIL — engine module failed to load"
			exit 1
		fi

		# Test 3: verify all shared modules can be required (non-blocking)
		echo "  Test: require all shared modules..."
		SHARED_MODS=(
			"keylogger.utils"
			"keylogger.metrics"
			"keylogger.aggregator_helpers"
			"llm.prompt_builder"
			"infra.llm_bridge"
			"tray.protocol"
			"compat.utf8"
			"keymap.terminators"
			"keycodes.evdev"
			"updater.version"
		)
		SHARED_OK=true
		for mod in "${SHARED_MODS[@]}"; do
			if ! _lua_with_path "
				local ok, m = pcall(require, '${mod}')
				assert(ok, 'require failed: ' .. tostring(m))
			"; then
				echo "    FAIL — require('${mod}') failed"
				SHARED_OK=false
			fi
		done
		if [ "$SHARED_OK" = true ]; then
			echo "    OK — all ${#SHARED_MODS[@]} shared modules load"
		fi
	else
		echo "  (skipping engine/module tests — not on Linux, uses native paths)"
	fi
fi

echo ""
echo "=== Linux driver assembled successfully ==="
echo "  Output  : ${BUILD_DIR}/"
echo "  Binary   : ${BUILD_DIR}/bin/ergopti-hotstrings"
echo "  Kanata   : ${BUILD_DIR}/kanata.kbd"
echo "  Installer: ${BUILD_DIR}/install.sh"
