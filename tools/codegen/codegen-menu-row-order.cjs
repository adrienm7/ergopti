// tools/codegen/codegen-menu-row-order.cjs

/**
 * ==============================================================================
 * MODULE: Menu Row Order Data Generator
 * DESCRIPTION:
 * Projects the display-order rules of _shared/modules/menu/row_order.json into
 * shared Lua data, so no driver spells an order of its own.
 *
 * FEATURES & RATIONALE:
 * 1. Each rule must be a non-empty list of distinct strings: a duplicate would
 *    make the rank of a name depend on which entry won.
 * 2. Only the order is projected; descriptions stay in the JSON source.
 * ==============================================================================
 */
'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const { shared } = require('../lib/paths.cjs');

/** Serializes a string as a Lua literal, escaping what Lua reads differently. */
function literal(text) {
	return JSON.stringify(text).replace(/\\u([0-9a-f]{4})/gi, (_match, hex) => {
		const code = parseInt(hex, 16);
		return code < 256 ? `\\${String(code).padStart(3, '0')}` : String.fromCharCode(code);
	});
}

const source = shared('modules', 'menu', 'row_order.json');
const target = shared('lua', 'menu', 'row_order_data.lua');
const data = JSON.parse(fs.readFileSync(source, 'utf8'));
const names = Object.keys(data.rules);
assert(names.length > 0, 'row_order.json declares no rule');
const blocks = names.map((name) => {
	const order = data.rules[name].order;
	assert(
		Array.isArray(order) &&
			order.length > 0 &&
			order.every((item) => typeof item === 'string' && item !== ''),
		`${name}: an order is a non-empty list of strings`
	);
	assert.equal(new Set(order).size, order.length, `${name}: duplicate entry`);
	return `\t[${literal(name)}] = {\n${order.map((item) => `\t\t${literal(item)},`).join('\n')}\n\t},`;
});
fs.writeFileSync(
	target,
	'--- _shared/lua/menu/row_order_data.lua\n\n' +
		'--- Generated by tools/codegen/codegen-menu-row-order.cjs; do not edit.\n' +
		'--- Source: _shared/modules/menu/row_order.json.\n' +
		`return {\n${blocks.join('\n')}\n}\n`,
	'utf8'
);
console.log('[OK] Generated shared menu row order data.');
