// tools/codegen/codegen-platform-parity.cjs

/**
 * ============================================================================
 * MODULE: Platform Parity Table Generator
 * DESCRIPTION:
 * Writes docs/platform-parity-table.md, the one table of every user-facing
 * feature, bindable action, layer entry and interactive menu row with its
 * status, owner and reasons on Windows, macOS and Linux. `--check` fails when
 * the table is stale or when a parity rule of tools/lib/platform-parity.cjs is
 * broken; test-linux-feature-parity.cjs runs that check.
 * ============================================================================
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const toml = require('smol-toml');
const { loadFeatureModel } = require('../build/build-features-manifest.js');
const { withSectionReasons } = require('./codegen-feature-inventory.cjs');
const Parity = require('../lib/platform-parity.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const SHARED = 'static/ergopti_plus/_shared';
const OUT_MD = 'docs/platform-parity-table.md';
const PARITY_FILE = `${SHARED}/settings/data/features/platform_parity.toml`;
const LOCALES_DIR = `${SHARED}/core/i18n/data/locales`;
const OS_LABEL = { windows: 'Windows', macos: 'macOS', linux: 'Linux' };
const KIND_LABEL = {
	feature: 'Features and settings',
	action: 'Bindable actions',
	layer: 'Navigation layer entries',
	menu: 'Interactive menu rows'
};

/** @param {string} rel Repository path. @returns {string} File content. */
function readText(rel) {
	return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

/** @param {string} rel Repository path. @returns {string|null} Content, or null when absent. */
function readSource(rel) {
	const absolute = path.join(ROOT, rel);
	return fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : null;
}

/** @returns {Record<string, object>} The 21 locale dictionaries by language. */
function loadLocales() {
	const locales = {};
	for (const name of fs.readdirSync(path.join(ROOT, LOCALES_DIR)).sort())
		if (name.endsWith('.json'))
			locales[name.slice(0, -5)] = JSON.parse(readText(`${LOCALES_DIR}/${name}`));
	return locales;
}

/** @returns {object} Every catalogue the table projects. */
function loadCatalogues() {
	const model = loadFeatureModel();
	return {
		features: withSectionReasons(model.features, model.manifest.sections),
		actions: toml.parse(readText(`${SHARED}/shortcuts/data/actions/actions.toml`)),
		layers: toml.parse(readText(`${SHARED}/layouts/data/layer_actions.toml`)),
		menu: JSON.parse(readText(`${SHARED}/menu/data/menu_manifest.json`)),
		hiddenReasons: JSON.parse(readText(`${SHARED}/menu/data/hidden_row_reasons.json`))
	};
}

/** @param {string} text Cell text. @returns {string} Text safe inside a Markdown table. */
function cell(text) {
	return String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

/** @param {object} row Table row. @param {object} en English locale. @returns {string} Label. */
function label(row, en) {
	return (row.label_key && en[row.label_key]) || row.id;
}

/**
 * One table cell: the status and the owner file, or the reason key.
 * @param {object} state Cell of one OS.
 * @returns {string} Markdown.
 */
function stateCell(state) {
	if (state.status === 'unavailable') return `— \`${state.reason_key}\``;
	const mark = state.status === 'degraded' ? '◐' : '✓';
	if (!state.owner) return `${mark} **no owner**`;
	const file = state.owner.replace(/^static\/ergopti_plus\//, '');
	const more = state.owner_files > 1 ? ` +${state.owner_files - 1}` : '';
	const rule = state.owner_rule && state.owner_rule !== 'spelled' ? ' (declared)' : '';
	return `${mark} [${file}](../${state.owner})${more}${rule}`;
}

/**
 * Renders the Markdown table from a validated table.
 * @param {Array<object>} table Rows.
 * @param {object} context Parity declarations and locales.
 * @returns {string} Markdown.
 */
function render(table, { parity, locales }) {
	const en = locales.en;
	const counts = Parity.summarize(table);
	const lines = [
		'<!-- Generated by tools/codegen/codegen-platform-parity.cjs. Do not edit. -->',
		'',
		'# Platform parity table',
		'',
		'Every user-facing feature and setting (`manifest.toml`), bindable action (`actions.toml`), navigation layer entry (`layer_actions.toml`) and interactive menu row (`menu_manifest.json`), with its status on each OS. Regenerate with `node tools/codegen/codegen-platform-parity.cjs`; `tools/test/test-linux-feature-parity.cjs` fails when this file is stale or a rule below breaks.',
		'',
		'- ✓ **supported**: the catalogue declares it there, and the linked production file is its owner: the file of that driver whose code spells the entry the most often (`+n`: other files that spell it). « (declared) » marks an owner `platform_parity.toml` names because the entry is read generically (a section loop, a slot prefix, a data-driven layer). An owner is source evidence, not proof that the feature works on a real machine.',
		'- ◐ **degraded**: supported, but only on some sessions or hardware of that OS; the reason says which.',
		'- — **unavailable**: the catalogue leaves that OS out. The key is the reason the menu shows, present in all 21 locales; the technical reason and its class are in the reason list below.',
		'',
		'The gate checks that every non-supported cell has a reason key present in the 21 locales and a technical reason, that every supported or degraded cell has an owner on that OS (or a recorded PPT-nn finding), and that no menu row bound to a feature shows on an OS where the feature is unavailable.',
		'',
		'## Counts',
		'',
		'| OS | Supported | Degraded | Unavailable |',
		'| --- | ---: | ---: | ---: |'
	];
	for (const os of Object.keys(OS_LABEL))
		lines.push(
			`| ${OS_LABEL[os]} | ${counts[os].supported} | ${counts[os].degraded} | ${counts[os].unavailable} |`
		);
	lines.push('', '| Reason class | Unavailable or degraded cells |', '| --- | ---: |');
	const byKind = {};
	for (const row of table)
		for (const state of Object.values(row.cells))
			if (state.status !== 'supported') {
				const kind = parity.reasons[state.reason_key].kind;
				byKind[kind] = (byKind[kind] || 0) + 1;
			}
	for (const [kind, description] of Object.entries(Parity.REASON_KINDS))
		lines.push(`| \`${kind}\`: ${description} | ${byKind[kind] || 0} |`);
	const gaps = [];
	for (const row of table)
		for (const [os, state] of Object.entries(row.cells))
			if (state.status !== 'unavailable' && !state.owner)
				gaps.push(`- ${OS_LABEL[os]}: \`${row.path}\` (${parity.unowned[os][row.path].finding})`);
	lines.push(
		'',
		'## Declared but unowned',
		'',
		'Cells the catalogue declares supported where no production code of that driver reads the entry. Each is a finding of the [parity register](platform-parity-audit.md#platform-parity-table--november-19-2026).',
		'',
		...(gaps.length ? gaps : ['None.']),
		'',
		'## Reasons',
		'',
		'| Reason key | Class | Technical reason | Menu text (English) | Cells |',
		'| --- | --- | --- | --- | ---: |'
	);
	const used = {};
	for (const row of table)
		for (const state of Object.values(row.cells))
			if (state.reason_key && state.status !== 'supported')
				used[state.reason_key] = (used[state.reason_key] || 0) + 1;
	for (const key of Object.keys(parity.reasons).sort())
		lines.push(
			`| \`${key}\` | ${parity.reasons[key].kind} | ${cell(parity.reasons[key].technical)} | ${cell(en[key])} | ${used[key] || 0} |`
		);
	for (const kind of Object.keys(KIND_LABEL)) {
		const rows = table.filter((row) => row.kind === kind);
		lines.push(
			'',
			`## ${KIND_LABEL[kind]} (${rows.length})`,
			'',
			'| Entry | Label | Windows | macOS | Linux |',
			'| --- | --- | --- | --- | --- |'
		);
		for (const row of rows)
			lines.push(
				`| \`${row.path}\` | ${cell(label(row, en))} | ${Object.keys(OS_LABEL)
					.map((os) => cell(stateCell(row.cells[os])))
					.join(' | ')} |`
			);
	}
	return `${lines.join('\n')}\n`;
}

/** Formats the owned output with the repository's Prettier configuration. */
function format(source) {
	return execFileSync(
		process.execPath,
		[
			'--input-type=module',
			'-e',
			`import * as prettier from 'prettier';
process.stdin.setEncoding('utf8');
let source = '';
for await (const chunk of process.stdin) source += chunk;
const config = await prettier.resolveConfig(process.argv[1]);
process.stdout.write(await prettier.format(source, { ...config, filepath: process.argv[1] }));`,
			OUT_MD
		],
		{ cwd: ROOT, input: source, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
	);
}

/**
 * Builds and validates the table.
 * @returns {{table: Array<object>, errors: string[], parity: object, locales: object}} Result.
 */
function build() {
	const parity = toml.parse(readText(PARITY_FILE));
	const locales = loadLocales();
	const table = Parity.buildTable({
		catalogues: loadCatalogues(),
		sources: Parity.loadSourceIndex(),
		parity
	});
	const errors = Parity.validateTable(table, { parity, locales, readSource });
	return { table, errors, parity, locales };
}

/** Builds, validates and renders; throws on the first broken rule. */
function output() {
	const { table, errors, parity, locales } = build();
	if (errors.length) throw new Error(`Platform parity rules broken:\n  - ${errors.join('\n  - ')}`);
	return format(render(table, { parity, locales }));
}

/** Fails when the committed table differs from a fresh render. */
function check() {
	const expected = output();
	if (readSource(OUT_MD) !== expected)
		throw new Error(`${OUT_MD} is stale; run node tools/codegen/codegen-platform-parity.cjs`);
}

if (require.main === module) {
	if (process.argv.includes('--check')) check();
	else fs.writeFileSync(path.join(ROOT, OUT_MD), output());
}

module.exports = { build, check, format, output, render };
