local root='/workspace/ergopti/static/ergopti_plus/'
package.path=root..'macos/?.lua;'..root..'macos/?/init.lua;'..root..'_shared/lua/?.lua;'..root..'_shared/lua/?/init.lua;'..package.path
_G.hs=require('tests.stubs.hs')
local function harness(path,extra)
 local f=assert(io.open(root..'macos/'..path));local s=f:read('*a');f:close()
 local prefix=assert(s:match('^(.-)helpers%.describe%('))
 return assert(load(prefix..extra,'@'..root..'macos/'..path))()
end
local fresh=harness('tests/unit/modules/gestures/actions/test_karabiner_actions_reachable.lua','return fresh_registry')
local wheel=harness('tests/unit/modules/shortcuts/physical/test_layer_wheel.lua','return {make=make_ctx,sentinel=sentinel,event=scroll_event,drain=fire_post_callback_actions}')
local Actions,seen=fresh()
local ctx=wheel.make()
assert(Actions.execute_single('layer_on'))
assert(#seen.variables==1 and seen.variables[1].name=='layer_active' and seen.variables[1].value==1)
local consumed=ctx.scroll(wheel.event(1))
assert(consumed==false and #ctx.asked==0)
print('REPRO ON: registered layer_on writes layer_active=1, but bound wheel passes ordinary scroll (zero slot lookups)')
wheel.sentinel('F20_LAYER_NAV_ENTERED')
assert(ctx.scroll(wheel.event(1))==true)
wheel.drain(ctx)
assert(#ctx.posted==2)
assert(Actions.execute_single('layer_off'))
assert(#seen.variables==2 and seen.variables[2].name=='layer_active' and seen.variables[2].value==0)
assert(ctx.scroll(wheel.event(1))==true)
wheel.drain(ctx)
assert(#ctx.posted==4)
print('REPRO OFF: registered layer_off writes layer_active=0, but wheel still consumes scroll and posts SOUND_UP down/up')
wheel.sentinel('F19_LAYER_NAV_EXITED')
assert(ctx.scroll(wheel.event(1))==false)
assert(ctx.owner:delete()==true)
print('CONTROL: generated F20/F19 sentinels do synchronize wheel entry/exit; same wheel owner stays healthy')
