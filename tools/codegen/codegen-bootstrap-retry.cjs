// tools/codegen/codegen-bootstrap-retry.cjs

/** Project unchanged bootstrap budgets from their one shared data owner. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const SOURCE = 'static/ergopti_plus/_shared/modules/network/bootstrap_retry.json';
const SHELL = 'static/ergopti_plus/macos/modules/llm/network-retry.sh';
const LUA = 'static/ergopti_plus/macos/modules/llm/bootstrap_retry_generated.lua';

function validate(data) {
	const keys = ['schema_version', 'admission_seconds', 'idle_seconds', 'retirement_seconds'];
	if (
		!data ||
		typeof data !== 'object' ||
		Array.isArray(data) ||
		Object.keys(data).length !== keys.length ||
		keys.some((key) => !(key in data)) ||
		data.schema_version !== 1 ||
		keys.slice(1).some((key) => !Number.isSafeInteger(data[key]) || data[key] <= 0)
	)
		throw new TypeError('Bootstrap retry data refused.');
	return data;
}

function render(raw, shell) {
	const data = validate(JSON.parse(raw));
	if (JSON.stringify(data, null, '\t') + '\n' !== raw)
		throw new TypeError('Bootstrap retry canonical bytes refused.');
	for (const [key, name] of [
		['admission_seconds', 'CURL_CONNECT_TIMEOUT_SEC'],
		['idle_seconds', 'CURL_STALL_SEC'],
		['retirement_seconds', 'CURL_MAX_TIME_SEC']
	]) {
		const expression = new RegExp(`^${name}=[^\\n]*$`, 'gm');
		const matches = shell.match(expression);
		if (!matches || matches.length !== 1 || !new RegExp(`^${name}=[1-9][0-9]*$`).test(matches[0]))
			throw new TypeError('Bootstrap shell binding refused.');
		shell = shell.replace(expression, `${name}=${data[key]}`);
	}
	const digest = crypto.createHash('sha256').update(raw).digest('hex');
	return {
		[SHELL]: shell,
		[LUA]: `--- modules/llm/bootstrap_retry_generated.lua
--- Generated by tools/codegen/codegen-bootstrap-retry.cjs; do not edit.
--- Source: _shared/modules/network/bootstrap_retry.json.
return {
\tadmission_seconds = ${data.admission_seconds},
\tidle_seconds = ${data.idle_seconds},
\tretirement_seconds = ${data.retirement_seconds},
\tsource_sha256 = "${digest}",
}
`
	};
}

function generate(root = path.resolve(__dirname, '../..'), { check = false } = {}) {
	const outputs = render(
		fs.readFileSync(path.join(root, SOURCE), 'utf8'),
		fs.readFileSync(path.join(root, SHELL), 'utf8')
	);
	for (const [relative, bytes] of Object.entries(outputs)) {
		const output = path.join(root, relative);
		if (check) {
			if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== bytes)
				throw new Error('Bootstrap retry projection drifted.');
		} else {
			fs.mkdirSync(path.dirname(output), { recursive: true });
			fs.writeFileSync(output, bytes);
		}
	}
	return outputs;
}

module.exports = { validate, render, generate, SOURCE, SHELL, LUA };
if (require.main === module) generate(undefined, { check: process.argv.includes('--check') });
