--- tests/unit/modules/shortcuts/text_actions/fifo/test_copy_capture_handoff.lua
--- Actual copy capture waits for Quartz handoff and joins its cancelled transaction.
local helpers = require("tests.helpers")
local World = require("tests.support.modules.shortcuts.apps_fifo_capture_fixture")
helpers.describe("Apps copy capture native FIFO handoff", function()
	helpers.it("keeps the empty FIFO control healthy", function()
		World.with_world({}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(1)
			local copies, restores, urls = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,1); helpers.assert_eq(urls,1)
			helpers.assert_true(w.clipboard()==w.original)
			helpers.assert_eq(w.synthetic.stats().pending,0)
			helpers.assert_eq(w.synthetic.stats().active_transactions,0)
		end)
	end)
	helpers.it("starts the capture interval after a real paced FIFO predecessor", function()
		World.with_world({backlog=true}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(0.21)
			local copies, restores, urls, reads = w.counts()
			helpers.assert_eq(copies,0); helpers.assert_eq(restores,0); helpers.assert_eq(urls,0); helpers.assert_eq(reads,0)
			helpers.assert_true(w.apps.has_pending_apps_action())
			w.advance(1)
			copies, restores, urls = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,1); helpers.assert_eq(urls,1)
			helpers.assert_true(w.clipboard()==w.original)
			helpers.assert_true(w.events[#w.events].at >= w.events[1].at+0.2)
		end)
	end)
	helpers.it("pause cancels the queued copy without cancelling the FIFO sibling", function()
		World.with_world({backlog=true}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(0.1)
			helpers.assert_eq(w.apps.pause_apps_actions(), false)
			w.advance(1)
			helpers.assert_true(w.apps.pause_apps_actions())
			local copies, restores, urls = w.counts()
			helpers.assert_eq(copies,0); helpers.assert_eq(restores,1); helpers.assert_eq(urls,0)
			helpers.assert_true(w.clipboard()==w.original)
			helpers.assert_eq(w.synthetic.stats().pending,0)
			helpers.assert_eq(w.events[1].kind,'restore')
			helpers.assert_eq(w.events[#w.events].kind,'head_terminal')
			helpers.assert_eq(w.fixture.key_posts,42)
		end)
	end)
	helpers.it("retains the all-type snapshot when the native restore refuses", function()
		World.with_world({backlog=true,restore_refusals=1}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(0.65)
			local copies, restores, urls = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,1); helpers.assert_eq(urls,1)
			helpers.assert_true(w.apps.has_pending_apps_action())
			w.advance(1)
			copies, restores, urls = w.counts()
			helpers.assert_eq(restores,2)
			helpers.assert_true(w.clipboard()==w.original)
		end)
	end)
	helpers.it("Finder path capture also waits for handoff", function()
		World.with_world({backlog=true,finder=true}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(0.21)
			local copies, restores, urls, reads = w.counts()
			helpers.assert_eq(copies,0); helpers.assert_eq(restores,0); helpers.assert_eq(reads,0)
			w.advance(1)
			copies, restores, urls = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,0); helpers.assert_eq(urls,0)
			helpers.assert_eq(w.clipboard()['public.utf8-plain-text'],'/Users/user/Documents/report.txt')
		end)
	end)
	helpers.it("Finder fallback owns a second copy handoff", function()
		World.with_world({backlog=true,finder=true,no_finder_path=true}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(1)
			local copies, restores, urls = w.counts()
			helpers.assert_eq(copies,2); helpers.assert_eq(restores,1); helpers.assert_eq(urls,1)
			helpers.assert_true(w.clipboard()==w.original)
		end)
	end)
	helpers.it("a short FIFO wait still preserves the full post-handoff interval", function()
		World.with_world({backlog=true,pairs=1}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			w.advance(0.21)
			local copies, restores, urls, reads = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,0); helpers.assert_eq(urls,0); helpers.assert_eq(reads,0)
			w.advance(1)
			copies, restores, urls = w.counts()
			helpers.assert_eq(restores,1); helpers.assert_eq(urls,1)
			helpers.assert_true(w.clipboard()==w.original)
		end)
	end)
	helpers.it("pause after handoff fences a late capture and its successor", function()
		World.with_world({backlog=true,pairs=1}, function(w)
			assert(w.apps.copy_or_open_path()==true)
			local old
			for _,timer in ipairs(w.fixture.timers) do if timer.delay==0.2 then old=timer end end
			assert(old)
			w.advance(0.1)
			helpers.assert_true(w.apps.pause_apps_actions())
			w.advance(0.3)
			local copies, restores, urls, reads = w.counts()
			helpers.assert_eq(copies,1); helpers.assert_eq(restores,1); helpers.assert_eq(urls,0); helpers.assert_eq(reads,0)
			helpers.assert_true(w.apps.resume_apps_actions())
			assert(w.apps.copy_or_open_path()==true)
			old.callback()
			w.advance(1)
			copies, restores, urls, reads = w.counts()
			helpers.assert_eq(copies,2); helpers.assert_eq(restores,2); helpers.assert_eq(urls,1); helpers.assert_eq(reads,1)
			helpers.assert_true(w.clipboard()==w.original)
		end)
	end)
end)
