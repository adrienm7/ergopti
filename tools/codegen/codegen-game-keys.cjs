// tools/codegen/codegen-game-keys.cjs

/**
 * ==============================================================================
 * MODULE: Game Keys Names Generator
 * DESCRIPTION:
 * Projects the names of « Touches de jeu » (layout.game_keys) to the three
 * drivers: the choices (the enum of layout.game_keys in config.schema.json),
 * and the modes, strategies and reason keys of
 * `_shared/layouts/data/game_keys.json`. The macOS and Linux drivers read
 * `_shared/layouts/engine/emulation/game_keys_data.lua` through game_keys.lua;
 * Windows reads `windows/_generated/game_keys_names.ahk`, a class whose
 * unknown member fails at the first access.
 *
 * FEATURES & RATIONALE:
 * 1. One source (Rule A, docs/design/structure-plan.md): the Windows twin
 *    used to type every name the Lua module typed.
 * 2. Fails on a malformed source: an empty or repeated list, a name that is
 *    not a lower-case identifier, an application enum that differs from the
 *    choice enum.
 * 3. Output is deterministic and carries no timestamp, so the drift gate holds.
 * ==============================================================================
 */

'use strict';

const fs = require('fs');
const { shared } = require('../lib/paths.cjs');

const NAME = /^[a-z][a-z0-9_]*$/;

/**
 * @param {string} label What the list is, for the error.
 * @param {unknown} list The names.
 * @returns {string[]} The names, checked.
 */
function names(label, list) {
	if (!Array.isArray(list) || list.length === 0) throw new Error(`${label} is not a list of names`);
	if (new Set(list).size !== list.length) throw new Error(`${label} repeats a name`);
	for (const name of list)
		if (typeof name !== 'string' || !NAME.test(name))
			throw new Error(`${label} holds a name that is not an identifier: ${name}`);
	return list;
}

const data = JSON.parse(fs.readFileSync(shared('layouts', 'data', 'game_keys.json'), 'utf8'));
const schema = JSON.parse(
	fs.readFileSync(shared('settings', 'data', 'config_schema', 'config.schema.json'), 'utf8')
);
const layout = schema.$defs?.layout?.properties;
if (!layout?.game_keys || !layout?.game_keys_apps)
	throw new Error('config.schema.json declares no layout.game_keys or layout.game_keys_apps');
const choices = names('layout.game_keys enum', layout.game_keys.enum);
const appChoices = layout.game_keys_apps.additionalProperties?.enum;
if (JSON.stringify(appChoices) !== JSON.stringify(choices))
	throw new Error('layout.game_keys_apps does not allow exactly the layout.game_keys choices');

const modes = names('modes', data.modes);
const strategies = names('strategies', data.strategies);
if (!data.reasons || typeof data.reasons !== 'object')
	throw new Error('reasons is not a map of names to locale keys');
const reasons = names('reasons', Object.keys(data.reasons)).map((name) => {
	const key = data.reasons[name];
	if (typeof key !== 'string' || !/^platform_reason\.[a-z0-9_]+$/.test(key))
		throw new Error(`reason ${name} is not a platform_reason.* locale key`);
	return [name, key];
});

const upper = (name) => name.toUpperCase();
const quote = (value) => JSON.stringify(value);

// ──────────────────────────────────────────────────────────────────────────────
// Lua
// ──────────────────────────────────────────────────────────────────────────────

const luaMap = (list) => list.map((n) => `\t\t${upper(n)} = ${quote(n)},`);
const lua = [
	'--- _shared/layouts/engine/emulation/game_keys_data.lua',
	'',
	'--- Generated by tools/codegen/codegen-game-keys.cjs; do not edit.',
	'--- Source: _shared/layouts/data/game_keys.json and the layout.game_keys enum.',
	'return {',
	'\tchoices = {',
	...luaMap(choices),
	'\t},',
	'\tmodes = {',
	...luaMap(modes),
	'\t},',
	'\tstrategies = {',
	...luaMap(strategies),
	'\t},',
	'\treasons = {',
	...reasons.map(([name, key]) => `\t\t${name} = ${quote(key)},`),
	'\t},',
	'}',
	''
].join('\n');

// ──────────────────────────────────────────────────────────────────────────────
// AutoHotkey
// ──────────────────────────────────────────────────────────────────────────────

const ahkClass = (label, pairs) => [
	`\tclass ${label} {`,
	...pairs.map(([name, value]) => `\t\tstatic ${upper(name)} := ${quote(value)}`),
	'\t}'
];
const same = (list) => list.map((n) => [n, n]);
const ahk = [
	'﻿; _generated/game_keys_names.ahk',
	'; AUTO-GENERATED from _shared/layouts/data/game_keys.json and the',
	'; layout.game_keys enum of _shared/settings/data/config_schema/config.schema.json.',
	'; DO NOT EDIT BY HAND — run `npm run codegen:game-keys` to refresh.',
	'#Requires AutoHotkey v2.0',
	'',
	'; ==============================================================================',
	'; MODULE: Game Keys Names',
	'; DESCRIPTION:',
	'; The choices, Ergopti modes, strategies and reason keys of the game keys',
	'; (modules/keymap/keylayout/game_keys.ahk), the names game_keys.lua reads on',
	'; macOS and Linux. A misspelt name fails at the first access.',
	'; ==============================================================================',
	'',
	'class GameKeysName {',
	...ahkClass('Choice', same(choices)),
	...ahkClass('Mode', same(modes)),
	...ahkClass('Strategy', same(strategies)),
	...ahkClass('Reason', reasons),
	'}',
	''
].join('\n');

fs.writeFileSync(shared('layouts', 'engine', 'emulation', 'game_keys_data.lua'), lua, 'utf8');
fs.writeFileSync(shared('..', 'windows', '_generated', 'game_keys_names.ahk'), ahk, 'utf8');
console.log('[OK] Generated the game keys names.');
